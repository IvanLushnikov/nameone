/**
 * Интерактив в конструкторе учителя (лист 4.1.1).
 *
 * Движок давно готов: шесть форматов в реестре, ранклер на бэке, плееры и
 * страница прохождения `/play/?t=…`. Не хватало только входа из конструктора —
 * тип стоял в `NOT_YET_IMPLEMENTED_TYPES`, и учитель вместо игры получал
 * «этот формат ещё в работе».
 *
 * Здесь лежат ПРАВИЛА этого входа, а не вёрстка:
 *
 *   1. Список форматов берётся из реестра движка (`INTERACTIVE_FORMATS`), а не
 *      из ручного перечисления здесь. Спрятать формат нельзя: учитель видит
 *      ровно то, что сервер умеет собирать, и не больше. Если движок умеет
 *      семь форматов — учитель увидит семь.
 *   2. Деньги и лимиты — словами ДО кнопки. Интерактив это отдельный вызов
 *      модели (на сервере 20 сборок в час на учителя), а если листа ещё нет —
 *      то сначала лист, потом игра, то есть два вызова.
 *   3. Блокировки — словами же. Когда не хватает входа или листа, кнопки
 *      «собрать игру» на экране НЕТ: есть причина и ровно одно действие,
 *      которое приводит к результату. Кнопка, которая обещает игру и молчит,
 *      хуже честного «сначала войдите».
 */

import {
  DEFAULT_OPTIONS,
  FORMAT_META,
  type FormatMeta,
} from "@/lib/interactives/formats";
import {
  INTERACTIVE_ERROR_MESSAGE,
  INTERACTIVE_FORMATS,
  type InteractiveApiError,
  type InteractiveFormat,
  type InteractiveOptions,
} from "@/lib/interactives/types";

/**
 * Форматы, которые учитель может выбрать.
 *
 * Порядок и состав — из реестра движка. Ничего не отфильтровываем: если
 * формат есть в движке, он есть в списке, иначе получилось бы ровно то, ради
 * чего писался этот файл — кнопка без результата.
 */
export const CONSTRUCTOR_INTERACTIVE_FORMATS: readonly InteractiveFormat[] = INTERACTIVE_FORMATS;

/** Формат по умолчанию — тот, который сервер рекомендует для первого показа. */
export const DEFAULT_CONSTRUCTOR_FORMAT: InteractiveFormat = INTERACTIVE_FORMATS[0];

/** Карточка формата для выбора: что делает ученик — одной строкой. */
export function constructorFormatCard(format: InteractiveFormat): FormatMeta {
  return FORMAT_META[format] ?? FORMAT_META[DEFAULT_CONSTRUCTOR_FORMAT];
}

/**
 * Настройки по умолчанию для формата — копия, а не сам объект реестра:
 * сервер получает options отдельным запросом, и общий объект трогать нельзя.
 */
export function constructorInteractiveOptions(format: InteractiveFormat): InteractiveOptions {
  return { ...(DEFAULT_OPTIONS[format] ?? DEFAULT_OPTIONS[DEFAULT_CONSTRUCTOR_FORMAT]) };
}

/**
 * Ссылка, которую открывает ученик.
 *
 * Путь собираем на клиенте: бэк про адрес фронта не знает, и пустой `url` в
 * ответе — не повод оставлять учителя без ссылки. Это ровно тот адрес, что
 * ждёт `src/app/play/page.tsx` (query-параметр `t`).
 */
export function interactivePlayPath(shareToken: string): string {
  return `/play/?t=${encodeURIComponent(shareToken)}`;
}

/** Что видит учитель, когда игра собрана: формат, из чего собрана и что дальше. */
export interface InteractiveCostNote {
  /** Короткие строки о стоимости — под кнопкой. */
  lines: readonly string[];
}

/**
 * Стоимость сборки — до кнопки, а не после.
 *
 * `hasWorksheet` меняет цифру: без листа это два вызова модели (сначала лист,
 * потом игра), с готовым листом — один. Оба числа названы прямо, потому что
 * «интерактив стоит отдельного вызова модели» должно быть видно ДО кнопки,
 * а не в счёте после неё.
 */
export function interactiveCostNote(hasWorksheet: boolean): InteractiveCostNote {
  const lines = hasWorksheet
    ? [
        "Игра — отдельный вызов модели: примерно 20–40 секунд.",
        "Лимит на сервере: 20 игр в час на учителя.",
        "Тот же лист и тот же формат второй раз модель не зовут — сервер отдаёт готовое.",
      ]
    : [
        "Листа ещё нет, поэтому это два вызова модели: сначала лист, потом игра — примерно минута.",
        "Лимит на сервере: 20 игр в час на учителя.",
        "Тот же лист и тот же формат второй раз модель не зовут — сервер отдаёт готовое.",
      ];
  return { lines };
}

export interface InteractiveBlockInput {
  /** Учитель вошёл в аккаунт: без него сервер не хранит игру и не даёт ссылку. */
  loggedIn: boolean;
  /** Лист есть на экране (может быть заготовкой демо-режима — это не блок). */
  hasWorksheet: boolean;
  /** Id листа В БАЗЕ: ранклер читает задания по нему, клиентского id не хватит. */
  serverWorksheetId: string | null;
  /**
   * Бесплатные генерации закончились (без учёта платных тарифов — их лимит
   * считает бэк).
   *
   * Учитывается ТОЛЬКО когда листа ещё нет: игра собирается из готового листа
   * и счётчик бесплатных генераций не трогает (у неё свой серверный лимит,
   * 20 в час). Иначе мы бы написали «нужна подписка» человеку, которому
   * подписка для игры не нужна.
   */
  outOfQuota: boolean;
}

export type InteractiveBlock =
  | { kind: "ready"; cta: string }
  | { kind: "need-login"; title: string; text: string }
  | { kind: "need-quota"; title: string; text: string; cta: string }
  | { kind: "need-worksheet"; title: string; text: string; cta: string }
  | { kind: "no-server-sheet"; title: string; text: string; cta: string };

/**
 * Что мешает собрать игру прямо сейчас — словами учителю.
 *
 * Порядок проверок = порядок вопросов к учителю: сначала вход (без него не
 * существует ссылки), потом лимит (нет листа — нужна генерация, а она платная),
 * потом лист (игра собирается из его заданий), потом сохранение листа на
 * сервере (ранклер читает базу, а не экран).
 *
 * Отдельного состояния «лист сохраняется» здесь нет намеренно: сохранение
 * идёт секунду-две, и блокировка на это время оставила бы учителя с экраном,
 * где ничего нажать нельзя. Вместо блокировки — подсказка в панели, а кнопка
 * при этом рабочая: повторное нажатие не плодит дубликаты, сборщик дожидается
 * уже идущего сохранения и берёт его id.
 */
export function interactiveBlock(input: InteractiveBlockInput): InteractiveBlock {
  if (!input.loggedIn) {
    return {
      kind: "need-login",
      title: "Войдите, чтобы выдать игру классу",
      text: "Ссылка, QR-код и результаты учеников хранятся на сервере под вашим аккаунтом. Без входа собрать игру нельзя — и врать, что получилось, мы не будем.",
    };
  }
  if (!input.hasWorksheet && input.outOfQuota) {
    return {
      kind: "need-quota",
      title: "Бесплатные генерации закончились",
      text: "Лист для игры ещё не сделан, а сделать его без подписки уже нельзя. Сама игра лимит не расходует — она собирается из готового листа.",
      cta: "Оформить подписку",
    };
  }
  if (!input.hasWorksheet) {
    return {
      kind: "need-worksheet",
      title: "Игра собирается из заданий листа",
      text: "Заданий пока нет. Соберём лист по этой теме — и сразу из него игру.",
      cta: "Сделать лист и собрать игру",
    };
  }
  if (!input.serverWorksheetId) {
    return {
      kind: "no-server-sheet",
      title: "Лист есть на экране, но не на сервере",
      text: "Ранклер берёт задания из базы, а не с экрана. Попробуйте сохранить лист ещё раз — если сервер недоступен, игра соберётся позже.",
      cta: "Сохранить лист и собрать игру",
    };
  }
  return { kind: "ready", cta: "Собрать игру и получить QR" };
}

/**
 * Тексты ошибок сборки — в контексте «создаём», а не «смотрим список».
 *
 * Общие формулировки `INTERACTIVE_ERROR_MESSAGE` написаны для кабинета («войдите,
 * чтобы увидеть интерактивы»). Здесь учитель создаёт игру, поэтому 401 — это
 * «войдите, чтобы выдать игру классу», а 404 — «сервер не нашёл лист, из
 * которого собираем».
 */
export function interactiveCreateErrorMessage(error: InteractiveApiError["error"]): string {
  switch (error) {
    case "unauthorized":
      return "Войдите, чтобы выдать игру классу: ссылка и результаты хранятся на сервере под вашим аккаунтом";
    case "not_found":
      return "Сервер не нашёл лист, из которого собирается игра. Сохраните лист заново и попробуйте ещё раз";
    case "rate_limited":
      return "Лимит: 20 игр в час. Подождите немного и попробуйте ещё раз";
    default:
      return INTERACTIVE_ERROR_MESSAGE[error];
  }
}

