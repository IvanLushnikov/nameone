/** Базовый URL сайта.
 *
 *  Домен — `uchlist.ru` (решение владельца 2026-10-03, см. docs/tz/18-money-and-trust.md §7).
 *  ⚠️ Домен ещё не куплен и не резолвится. До его делегирования в сборке обязательно
 *  должен быть задан `NEXT_PUBLIC_SITE_URL` (например на pages.dev), иначе
 *  sitemap, robots, canonical и JSON-LD укажут на нерезолвящийся хост —
 *  это уже случалось с предыдущим доменом. */
export const SITE_URL = (process.env.NEXT_PUBLIC_SITE_URL ?? "https://listai-prototype.pages.dev").replace(/\/+$/, "");

/** SITE_URL без схемы — для мест, где нужен голый домен (подписи в печатных листах). */
export const SITE_HOST = SITE_URL.replace(/^https?:\/\//, "");

/**
 * Почта поддержки.
 *
 * Раньше адрес был зашит строкой в трёх местах (главная в JSON-LD, футер,
 * политика). Пока домен не делегирован, письмо на него не дойдёт — учитель
 * пишет «в поддержку», ответа нет. Задай рабочий адрес в
 * `NEXT_PUBLIC_SUPPORT_EMAIL`. На новом домене — `hello@uchlist.ru`.
 */
export const SUPPORT_EMAIL = process.env.NEXT_PUBLIC_SUPPORT_EMAIL ?? "hello@uchlist.ru";

/**
 * Реквизиты оператора персональных данных.
 *
 * Ч. 4 ст. 9 152-ФЗ: согласие на обработку ПДн обязано содержать наименование
 * (ФИО) и адрес оператора. Без них текст согласия недействителен, а форма
 * сбора согласия — нарушение (штраф по ч. 2 ст. 13.11 КоАП, 300–700 тыс. ₽).
 *
 * ⚠️ ДЕФОЛТЫ — ПЛЕЙСХОЛДЕРЫ. Перед продом проставь реальные значения через
 * NEXT_PUBLIC_OPERATOR_NAME / NEXT_PUBLIC_OPERATOR_ADDRESS. Оператором
 * считается тот, кто определяет цели и средства обработки: при самозанятости
 * это ФИО самозанятого, при ИП — наименование и адрес ИП.
 */
export const OPERATOR_NAME = process.env.NEXT_PUBLIC_OPERATOR_NAME ?? "ИП Лушников Иван";

/**
 * Адрес оператора. Раньше здесь стояла подставная строка
 * «(уточняется)», и она попадала в текст согласия на обработку ПДн —
 * то есть прямо в юридический документ. Плейсхолдер в таком документе
 * делает согласие неполным, поэтому его убрали: при незаданной переменной
 * показываем нейтральную формулировку и отсылку к письму, а не слово
 * «уточняется». Полные реквизиты (ИНН, ОГРНИП, адрес) проставляются через
 * NEXT_PUBLIC_OPERATOR_* перед запуском.
 */
export const OPERATOR_ADDRESS = process.env.NEXT_PUBLIC_OPERATOR_ADDRESS ?? "";

/** Домен оператора — для блока «кто обрабатывает данные» в согласии. */
export const OPERATOR_SITE = SITE_HOST;

