/**
 * Проверка ответов листа по нажатию кнопки (F-05, решение владельца 06.10.2026).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ИМЕННО ТАК
 * ─────────────────────────────────────────────────────────────────────────────
 * Проверка одного задания занимает 5–20 секунд (замерено на проде 06.10.2026:
 * медиана 9 с). В листе 10–20 заданий, то есть весь прогон — 1–3 минуты.
 *
 * Из-за этого синхронно (в момент генерации) проверку поставить НЕЛЬЗЯ:
 * генерация отдаётся за 10–20 секунд, и добавление 1–3 минут уронило бы
 * и сценарий, и таймаут фронта (90 с). Фоновая очередь — это переделка
 * архитектуры, которая тянет за собой статус проверки в модели данных,
 * опрос с фронта и перенос учёта расхода.
 *
 * Выбранный вариант: учитель сам жмёт «Проверить ответы» и видит прогресс.
 * Честно, предсказуемо и не требует новой инфраструктуры — ручка
 * `POST /api/llm/verify` уже работает и проверена (19 запросов из 19 успешны).
 * Цена вопроса: проверка идёт по одному заданию за раз, поэтому по листу
 * будет 10–20 платных вызовов — это осознанный выбор учителя, а не молчаливая
 * трата на каждой генерации.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ГЛАВНОЕ ПРАВИЛО: ЗАГОТОВКА НЕ ПРОВЕРЯЕТСЯ
 * ─────────────────────────────────────────────────────────────────────────────
 * Раньше проверку звал генератор-заглушка (`src/lib/mock/generator.ts`), то
 * есть бейдж «проверено» получали ЗАГОТОВОЧНЫЕ задания, а настоящие листы,
 * пришедшие с сервера, не проверялись вообще никогда. Проверять типовой шаблон
 * бессмысленно — там заведомо верные ответы, — поэтому функция ниже отказывает
 * заранее, если результат демонстрационный.
 */

import { selfVerifyTask, type SelfVerifyResult } from "./self-verify";
import type { Worksheet, WorksheetTask } from "@/lib/types";

export interface VerifyProgress {
  /** Сколько заданий уже проверено. */
  done: number;
  /** Сколько всего заданий в листе. */
  total: number;
  /** Проверяется ли прямо сейчас (идёт запрос). */
  running: boolean;
  /** Итог последнего завершённого прогона: сколько сошлось. */
  matched: number | null;
  /** Завершён ли прогон целиком. */
  finished: boolean;
}

/**
 * Проверить все задания листа по одному, отдавая прогресс.
 *
 * Порядок — строго последовательный, а не параллельный:
 *   · 10–20 одновременных запросов означали бы 10–20 платных вызовов в секунду
 *     с одного браузера — и гарантированный 429 по лимиту в 200/час на IP;
 *   · провайдер так не любит, и лимит на ручку один на адрес, а не на вкладку.
 *
 * Поэтому проверка идёт как очередь: одно задание → пауза → следующее.
 * Кнопка при этом не «висит» — прогресс виден, а прерывание безопасно:
 * уже проверенные задания сохраняют свой бейдж.
 */
export async function verifyWorksheetTasks(
  worksheet: Worksheet,
  onProgress: (p: VerifyProgress) => void,
  options: { signal?: AbortSignal } = {},
): Promise<WorksheetTask[]> {
  const tasks = worksheet.tasks;
  const total = tasks.length;
  const next: WorksheetTask[] = [];
  let matched = 0;

  for (let i = 0; i < total; i++) {
    if (options.signal?.aborted) {
      // Прервали посреди прогона: отдаём то, что успели проверить, и не
      // выдаём это за «проверено всё» — учитель увидит счётчик «3 из 12».
      onProgress({ done: i, total, running: false, matched, finished: false });
      return next;
    }

    const task = tasks[i]!;
    onProgress({ done: i, total, running: true, matched, finished: false });

    const result: SelfVerifyResult = await selfVerifyTask({
      subject: worksheet.subject,
      grade: worksheet.grade,
      topic: worksheet.topic,
      text: task.text,
      expectedAnswer: task.answer,
    });

    const verifiedTask: WorksheetTask = {
      ...task,
      // null = «проверить не удалось», и это НЕ то же самое, что «неверно».
      // Бейдж по null показывает «— не проверено», и это правда.
      verified: result.verified,
      verifiedExplanation: result.explanation,
    };
    next.push(verifiedTask);
    if (result.verified === true) matched++;

    onProgress({ done: i + 1, total, running: i + 1 < total, matched, finished: i + 1 === total });
  }

  return next;
}
