/**
 * Отзывы клиентов. ИСТОЧНИК ПУСТ.
 *
 * ## Почему источник, а не текст на странице
 *
 * Отзывы нельзя хранить разметкой в `page.tsx`: их приходится добавлять и
 * удалять, а правило проекта одно — на сайте нет ни одного выдуманного
 * отзыва. Пустой массив здесь означает, что блока на `/about/` просто нет.
 * Никакой заглушки «пока нет отзывов, но скоро»: такая фраза обещает
 * отзывы, которых нет, и выглядит как вставка рекламного отдела.
 *
 * ## Что происходит, когда владелец добавит запись
 *
 * 1. добавить объект в `REVIEWS` ниже;
 * 2. пересобрать сайт — блок появится на `/about/` сам, разметка страницы
 *    не меняется.
 *
 * ## Правила заполнения
 *
 * - `author` — имя, которым человек сам согласен называться. Не «Иван И. из
 *   Москвы», если человек не давал на это согласия: текст отзыва с именем и
 *   городом — это персональные данные (152-ФЗ), согласие на них берётся
 *   отдельно, ч. 4 ст. 9.
 * - `date` — ISO-дата, когда человек дал согласие на публикацию.
 * - `rating` — необязательное поле. Оценка без реальных отзывов придумывается
 *   вместе с ними, поэтому по умолчанию её нет.
 */

export interface Review {
  /** Уникальный ключ записи. Обязателен — по нему React переупорядочивает список. */
  id: string;
  /** Имя, опубликованное с согласия автора отзыва. */
  author: string;
  /** Роль, если человек её назвал: «учитель математики, 6 класс». */
  role?: string;
  /** Дата согласия на публикацию, ISO: `2026-10-11`. */
  date: string;
  /** Оценка от 1 до 5. Не заполняйте, если реальной оценки никто не ставил. */
  rating?: number;
  /** Сам отзыв. Одна-две фразы, без рекламных восклицаний. */
  text: string;
}

/**
 * Отзывы. Пусто — значит блок не рисует НИЧЕГО: ни заголовка, ни пустого
 * списка, ни приглашения оставить отзыв.
 *
 * @example
 * REVIEWS.push({
 *   id: "2026-10-11-ivanova",
 *   author: "И. И.",
 *   role: "учитель математики, 6 класс",
 *   date: "2026-10-11",
 *   text: "Лист на дроби выходит ровно под урок. Правлю формулировки и печатаю.",
 * });
 */
export const REVIEWS: Review[] = [];