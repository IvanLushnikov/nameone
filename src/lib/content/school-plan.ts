import { PLANS } from "./plans";

/**
 * Пункты тарифа «Школа», которых в продукте ещё нет.
 *
 * Текст пункта пишется здесь ровно так же, как он записан в `plans.ts`:
 * список намеренно ссылается на формулировки плана, а не заводит свои
 * копии. Расхождение ловит тест.
 */
export const SCHOOL_PLAN_PLANNED_FEATURES: readonly string[] = [
  "Шаблоны для контрольных",
  "Интеграция со Сферум / Moodle",
  "Готовые КТП для администрации",
  "Без ограничения по числу учеников в классе",
];

/**
 * Разделяет пункты тарифа «Школа» на «уже работает» и «в планах».
 *
 * Порядок пунктов сохраняется: `features` — это порядок, задуманный
 * владельцем, и переставлять его здесь нельзя.
 */
export function splitSchoolPlanFeatures(
  features: readonly string[] = PLANS.school.features,
): { available: string[]; planned: string[] } {
  const planned = new Set(SCHOOL_PLAN_PLANNED_FEATURES);
  return {
    available: features.filter((f) => !planned.has(f)),
    planned: features.filter((f) => planned.has(f)),
  };
}
