/**
 * Чистый текст без markdown для JSON-LD.
 *
 * Google показывает `mainEntity.question.name` как есть: если там остались
 * `**жирный**` или `` `код` ``, учитель в выдаче увидит звёздочки. Режем
 * маркеры, сносим переносы строк и схлопываем пробелы.
 */
export function stripMarkdown(input: string): string {
  return input
    .replace(/`([^`]*)`/g, "$1")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/__([^_]+)__/g, "$1")
    .replace(/\*([^*]+)\*/g, "$1")
    .replace(/\[([^\]]+)\]\([^)]*\)/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

/** «1–4 класс», «5–6 класс», «7–9 класс», «10–11 класс». */
function gradeRanges(grades: number[]): string[] {
  const sorted = [...new Set(grades)].sort((a, b) => a - b);
  const runs: number[][] = [];
  for (const num of sorted) {
    const last = runs[runs.length - 1];
    if (last && num === last[last.length - 1] + 1) last.push(num);
    else runs.push([num]);
  }
  return runs.map((run) =>
    run.length === 1 ? `${run[0]} класс` : `${run[0]}–${run[run.length - 1]} класс`
  );
}

/** Классы УМК одной строкой: «5–6 класс». Пусто, если классы не заданы. */
export function umkGradesLabel(grades?: number[]): string {
  if (!grades || grades.length === 0) return "";
  return gradeRanges(grades).join(", ");
}

/**
 * Подпись УМК так, как его называют в школе и как его ищут в Google:
 * «Математика. 5–6 класс. Виленкин Н.Я.».
 *
 * Название предмета необязательно — на /subject/<slug>/ оно уже есть в H1,
 * и там подпись остаётся короче: «5–6 класс. Виленкин Н.Я.».
 * Классы берём из `UMKEntry.grades`, а не из диапазона предмета: учебник
 * Виленкина — это 5–6 класс, хотя сама математика в проекте 1–11.
 */
export function umkEntryLabel(entry: UMKEntry, subjectTitle?: string): string {
  const grades = umkGradesLabel(entry.grades);
  const parts = [subjectTitle, grades, entry.name].filter(Boolean);
  return parts.join(". ");
}
