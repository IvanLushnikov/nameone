/**
 * Метрики лендинга — считаются на СЕРВЕРЕ, клиенту уходят только числа.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ФАЙЛ
 * ─────────────────────────────────────────────────────────────────────────────
 * Блок «Что внутри» на главной показывает реальные числа: сколько предметов,
 * сколько пар (предмет, класс), сколько тем. Раньше эти числа считались прямо
 * в клиентском компоненте `landing/Stats.tsx`, и тот импортировал ради одного
 * счётчика `MATERIALS_CATALOG` — а каталог материалов собирается из полной
 * таксономии (`subjects.ts`, 3.8 МБ с текстами заданий).
 *
 * В итоге webpack запекал таксономию в общий клиентский чанк на 4.2 МБ, и он
 * грузился на главной — самой посещаемой странице сайта. Ради трёх чисел.
 *
 * Теперь числа считаются здесь, на сервере, а в клиент уходят только
 * значения. Каталог и таксономия в браузер не попадают.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧЕСТНОСТЬ ЦИФР
 * ─────────────────────────────────────────────────────────────────────────────
 * Числа не вписаны в разметку — они считаются из тех же источников, из которых
 * рисуются страницы: сводки таксономии (`subject-index.json`, генерируется из
 * `subjects.ts`) и каталога материалов. Расхождение сводки с таксономией
 * ловит тест `tests/subject-index.test.ts`.
 *
 * Тут нет и не должно быть «среднего времени генерации» и прочих метрик,
 * которых в коде нет: придуманное число на витрине учитель видит сразу.
 */

import { subjectIndex, totalGradePairsCount, totalTopicsCount } from "./subject-index";
import { MATERIALS_CATALOG } from "./materials-catalog";

export interface LandingMetrics {
  /** Сколько предметов в каталоге. */
  subjects: number;
  /** Сколько пар (предмет, класс). */
  subjectGradePairs: number;
  /** Сколько тем в каталоге. */
  topics: number;
  /** Сколько записей в банке материалов. */
  materials: number;
}

/**
 * Реальные метрики продукта (не выдуманные цифры активности).
 *
 * Экспортируется наружу, потому что число тем показывают ДВА блока лендинга —
 * эта секция и «Тем в каталоге» в Hero. Раньше Hero держал свою цифру
 * в строке, а здесь считалось настоящее: каталог и Hero показывали разные
 * числа. Теперь оба берут значение отсюда.
 */
export function getLandingMetrics(): LandingMetrics {
  return {
    subjects: subjectIndex.length,
    subjectGradePairs: totalGradePairsCount(),
    topics: totalTopicsCount(),
    // ТЗ-21 п.9: витринных чисел на сайте не было вообще — у конкурентов
    // «110 000 учителей», у нас молчание выглядело как пустой продукт. Показываем
    // то, что можно посчитать в коде, а не выдуманную активность.
    //
    // ЧЕГО ТУТ НЕТ И ПОЧЕМУ. Счётчика «сколько листов сделали» в коде нет:
    // worksheets считаются в БД (backend/src/db/schema.sql), на главной он был
    // бы нулём у каждого нового посетителя. Выдумывать «10 000 листов»
    // нельзя — это ровно тот приём, из-за которого конкуренты и не верят.
    materials: MATERIALS_CATALOG.length,
    // Здесь раньше стоял `avgTimeSec: 30` — в блоке «Что внутри» он выводился
    // рядом с настоящими числами и подписью «генерация листа · оценка».
    // Замера длительности генерации в коде нет, поэтому в ряду метрик это
    // было единственное придуманное число. Плашка убрана: «за 30 секунд»
    // осталось обещанием в заголовке и кнопках, но не фактом в статистике.
    // Если появится реальный замер (например, median по llm_logs), вернуть
    // можно будет вместе с данными.
  };
}
