/**
 * Какого ответа ждёт задание этого типа.
 *
 * · `exact`   — один точный ответ («12», «3/4», «2/3»).
 * · `choice`  — выбор из вариантов; в `options` лежат варианты.
 * · `text`    — свободный текст, сверяется по критериям или вручную.
 * · `criteria`— развёрнутый ответ с критериями приёмки (`criteria`).
 * · `order`   — порядок или соответствие: ответ задаёт перестановку/пары.
 */
export type TaskAnswerKind = "exact" | "choice" | "text" | "criteria" | "order";

export interface TaskTypeSpec {
  /** Идентификатор типа. Это значение попадает в `WorksheetTask.type` и в JSON модели. */
  id: string;
  /** Название для учителя. «По образцу», «Установите соответствие». */
  name: string;
  /**
   * Как это звучит в учительской формулировке — одной строкой, от лица
   * учителя. Это то, что попадает в промпт: модель читает не идентификатор,
   * а живую формулировку, и отвечает соответствующе.
   */
  whatTeacherAsks: string;
  /** Какого ответа ждёт задание. Определяет проверку и печать ответа. */
  answerKind: TaskAnswerKind;
  /**
   * Максимальный балл за задание этого типа (ТЗ-34, AD-3).
   *
   * Вес — свойство ФОРМЫ задания, а не конкретного задания: расчёт весит
   * столько же, сколько краткий ответ, а развёрнутый — втрое больше. Отсюда
   * два следствия, и оба важные:
   *
   *   · НОВЫЙ ТИП ЗАДАНИЯ ПОЛУЧАЕТ ВЕС АВТОМАТИЧЕСКИ, а не через «ещё одно
   *     жёсткое правило» в валидаторе;
   *   · МОДЕЛЬНОЕ ПОЛЕ `points` ПЕРЕСТАЁТ БЫТЬ ИСТОЧНИКОМ ПРАВДЫ. Раньше в
   *     одном файле жили два разных числа о балле задания — и учитель, и
   *     проверяющий видели разные баллы.
   *
   * Основание — трудоёмкость ответа учителя, а не «сколько баллов в школьной
   * системе»: за один и тот же объём работы в разных школах ставят по-разному.
   */
  weight: number;
  /**
   * Требуется образец В ТЕКСТЕ задания. У типа `pattern` образец обязателен:
   * задание «выполните по образцу» без образца в листе — это дефект, который
   * учитель уносит в класс (жалоба №5, docs/30-feedback-cases-2026-10-08.md).
   */
  needsSample?: boolean;
  /** Нужны варианты ответа (`options`). */
  needsOptions?: boolean;
  /** Нужна таблица или рисунок в задании (`table`). */
  needsTable?: boolean;
  /** Нужна картинка (`image`). */
  needsImage?: boolean;
  /**
   * Где форма применима. Пусто — применима везде. Значения — слаги предметов
   * из `src/lib/types.ts` (math, russian, english, …).
   */
  subjects?: string[];
  /** Где форма применима по классу. Пусто — все классы. */
  grades?: [number, number];
  /**
   * Подсказки для вёрстки: что и как печатать (колонки, рамка, чек-лист).
   * Читаются человеком при правке печати — машиной не парсятся.
   */
  printHints: string[];
  /**
   * Как проверить, что задание «сделано правильно». Формулировка проверяющего,
   * а не машинально проверяемое условие.
   */
  checkHint: string;
}

