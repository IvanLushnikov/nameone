/**
 * Полный реестр: сначала пять привычных, потом двенадцать новых.
 *
 * Порядок значим для промпта: модель читает список сверху вниз и при
 * равных условиях выбирает первое. Поэтому пять старых — впереди: частая
 * смена формы в листе ломает привычку учителя, а редкие формы нужны там,
 * где старые не работают.
 */
export const TASK_TYPE_REGISTRY: readonly TaskTypeSpec[] = [
  ...LEGACY_TASK_TYPES,
  ...NEW_TASK_TYPES,
];

/**
 * Идентификаторы всех типов — массивом, без readonly-типа: он нужен как
 * `z.enum(...)`, а zod принимает и readonly-массив, и обычный.
 */
export const TASK_TYPE_IDS: string[] = TASK_TYPE_REGISTRY.map((t) => t.id);

/** Все идентификаторы — литеральным union, для типов. */
export type TaskTypeId = (typeof TASK_TYPE_REGISTRY)[number]["id"];

/** Реестр по идентификатору. `undefined` — типа в реестре нет. */
const BY_ID = new Map<string, TaskTypeSpec>(TASK_TYPE_REGISTRY.map((t) => [t.id, t]));

/** Спецификация типа по его `id`. */
export function getTaskTypeSpec(id: string): TaskTypeSpec | undefined {
  return BY_ID.get(id);
}

/** Есть ли такой тип в реестре. */
export function isKnownTaskType(id: string): boolean {
  return BY_ID.has(id);
}

/**
 * Типы, применимые к предмету и классу.
 *
 * Правило владельца (ТЗ-33, AD-6): тип, который предмету не подходит,
 * НЕЛЬЗЯ просить у модели — «не просить, а потом отфильтруем». Значит
 * отсечение происходит ДО сборки промпта, и модель физически не получает
 * задание, которое ей нельзя делать.
 *
 * Типы без `subjects` и без `grades` применимы везде — так объявлены пять
 * привычных, и обратная совместимость не ломается.
 */
export function typesForSubject(subject: string, grade: number): TaskTypeSpec[] {
  return TASK_TYPE_REGISTRY.filter((spec) => {
    if (spec.subjects && spec.subjects.length > 0 && !spec.subjects.includes(subject)) {
      return false;
    }
    if (spec.grades) {
      const [min, max] = spec.grades;
      if (grade < min || grade > max) return false;
    }
    return true;
  });
}

/**
 * Блок промпта: какие формы задания модель может использовать.
 *
 * Формируется из реестра, а не вписан в шаблон промпта. Правила добавляются
 * записью в реестр, а не восемнадцатым «жёстким правилом» (ТЗ-33, AD-7).
 *
 * Список отсортирован по частоте: сначала пять привычных, потом новые —
 * модель при равных условиях выбирает первое, и привычные формы не
 * вытесняются редкими.
 */
export function buildTaskTypesPromptBlock(
  subject: string,
  grade: number,
  count: number,
): string {
  const specs = typesForSubject(subject, grade);
  const lines = specs.map((spec) => `- \`${spec.id}\` — ${spec.name}. ${spec.whatTeacherAsks}`);
  const limits = diversityLimits(count);
  return [
    "ДОСТУПНЫЕ ТИПЫ ЗАДАНИЙ (выбирай из этого списка, и только из него):",
    ...lines,
    "",
    "ПРАВИЛА РАЗНООБРАЗИЯ:",
    `1. В листе ${count} ${plural(count, "задание", "задания", "заданий")}. ` +
      `Не больше ${limits.maxSameType} ${plural(limits.maxSameType, "задания", "заданий", "заданий")} ` +
      `одного типа.`,
    limits.minOtherTypes > 0
      ? `2. Остальные ${limits.minOtherTypes} ${plural(limits.minOtherTypes, "задание", "задания", "заданий")} ` +
        `должны быть других видов.`
      : "2. Разнообразие в листе из одного задания не требуется.",
    limits.minTypes > 1
      ? `3. Используй не меньше ${limits.minTypes} разных типов за лист.`
      : "3. Разнообразие в таком коротком листе не требуется.",
    "4. Тип задания выбирай по смыслу, а не по кругу: расчёт — там, где считают, " +
      "соответствие — там, где есть две колонки, «по образцу» — там, где есть " +
      "разобранный пример в условии.",
    "5. Не выдумывай типов, которых нет в списке выше. Если подходящего типа " +
      "не нашлось — возьми ближайший по смыслу.",
  ].join("\n");
}

/**
 * Числовые ограничения разнообразия для листа из `count` заданий.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ НЕ «НЕ БОЛЬШЕ ПОЛОВИНЫ»
 * ─────────────────────────────────────────────────────────────────────────────
 * Первая версия правила звучала как «не больше половины заданий одного вида».
 * Формулировка неоднозначна: половина — от чего? Модель трактовала её как
 * угодно и выдавала листы, где шесть из восьми заданий были расчётами:
 * формально «не больше половины», по сути тот же однообразный лист.
 *
 * Теперь числа считаются в коде и попадают в промпт дословно — «не больше 6
 * одного типа из 12». Модели не нужно считать и не нужно интерпретировать:
 * лимит либо выполнен, либо нет.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * КАК СЧИТАЕТСЯ
 * ─────────────────────────────────────────────────────────────────────────────
 * · `maxSameType` — верхняя граница доли одного типа: округлённая вверх
 *   половина, но не меньше 1. Для 12 заданий это 6, для 5 — 3, для 1 — 1.
 *   Округление ВВЕРХ, а не вниз: при 5 заданиях «не больше 2 одного вида»
 *   запрещало бы нормальный лист из трёх расчётов и двух коротких ответов.
 * · `minOtherTypes` — сколько заданий обязаны быть ДРУГИХ видов: это
 *   `count − maxSameType`, то есть сколько остаётся, когда один тип занял
 *   максимум.
 * · `minTypes` — минимальное число РАЗНЫХ типов в листе. Для коротких листов
 *   (1–3 задания) требование «минимум два типа» бессмысленно: лист из двух
 *   заданий не разнообразишь, и требование только мешает. Поэтому при
 *   `count ≤ 3` достаточно одного типа, дальше — минимум два.
 *
 * Лист из одного задания — частый случай (учитель хочет «одно задание на
 * доску»): там `maxSameType = 1`, и никакого разнообразия не требуется.
 */
export interface DiversityLimits {
  /** Максимум заданий одного типа. */
  maxSameType: number;
  /** Минимум заданий других типов. */
  minOtherTypes: number;
  /** Минимальное число разных типов в листе. */
  minTypes: number;
}

export function diversityLimits(count: number): DiversityLimits {
  const safeCount = Math.max(1, Math.floor(count));
  const maxSameType = Math.max(1, Math.ceil(safeCount / 2));
  return {
    maxSameType,
    minOtherTypes: Math.max(0, safeCount - maxSameType),
    minTypes: safeCount >= 4 ? 2 : 1,
  };
}

/**
 * Русское склонение по числу: «1 задание», «2 задания», «5 заданий».
 *
 * Написано здесь, а не взято из `plural()` из `src/lib/utils/cn.ts`: этот
 * файл — единственный, который бэк читает из фронта, а `cn.ts` тянет за собой
 * `clsx` и `tailwind-merge`, которых в `backend/node_modules` нет. Правило
 * склонения тут одно, и оно не менялось.
 */
function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  if (mod10 === 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return many === "заданий" ? "задания" : few;
  return many;
}
