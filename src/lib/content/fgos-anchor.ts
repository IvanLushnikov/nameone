/**
 * ФГОС-ЯКОРЬ ДЛЯ ЗАПРОСА (ТЗ-39): раздел программы + один пример.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ОТДЕЛЬНЫЙ ФАЙЛ
 * ─────────────────────────────────────────────────────────────────────────────
 * Таксономия ФГОС собрана и проверена: 5 658 тем по 141 паре «предмет × класс»,
 * покрытие полное. У каждой темы есть `fgosRef` — название раздела федеральной
 * программы — и `examples`: примеры заданий, написанные ПО ЭТОМУ СОДЕРЖАНИЮ.
 *
 * Но до генерации эта таксономия не доходила: в запрос уезжало только название
 * темы, и модель выдумывала навыки сама. Якорь — это ровно то, чего не
 * хватало: ЧТО проверять (название раздела) и КАК это звучит (один пример).
 *
 * Файл отдельный, потому что это ПРАВИЛО ВЫБОРА, а не данные: правило должно
 * быть в одном месте, иначе через месяц в конструкторе появится свой
 * «а давай ещё и раздел пришлём», а в бэке — свой «а давай и пример».
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПРАВИЛА ВЫБОРА (и почему именно такие)
 * ─────────────────────────────────────────────────────────────────────────────
 * 1. ТЕМА ИЗ КАТАЛОГА — РАЗДЕЛ ЕСТЬ. Берём `topic.fgosRef` как есть: это
 *    название раздела федеральной программы, а не наш пересказ.
 *
 * 2. ТЕМА БЕЗ РАЗДЕЛА — ЯКОРЯ НЕТ. У части тем раздел не проставлен (у 4
 *    программ эталон не собран, у одной нет источника). Придумывать раздел
 *    нельзя: тогда модель получит выдумку и будет считать её программой —
 *    ровно тот дефект, который задача чинит. Тема без раздела работает как
 *    раньше.
 *
 * 3. ТЕМА, ВВЕДЁННАЯ РУКАМИ, — ЯКОРЯ НЕТ. Её нет в каталоге, значит нет и
 *    раздела программы. Выдумывать нечего.
 *
 * 4. ПРИМЕР — РОВНО ОДИН. Два примера превращаются в шаблон: модель начинает
 *    повторять их конструкции, а сузить разнообразие — ровно тот дефект,
 *    который здесь чинят.
 *
 * 5. ОБРЕЗКУ НЕ ДЕЛАЕМ. Длинные разделы (в литературе 10 класса есть на 549
 *    знаков) обрезает бэк, в промпте: правило обрезки должно быть одно, и
 *    бэк — последний, кто видит значение из браузера.
 */

import { getTopic } from "./subjects";
import type { GenerationRequestMeta } from "../types";

/**
 * Якорь для запроса — ровно те два поля, которые едут в `request.meta`.
 *
 * Названия полей совпадают с бэком (`backend/src/types.ts`): значение идёт по
 * сети без преобразования.
 */
export type FgosAnchor = NonNullable<GenerationRequestMeta> & {
  fgosRef: string;
};

/**
 * Собрать якорь по теме из каталога.
 *
 * @param subject слаг предмета (`math`, `history`, …).
 * @param grade   класс.
 * @param topicSlug слаг темы; `null` — тема не выбрана.
 * @returns якорь или `null`, если якоря нет (см. правила выше).
 */
export function fgosAnchorForTopic(
  subject: string,
  grade: number,
  topicSlug: string | null | undefined,
): FgosAnchor | null {
  if (!topicSlug) return null;
  const topic = getTopic(subject, grade, topicSlug);
  // Темы может не быть в каталоге (тема, введённая руками; экзаменационный
  // режим, где тема синтезирована) — тогда якоря нет, и запрос уходит как
  // раньше.
  if (!topic?.fgosRef) return null;

  const example = topic.examples?.[0];
  return {
    fgosRef: topic.fgosRef,
    ...(example
      ? {
          fgosExample: {
            text: example.text,
            ...(example.answer ? { answer: example.answer } : {}),
          },
        }
      : {}),
  };
}
