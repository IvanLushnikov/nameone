/**
 * Предметно-зависимое содержание массовых страниц.
 *
 * ## Зачем этот файл существует
 *
 * Страницы темы, плана урока и презентации собирали текст из ЖЁСТКО ЗАШИТЫХ
 * массивов в теле компонента. Менялись только имя предмета, номер класса и
 * название темы — весь остальной текст был одинаковым на всех 1075 страницах.
 * Замер по собранному сайту это показывал: длина видимого текста у страниц
 * плана урока держалась в коридоре 2819–3136 знаков (разброс 10,7%).
 *
 * Здесь лежат данные, которые РЕАЛЬНО зависят от предмета и класса: какие
 * операции входят в тему на этом этапе, что типично проседает у учеников,
 * из чего состоит урок по этому предмету, как выглядит готовый лист.
 *
 * ## Правило «никаких выдуманных чисел»
 *
 * В этих данных НЕТ цифр, которых нет в коде продукта. Длительность урока
 * (45 минут) и диапазон числа заданий (5–30) взяты из бэкенда и конструктора:
 * см. `backend/src/llm/prompts/lesson-plan-gen.ts` («хронометраж_урока_минут:
 * 45») и `src/components/constructor/ArtifactTypePicker.tsx` («5–30 заданий»).
 * Хронометраж по стадиям на странице НЕ проставлен: план собирает модель, и
 * сколько минут достанется конкретной стадии — заранее неизвестно, значит
 * печатать цифры на маркетинговой странице было бы выдумкой.
 *
 * ## Правило «норма ссылается на норму»
 *
 * Никаких номеров приказов и цитат из ФГОС здесь нет. Пункт программы, по
 * которому идёт страница, берётся из поля `fgosRef` самой темы — то есть из
 * таксономии, а не из этого файла.
 */

import type { SubjectSlug } from "../../types";

/**
 * Стадия урока. Значения `kind` — те же шесть, что и в бэкенде
 * (`LessonPlanStage.kind` в `backend/src/llm/prompts/lesson-plan-gen.ts`).
 * Держим их в том же виде, чтобы по этой странице можно было понять, какая
 * стадия в готовом DOCX за что отвечает.
 */
export type LessonStageKind =
  | "org-moment"
  | "motivation"
  | "new-topic"
  | "practice"
  | "reflex"
  | "homework";

export type LessonStage = {
  kind: LessonStageKind;
  /** Название стадии так, как его называет предметник, а не как в общем шаблоне. */
  name: string;
  /** Что делает учитель в этой стадии — конкретно по предмету. */
  teacher: string;
  /** Что делают ученики. */
  students: string;
};

/** Слайд презентации по предмету: заголовок и что на нём стоит. */
export type SlideUnit = {
  name: string;
  content: string;
};

/**
 * Содержание по одному классу (или по диапазону классов).
 *
 * Все поля — про содержание, а не про продукт: что входит в тему на этом
 * этапе, с чем у учеников обычно не получается, как выглядит работа.
 */
export type GradeContent = {
  /** Что охватывает тема на этом этапе — одной фразой, по-человечески. */
  focus: string;
  /** Конкретные операции и понятия, которые входят в тему. */
  operations: string[];
  /** Что типично проседает у учеников на этом этапе. */
  pitfalls: string[];
  /** Чем работа с темой отличается на этом этапе — вид заданий, темп, опора. */
  workingStyle: string;
};

export type SubjectContent = {
  slug: SubjectSlug;
  /** Как предмет называется в федеральной рабочей программе. */
  programArea: string;
  /** Главное действие ученика — как выглядит выполнение задания. */
  workKind: string;
  /** Как выглядит готовый лист по этому предмету. */
  worksheetLook: string;
  /**
   * Как примеры из темы попадают на урок. Отдельное поле, а не часть
   * `worksheetLook`, потому что формулировка зависит от предмета: у
   * математики «сначала у доски, затем в тетради», у физкультуры
   * «показывается и отрабатывается на площадке». Общая фраза выдавала бы
   * предмет, которому она не подходит.
   */
  exampleFraming: string;
  /** Этапы урока по предмету — вместо общего списка из шести стадий. */
  lessonStages: LessonStage[];
  /** Структура слайдов презентации по предмету. */
  slidePlan: SlideUnit[];
  /** Оборудование и материалы, которые предметник реально ставит на стол. */
  equipment: string[];
  /** Сложности предмета, общие для всех классов. */
  basePitfalls: string[];
  /** Данные по конкретным классам — приоритетный источник. */
  grades: Record<number, GradeContent>;
  /** Данные по диапазону классов — берутся, если точного класса нет. */
  bands: GradeBand[];
  /**
   * Уровень наполненности предмета. `deep` — есть записи по каждому классу
   * предмета; `subject` — только предметный уровень и диапазоны.
   *
   * Нужен не для красоты: по нему видно, где контент настоящий, а где честная
   * заглушка. Показывается в отчёте, а не пользователю.
   */
  depth: "deep" | "subject";
};

export type GradeBand = {
  from: number;
  to: number;
  content: GradeContent;
};

/**
 * Собранный ответ: содержание под текущую тему + признак, под каким уровнем
 * оно найдено. Страницам нужно знать оба.
 */
export type TopicContent = {
  subject: SubjectContent;
  grade: GradeContent;
  /** Точная запись по классу или диапазон — от этого зависит честность текста. */
  match: "exact" | "band";
  /** Уровень наполненности предмета (см. `SubjectContent.depth`). */
  depth: SubjectContent["depth"];
  /** Есть ли вообще содержание по предмету. */
  filled: boolean;
};