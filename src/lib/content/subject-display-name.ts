/**
 * Человеческое название предмета (ТЗ-26, Ф-3, 13.10.2026).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ФАЙЛ
 * ─────────────────────────────────────────────────────────────────────────────
 * Внутренний ключ предмета (`algebra`, `math`, `english`) попадал в раздаточный
 * материал: в шапку DOCX «algebra · 8 класс · средний уровень» и в имя файла
 * `algebra-8kl-сокращение-и-действия.docx`. Учитель, который отдаёт файл ученику
 * или коллеге, получает латиницу там, где должно быть «Алгебра».
 *
 * Правило простое: КЛЮЧ ПРЕДМЕТА НЕ ВЫХОДИТ В ИНТЕРФЕЙС И В ИМЯ ФАЙЛА.
 * Ключ остаётся ключом — он нужен роутерам, таксономии и запросам к бэку.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО НЕ ДЕЛАЕМ
 * ─────────────────────────────────────────────────────────────────────────────
 * Отдельную карту «slug → название» здесь НЕ заводим: название предмета уже
 * есть в таксономии (`src/lib/content/subjects.ts`, поле `title`). Дублировать
 * его значит через месяц получить две разные карты и расхождение на странице.
 * Единственный источник — таксономия.
 */

import { getSubject } from "@/lib/content/subjects";

/**
 * Название предмета по-русски для показа учителю.
 *
 * Если предмета в таксономии нет (новый слаг, которого ещё не завели) —
 * возвращаем сам slug. Заглушка «Предмет» была бы хуже: в файле и в шапке
 * появилось бы «Предмет · 8 класс», и дефект стал бы невидимым.
 */
export function subjectDisplayName(slug: string | null | undefined): string {
  if (!slug) return "";
  return getSubject(slug)?.title ?? slug;
}
