/**
 * Лёгкая сводка таксономии для клиентского кода.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ФАЙЛ
 * ─────────────────────────────────────────────────────────────────────────────
 * `subjects.ts` — источник правды по таксономии, но он весит ~3.8 МБ: кроме
 * базовых классов он тянет `grade-extensions/fgos-program/data.json` (3.5 МБ —
 * 5 492 темы с текстами заданий). Любой клиентский компонент, который импортирует
 * `subjects.ts`, утаскивал эти 3.8 МБ в браузер: webpack запекал их в общий
 * чанк на 4.2 МБ, и тот грузился на семи маршрутах, включая главную.
 *
 * Клиенту нужна от таксономии ровно одна вещь — «визитка» предмета и счётчики:
 * название, эмодзи, цвет, описание, номера классов, число тем в классе и слаг
 * первой темы. Всё это помещается в десятки килобайт.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЭТО НЕ ДУБЛЬ ТАКСОНОМИИ
 * ─────────────────────────────────────────────────────────────────────────────
 * Файл `subject-index.json` генерируется скриптом `scripts/build-subject-index.mjs`
 * из `subjects.ts` — то есть из того же источника. Руками здесь не написано
 * ни строчки: любое расхождение с таксономией ловит тест
 * `tests/subject-index.test.ts`, который пересобирает сводку на лету и сверяет
 * с файлом на диске.
 *
 * Если файл разошёлся с таксономией — падает тест, а не появляется неправда
 * в цифрах на главной.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * КОГДА ЧТО ИСПОЛЬЗОВАТЬ
 * ─────────────────────────────────────────────────────────────────────────────
 * - Нужны темы, их тексты, примеры заданий, классы целиком → `subjects.ts`.
 *   Это серверный код или редкий интерактив (конструктор листов).
 * - Нужна «визитка» предмета, счётчики, слаг первой темы → этот файл.
 */

import raw from "./subject-index.json";

/** Счётчики и слаг первой темы для одного класса. */
export interface SubjectIndexGrade {
  num: number;
  title: string;
  /** Сколько тем в классе. Считается из таксономии при генерации сводки. */
  topicsCount: number;
  /** Слаг первой темы класса — на неё ведёт карточка. `null`, если тем нет. */
  firstTopicSlug: string | null;
}

/** «Визитка» предмета: всё, что нужно карточке и заголовку. */
export interface SubjectIndexEntry {
  slug: string;
  title: string;
  shortTitle: string;
  emoji: string;
  color: string;
  description: string;
  grades: SubjectIndexGrade[];
}

export const subjectIndex: SubjectIndexEntry[] = raw as SubjectIndexEntry[];

/** Суммарное число тем по всем предметам — «5 492 темы» на главной. */
export function totalTopicsCount(): number {
  let total = 0;
  for (const s of subjectIndex) {
    for (const g of s.grades) total += g.topicsCount;
  }
  return total;
}

/** Суммарное число пар (предмет, класс). */
export function totalGradePairsCount(): number {
  let total = 0;
  for (const s of subjectIndex) total += s.grades.length;
  return total;
}

/** Число тем в одном предмете. */
export function subjectTopicsCount(entry: SubjectIndexEntry): number {
  let total = 0;
  for (const g of entry.grades) total += g.topicsCount;
  return total;
}

/**
 * «Визитка» предмета по slug.
 *
 * Если предмета нет (новый slug, который ещё не завели) — возвращается
 * `undefined`, и вызывающий код показывает slug вместо названия. Заглушка
 * «Предмет» была бы хуже: в интерфейсе появилось бы «Предмет · 8 класс», и
 * дефект стал бы невидимым.
 */
export function getSubjectIndex(slug: string): SubjectIndexEntry | undefined {
  return subjectIndex.find((s) => s.slug === slug);
}
