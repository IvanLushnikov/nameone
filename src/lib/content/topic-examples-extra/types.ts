/**
 * Дополнительные примеры заданий для тем, у которых их было мало.
 *
 * ## Зачем отдельный слой
 * Темы с одним примером задания — это наследие первой наполняющей серии.
 * Блок «Примеры заданий» на странице темы — то, из чего учитель видит
 * качество листа; с одним примером он выглядит пустым. Править все 62
 * темы прямо в `subjects.ts` нельзя: файл на 5000 строк, любая правка
 * конфликтует с любой другой. Поэтому дополнения лежат здесь и сливаются
 * в `subjects.ts` по ключу `предмет/класс/slug` тем же приёмом, что и
 * `grade-extensions` — дописыванием, а не заменой.
 *
 * ## Формат
 * Ключ — `предмет/класс/slug`, значение — примеры, которые ДОПИСЫВАЮТСЯ
 * к уже существующим. Существующий пример при этом не меняется: он может
 * быть в индексе поисковика как часть сниппета.
 *
 * @example
 * "geometry/8/srednyaya-liniya": [
 *   { text: "Стороны треугольника равны 6, 8 и 10. Найдите среднюю линию.", answer: "3" },
 * ]
 */

