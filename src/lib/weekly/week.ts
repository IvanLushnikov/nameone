/**
 * Порядковый номер учебной недели (09.10.2026).
 *
 * Взято во `use client` виджетом «Тема недели», когда бэк недоступен, и
 * дублирует `getWeekIndex` в `backend/src/jobs/weeklyTopic.ts`.
 *
 * Дублирование намеренное: бэк и фронт — разные пакеты, а связать их импортом
 * нельзя. Расхождение здесь безвредно — номер недели лишь выбирает тему из
 * списка, и ошибка на единицу сдвигает ротацию на одну позицию, а не ломает
 * страницу. Именно поэтому бэк остаётся источником истины, а эта копия — только
 * запасной путь.
 *
 * Первая неделя учебного года — та, что начинается 1 сентября.
 */
export function getWeekIndex(now: Date = new Date()): number {
  // Учебный год переходит в следующий календарный в сентябре, а не в январе:
  // в декабре «учебный год» — это тот, что начался в сентябре этого же года.
  const year = now.getMonth() >= 8 ? now.getFullYear() : now.getFullYear() - 1;
  const yearStart = new Date(year, 8, 1);
  const diffMs = now.getTime() - yearStart.getTime();
  // +1: первая неделя года — первая, а не нулевая.
  return Math.max(1, Math.floor(diffMs / (7 * 24 * 60 * 60 * 1000)) + 1);
}