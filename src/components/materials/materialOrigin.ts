/**
 * Кто автор материала — редакция или учитель.
 *
 * Поле `author` есть в каждой записи каталога (`MaterialEntry`), и сейчас
 * оно у всех 150 записей одно и то же: «Редакция УчЛист» (`EDITORIAL_AUTHOR`
 * в `materials-catalog.ts`). Авторских публикаций учителей на сайте ещё нет:
 * ТЗ-15 §14 прямо пишет, что Фазы 2–3 (авторские публикации, Pages
 * Functions) не реализованы. То есть весь `/material/*` сегодня —
 * редакционный каталог, и это нормальные SEO-страницы под длинный хвост
 * («контрольная по математике 5 класс дроби»), а не пользовательский контент.
 *
 * Отсюда решение про robots: директива считается ПО ЗАПИСИ, а не по маршруту.
 * Редакционный материал индексируется, материал учителя — нет. Один и тот же
 * адрес `/material/<slug>/` обслуживает и то и другое, поэтому по URL принцип
 * не работает: пришлось бы закрыть от индексации 150 нормальных страниц
 * вместе с будущими материалами учителей.
 *
 * Что это даёт: `noindex, follow` ставится материалу учителя, когда он
 * появится (Фаза 2), и не трогает редакционный каталог, который ради
 * индексации и делался.
 */

/** Редакционный автор. Совпадает с `EDITORIAL_AUTHOR` в materials-catalog.ts. */
export const EDITORIAL_AUTHOR = "Редакция УчЛист";

/** Материал из редакционного каталога — его можно и нужно индексировать. */
export function isEditorialMaterial(material: { author: string }): boolean {
  return material.author === EDITORIAL_AUTHOR;
}

/**
 * robots для страницы материала.
 *
 * Учительский материал — `noindex, follow`: ссылку передаём, страницу в
 * индекс не пускаем. Причина не техническая, а продуктовая: у нас нет ни
 * рейтинга, ни счётчика использований, ни истории правок, а модерация
 * авторских публикаций по ТЗ-15 §6 идёт через ручную очередь. Индексируя
 * такое, мы отдаём наружу страницы, качество которых ещё не проверено.
 *
 * Редакционный материал — `index, follow`: это наш SEO-актив, его прячем
 * только в одном случае — если запись каталога вдруг перестанет быть
 * редакционной (сменится автор).
 */
export function materialRobots(material: { author: string }): {
  index: boolean;
  follow: boolean;
} {
  return { index: isEditorialMaterial(material), follow: true };
}