export function generateStaticParams() {
  return Object.keys(docs).map((slug) => ({ slug }));
}

export function generateMetadata({ params }: { params: { slug: string } }) {
  const doc = docs[params.slug];
  if (!doc) return { title: "Документ", robots: { index: false, follow: true } };
  return {
    description: doc.description,
    // «· УчЛист» добавляет шаблон из root layout — руками дописывать нельзя,
    // иначе в заголовке получается «… · УчЛист · УчЛист».
    title: doc.title,
    robots: { index: true, follow: true },
  };
}

export default function LegalPage({ params }: { params: { slug: string } }) {
  const doc = docs[params.slug];
  if (!doc) return null;

  return (
    <div className="container-tight max-w-3xl py-12">
      <div className="mb-6">
        <Link href="/" className="text-sm text-warm-500 hover:text-warm-900">
          ← На главную
        </Link>
      </div>
      <Card>
        <h1 className="text-3xl font-display font-bold text-warm-950 mb-1">
          {doc.title}
        </h1>
        <p className="text-sm text-warm-500 mb-8">Обновлено: {doc.updated}</p>

        <div className="space-y-6 prose prose-warm max-w-none">
          {doc.sections.map((s) => (
            <section key={s.h}>
              <h2 className="text-lg font-semibold text-warm-950 mb-2">{s.h}</h2>
              <p className="text-sm text-warm-700 leading-relaxed">{s.p}</p>
            </section>
          ))}
        </div>
      </Card>
    </div>
  );
}