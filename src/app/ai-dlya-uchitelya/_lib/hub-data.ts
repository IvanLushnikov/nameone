export const HUB_POSTS: HubPost[] = POST_SLUGS.map(({ slug, note }) => {
  const post = getPost(slug);
  if (!post) {
    // Молча пропустить пост нельзя: хаб — оглавление, и дырка в нём видна
    // читателю как «написали и забросили».
    throw new Error(
      `Хаб ссылается на пост ${slug}, но файла src/app/blog/posts/${slug}.md нет. Ссылка убрана или пост переименован.`,
    );
  }
  return {
    href: `/blog/${slug}/`,
    title: post.title,
    category: post.category,
    note,
  };
});

