/**
 * Данные хаба «ИИ для учителя» — `/ai-dlya-uchitelya/`.
 *
 * ## Зачем файл
 *
 * Хаб — это оглавление: он перечисляет блог, предметы и сравнения и держит
 * между ними смысловую связь. Такая страница держится на двух вещах, которые
 * ломаются одинаково незаметно:
 *
 *  1. **Ссылки ведут туда, куда должны.** Слаги и заголовки постов берутся из
 *     `getPost()` — из тех же `.md`, из которых собираются сами посты. Список
 *     на хабе не может разойтись с блогом: переименовали пост — сборка упала
 *     на отсутствующем файле, а не выпустила страницу со ссылкой в никуда.
 *  2. **Разметка совпадает с текстом.** `HUB_SECTIONS` — это одновременно
 *     оглавление для читателя и `ItemList` в JSON-LD. Список в разметке и
 *     список на странице строятся из одной константы, поэтому поисковик не
 *     может увидеть «оглавление», которого на странице нет.
 *
 * ## Почему порядок постов задан вручную
 *
 * `getAllPosts()` сортирует по дате. Для хаба это не то: восемь постов
 * разложены по смыслу — сначала то, что учитель спрашивает в первую очередь
 * (где теряют баллы), потом методика урока. Список по дате смешал бы «ВПР» и
 * разбор дробей в одну ленту и потерял бы структуру.
 */

