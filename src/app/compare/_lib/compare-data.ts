/* ── наши цифры, посчитанные из кода ────────────────────────────────── */

/**
 * Разряды через обычный пробел, а не через toLocaleString: в некоторых средах
 * ru-RU возвращает узкий неразрывный пробел, и в выдаче рядом с цифрой
 * появляется символ, который читается как «сломанный» шрифт.
 */
const num = (n: number): string => String(n).replace(/\B(?=(\d{3})+(?!\d))/g, " ");

const monthPrice = (plan: "base" | "standard" | "plus"): string =>
  `${num(PLANS[plan].prices.month.amount)} ₽/мес`;

/**
 * Цена за учебный год. Тип допускает `null` у тарифа без годового периода —
 * на странице сравнения молча пропускать такую цену нельзя, падаем сразу.
 */
const yearPrice = (plan: "base" | "standard" | "plus"): string => {
  const year = PLANS[plan].prices.academicYear;
  if (!year) throw new Error(`У тарифа ${plan} нет цены за учебный год — сравнение собирает неполную цену`);
  return `${num(year.amount)} ₽ за учебный год (${ACADEMIC_YEAR_MONTHS} мес)`;
};

/** Та же цена в пересчёте на месяц — для честного сравнения с месячными тарифами. */
const yearPerMonth = (plan: "base" | "standard" | "plus"): number => {
  const year = PLANS[plan].prices.academicYear;
  if (!year?.perMonth) {
    throw new Error(`У тарифа ${plan} нет пересчёта в месяц — сравнение собирает неполную цену`);
  }
  return year.perMonth;
};

const monthlyWorksheets = (plan: "base" | "standard" | "plus"): string => {
  const norm = PLANS[plan].normPerMonth;
  if (norm === null) throw new Error(`У тарифа ${plan} нет нормы в месяц — сравнение собирает неполную строку`);
  return `${tokensToWorksheetsLabel(norm)} в месяц`;
};

/** Предметов и тем — из `subjects.ts`, а не из памяти и не из файла фактов. */
const SUBJECT_COUNT = subjects.length;
const GRADE_COUNT = subjects.reduce((acc, s) => acc + s.grades.length, 0);
const TOPIC_COUNT = subjects.reduce(
  (acc, s) => acc + s.grades.reduce((g, gr) => g + gr.topics.length, 0),
  0,
);
const TOPIC_FGOS_COUNT = subjects.reduce(
  (acc, s) =>
    acc +
    s.grades.reduce(
      (g, gr) => g + gr.topics.filter((t) => Boolean(t.fgosRef)).length,
      0,
    ),
  0,
);

/** «1 075 тем» — тем самым разрядом, что и в файле фактов. */
const TOPIC_COUNT_LABEL = num(TOPIC_COUNT);

/** «1 075 тем, у 760 указан раздел ФГОС» — одна строка во всех трёх таблицах. */
const TOPICS_WITH_FGOS_LABEL = `${TOPIC_COUNT_LABEL} тем, у ${num(
  TOPIC_FGOS_COUNT,
)} указан раздел ФГОС`;

