import type { Metadata } from "next";

/**
 * Метаданные журнала живут здесь, а не в page.tsx: страница — клиентский
 * компонент («use client»), а `export const metadata` в таком файле запрещён
 * (Next роняет сборку, причём `tsc` и vitest при этом зелёные). Layout —
 * серверный компонент, и его metadata покрывают всю сегментную страницу.
 * Корневой layout не трогаем: он даёт template "%s · УчЛист", поэтому бренд
 * в title руками не пишем — иначе будет «Журнал проверок · УчЛист · УчЛист».
 *
 * Заголовок вкладки был не точен: без этого файла страница наследовала
 * дефолтный title главной («УчЛист — рабочие листы по ФГОС за 30 секунд»),
 * то есть вкладка называлась совсем не тем, чем является страница.
 *
 * `robots: noindex` — журнал закрыт входом и содержит персональные данные
 * учеников (фото тетрадей, отметки). В публичный индекс ему нельзя.
 */
export const metadata: Metadata = {
  title: "Журнал проверок",
  description:
    "Все работы, проверенные по фото: отметка, баллы и пометка, поставил её ИИ или вы сами.",
  robots: { index: false, follow: false },
};

export default function JournalLayout({ children }: { children: React.ReactNode }) {
  return children;
}
