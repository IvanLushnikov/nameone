/**
 * ТЗ-33: страница `/methodology` не должна врать о числе форм задания.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ЭТОТ ТЕСТ
 * ─────────────────────────────────────────────────────────────────────────────
 * Страница «Методика» — та, где продукт объясняет учителю, как устроен
 * материал. Раньше она перечисляла пять форм задания, и это было правдой.
 * После ТЗ-33 форм семнадцать, но текст остался прежним: страница продолжала
 * говорить «расчёт, выбор из вариантов, краткий ответ, развёрнутый ответ,
 * вставь в пропуск» — то есть врать ровно там, где обещана честность.
 *
 * Число берётся из РЕЕСТРА (`TASK_TYPE_COUNT`), а не зашито в тест: если
 * реестр расширяют, тест обязан обновляться вместе с текстом страницы, а не
 * молча пропускать рассинхрон.
 *
 * Проверка сделана по СМЕЖНОСТИ с числом («17 форм задания»), а не по входу
 * самого числа: иначе тест проходил бы и на старом тексте, где «17» и так
 * встречается где-то ещё на странице (в счётчиках тем).
 *
 * Сеть не используется, таймеров нет.
 */

import { describe, it, expect } from "vitest";
import { render } from "@testing-library/react";
import MethodologyPage from "@/app/methodology/page";
import { TASK_TYPE_COUNT } from "@/lib/content/trust";
import { TASK_TYPE_REGISTRY } from "@/lib/content/task-types";

describe("ТЗ-33: страница /methodology честно говорит о формах задания", () => {
  it("страница называет число форм, равное числу в реестре", () => {
    render(MethodologyPage());
    const text = document.body.textContent ?? "";

    // Число стоит рядом со словом «форм» — иначе проверка ловила бы любое
    // «17» на странице, а не число форм задания.
    expect(text).toMatch(new RegExp(`${TASK_TYPE_COUNT}\\s+форм`));
  });

  it("страница не утверждает, что форм всего пять", () => {
    render(MethodologyPage());
    const text = document.body.textContent ?? "";

    expect(text).not.toMatch(/пять\s+форм\s+задания/i);
  });

  it("число на странице совпадает с реестром, а не с зашитой константой", () => {
    // Страховка от «забыли обновить текст»: если бы константа в тексте
    // разошлась с реестром, проверка выше перестала бы иметь смысл.
    expect(TASK_TYPE_COUNT).toBe(TASK_TYPE_REGISTRY.length);
    expect(TASK_TYPE_COUNT).toBeGreaterThan(5);
  });
});
