/**
 * Вес страницы `/materials/` (блок C, кейс С-1 и С-2, аудит 11.10.2026).
 *
 * ## Что именно ловит этот файл
 *
 * 11.10.2026 страница отдавала `out/materials/index.html` весом 839 899 байт —
 * втрое тяжелее главной. Первый исполнитель объяснил это служебным блоком RSC
 * и искал клиентские компоненты с каталогом в пропсах. Их на странице не было.
 *
 * Настоящая причина — обычная разметка. Страница выводила ВЕСЬ каталог:
 * `MATERIALS_CATALOG.map(...)` в блоке «Весь каталог» (150 карточек), плюс
 * `getFeaturedMaterials(6)` выше и по 6 карточек в каждой из пяти секций
 * «Каталог по цели» (ещё 30). Итого 186 карточек по ~1,4 КБ разметки, и
 * каждая из них уезжала в HTML второй раз — внутри RSC-payload, который Next
 * кладёт рядом с разметкой.
 *
 * ## Почему тест ловит именно эту проблему, а не что-то другое
 *
 * Проверяется не размер собранного файла (сборка зависит от окружения и
 * медленная), а причина: сколько карточек каталога реально попало в разметку
 * и какого размера она получилась. На сломанном коде это 186 ссылок
 * `/material/...` при каталоге в 150 записей — то есть страница отдавала
 * больше карточек, чем есть в каталоге, потому что одни и те же записи
 * печатались в нескольких блоках сразу. Ровно это и есть раздувание.
 *
 * Порог `links.length <= 60` не привязан к текущим блокам страницы: он
 * означает «страница не рисует каталог целиком». Набор блоков может меняться,
 * защита от возврата именно этого дефекта — нет.
 */

import { createElement } from "react";
import { describe, it, expect } from "vitest";
import { renderToStaticMarkup } from "react-dom/server";
import MaterialsHubPage from "@/app/materials/page";
import { MATERIALS_CATALOG } from "@/lib/content/materials-catalog";

/** Порог С-1: 200 КБ на собранный файл (204 800 байт). */
const SIZE_LIMIT_BYTES = 200 * 1024;

/** Сколько ссылок на материалы страница имеет право отдать за раз. */
const MAX_MATERIAL_LINKS = 60;

describe("Банк материалов: страница не раздувается каталогом", () => {
  /** Разметка хаба — ровно то, что попадает в собранный HTML. */
  const html = () => renderToStaticMarkup(createElement(MaterialsHubPage));
  const materialLinks = () => html().match(/href="\/material\/[^"]+"/g) ?? [];

  // ГЛАВНАЯ проверка. На сломанном коде здесь было 186 ссылок при каталоге
  // в 150 записей, и тест падал с сообщением «страница отдала 186 карточек».
  it("не выводит весь каталог на сервере", () => {
    const links = materialLinks();

    expect(
      links.length,
      `страница отдала ${links.length} карточек при каталоге в ${MATERIALS_CATALOG.length} записей`,
    ).toBeLessThanOrEqual(MAX_MATERIAL_LINKS);

    // Выдача страницы заведомо меньше каталога, но не пустая.
    expect(links.length).toBeGreaterThan(0);
    expect(links.length).toBeLessThan(MATERIALS_CATALOG.length);
  });

  // Каталог не должен попадать в страницу и через пропсы клиентского
  // компонента: фильтру нужны слаг, заголовок, предмет, класс и цель.
  // Описание записи (250–800 символов) живёт на странице самого материала.
  it("в разметку не утекают описания материалов", () => {
    const markup = html();

    for (const m of MATERIALS_CATALOG.slice(0, 20)) {
      // Хвост описания — уникальная CTA-фраза, которой в заголовке нет.
      const tail = m.description.slice(-70);
      expect(
        markup.includes(tail),
        `описание материала ${m.slug} попало в разметку страницы`,
      ).toBe(false);
    }
  });

  // 126 УМК, и у каждого раньше была инлайновая иконка BookOpen — та же
  // строка SVG на 452 байта, то есть 57 КБ на страницу. Иконка не несла
  // смысла: рядом стоит название учебника текстом.
  it("страница не тащит сотни одинаковых инлайновых иконок", () => {
    const svgs = (html().match(/<svg/g) ?? []).length;
    expect(svgs, `инлайновых SVG на странице: ${svgs}`).toBeLessThan(30);
  });

  // Разметка сама по себе должна быть заметно меньше 200 КБ. Порог с запасом
  // относительно С-1: собранный файл — это разметка ПЛЮС RSC-payload, который
  // Next кладёт в тот же HTML, поэтому на разметку оставляем половину бюджета.
  // Итоговый порог проверяется на реальном файле сборки — см. отчёт агента.
  it("разметка страницы заметно меньше бюджета", () => {
    const bytes = Buffer.byteLength(html(), "utf8");
    // На сломанном коде здесь было 366 КБ.
    expect(bytes, `разметка страницы: ${bytes} байт`).toBeLessThan(SIZE_LIMIT_BYTES / 2);
  });
});