/**
 * /api/track — заглушка + последний рубеж для неизвестных /api/*.
 *
 * Серверный event-tracker для фронтовых trackEvent() вызовов.
 * Сейчас фронт пишет события только локально (см. src/lib/track.ts), поэтому
 * эндпоинт не активен: на /api/track отвечаем 501 — честно «не реализовано».
 *
 * ПОЧЕМУ ОСТАЛЬНОМУ — 404, А НЕ 501 (07.10.2026)
 *
 * Этот роутер подключается ПОСЛЕДНИМ под префиксом /api, поэтому `all("*")`
 * ловил вообще всё, что не совпало с зарегистрированными роутами, и отдавал
 * «Server-side tracking ещё не реализован». Именно из-за этого пять типов
 * материалов (lesson-plans, presentations, ktp, cards, materials) месяцами
 * отдавали 501 с текстом про трекинг: диагностировать это по ответу было
 * невозможно — 501 читается как «сервис есть, но временно недоступен», а не
 * как «такого адреса нет».
 *
 * Теперь честная семантика:
 *   /api/track      → 501 «трекинг не реализован» (так и есть);
 *   любой другой /api/* → 404 «нет такого адреса», с указанием пути.
 * Такой ответ нельзя спутать ни с «сбой», ни с «сервис недоступен».
 */

import { Hono } from "hono";
import type { Env } from "../env";

const trackRouter = new Hono<{ Bindings: Env }>();

// Собственно заглушка трекинга.
trackRouter.all("/track", (c) =>
  c.json(
    {
      ok: false,
      code: "NOT_IMPLEMENTED",
      error: "Server-side tracking ещё не реализован",
    },
    501,
  ),
);

// Всё прочее под /api — адреса не существует.
trackRouter.all("*", (c) =>
  c.json(
    {
      ok: false,
      code: "NOT_FOUND",
      error: "Такого адреса нет",
      path: c.req.path,
    },
    404,
  ),
);

export { trackRouter };