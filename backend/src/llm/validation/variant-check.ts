/**
 * Проверка «два варианта контрольной — РАЗНЫЕ» (ТЗ-25, AD-1).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЭТО КОД, А НЕ ПРАВИЛО ПРОМПТА
 * ─────────────────────────────────────────────────────────────────────────────
 * Правило «Варианты — РАЗНЫЕ» есть в system-промпте
 * (`prompts/worksheet-gen.ts`, раздел про `variants`). Оно снижает частоту
 * повторов, но не даёт гарантии — ровно тот же аргумент, по которому в проекте
 * уже написан `validation/quality-filter.ts`: правило промпта это просьба, а
 * гарантию даёт код ПОСЛЕ ответа модели.
 *
 * Жалоба, из-за которой всё это затевалось: контрольная по английскому, 11
 * класс, «задания повторяются, два варианта не сделано». Обе половины жалобы
 * были молчаливыми.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ СРАВНЕНИЕ ПО ПОЗИЦИЯМ, А НЕ ПО МНОЖЕСТВУ
 * ─────────────────────────────────────────────────────────────────────────────
 * Задание N первого варианта сравнивается с заданием N второго. Это ровно то,
 * что видит учитель, раздавая «первый» и «второй»: ученик с листом 2 должен
 * решать ту же по порядку и по содержанию задачу, что и ученик с листом 1.
 * Сравнение по множеству (сколько общих текстов вообще) дало бы «две похожие
 * формулировки на широкой теме — это нормально» и пропустило бы настоящий
 * кейс: вариант 2 — копия варианта 1 с переставленными заданиями.
 *
 * Порядок тем у вариантов должен совпадать (это уже есть в промпте, пункт 4
 * требований к двум вариантам), поэтому сравнение по позициям корректно.
 */

/** Задание в том виде, в каком лежит в листе. */
export interface VariantTaskLike {
  text?: unknown;
  number?: unknown;
}

/**
 * Нормализация текста задания перед сравнением.
 *
 * Что и зачем снимаем:
 *   · `trim` — края пробелов ничего не значат;
 *   · нижний регистр — «Растения» и «растения» это одно и то же задание;
 *   · сжатие пробелов — модель нестабильна в их количестве, и без этого
 *     половина одинаковых заданий выглядит разными только из-за переноса;
 *   · ведущий номер («1. », «2) », «3 — ») — номер одинаковый по позиции у
 *     обоих вариантов и к содержанию отношения не имеет;
 *   · завершающий «?» — «…в клетке?» и «…в клетке» это один текст.
 *
 * ЭТО НЕ «ПОЧИСТИТЬ ТЕКСТ ДЛЯ УЧИТЕЛЯ». Функция ничего не меняет в самих
 * заданиях и никуда, кроме сравнения, не отдаётся. Плохая нормализация здесь
 * дала бы ложное «варианты разные» — то есть пропуск настоящего дефекта.
 */
export function normalizeTaskText(value: unknown): string {
  if (typeof value !== "string") return "";
  return value
    .trim()
    .toLowerCase()
    // Сжатие пробелов ДО снятия номера: номер может быть отделён неразрывным
    // пробелом или идти после переноса строки.
    .replace(/\s+/g, " ")
    .trim()
    // Ведущий номер: «1. текст», «2) текст», «3 — текст», «4:текст».
    // Число с любой из этих пунктуаций и без неё («1 текст») — тоже номер.
    .replace(/^\d+\s*[.)—\-:]\s*/, "")
    .replace(/^\d+\s+/, "")
    .replace(/\s+/g, " ")
    .trim()
    // Завершающий знак вопроса. Только его: двоеточие в конце задания может
    // быть частью формулировки («выберите из списка:»).
    .replace(/\?+\s*$/, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Порог допустимых совпадений между вариантами (AD-2).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ⚠ ЭТО ГИПОТЕЗА, А НЕ ИЗМЕРЕННАЯ ВЕЛИЧИНА
 * ─────────────────────────────────────────────────────────────────────────────
 * Формула `max(1, floor(count / 5))` — это 20% совпадений. ОБОСНОВАНИЯ У НЕЁ
 * ЧИСТО КАЧЕСТВЕННОЕ, цифрами не подкреплено: строгая проверка «не совпало ни
 * одного задания» забраковала бы нормальные материалы — на широкой теме
 * («сказка про дракона») две похожие формулировки это стиль модели, а не брак.
 * Порог отсекает массовое копирование, а не единичное пересечение.
 *
 * ЧТО НУЖНО СДЕЛАТЬ, ЧТОБЫ ПРЕВРАТИТЬ ГИПОТЕЗУ В ЗНАНИЕ: прогнать 30 живых
 * контрольных разных предметов и посчитать распределение `duplicates`. Пока
 * этого прогона не было, число 20% — догадка, и её нужно пересматривать.
 * Сделать строже можно в одну строку здесь; сделать «правильным» без данных
 * нельзя.
 */
export function maxDuplicatesFor(count: number): number {
  if (count <= 0) return 0;
  return Math.max(1, Math.floor(count / 5));
}

/** Результат сверки двух вариантов. */
export interface VariantDiffResult {
  /** Разные ли варианты по мерке конвейера. */
  differ: boolean;
  /** Сколько заданий сравнили (размер более короткого списка). */
  compared: number;
  /** Позиции совпавших заданий (с 1, как их видит учитель). */
  duplicates: number[];
  /** Сколько заданий в каждом варианте. */
  countV1: number;
  countV2: number;
  /** Разошлись ли количества — это AD-8, лечится дозапросом. */
  countMismatch: boolean;
  /** Почему варианты признаны одинаковыми (для сообщения в ретрае и в API). */
  reason: string | null;
}

/**
 * Сравнить два варианта: задание N против задания N.
 *
 * Считаем варианты ОДИНАКОВЫМИ, когда:
 *   · совпало больше `maxDuplicatesFor(count)` заданий; либо
 *   · совпали ВСЕ задания — это плохо при любом `count` (отдельное правило
 *     AD-2: на трёх заданиях «иначе чем одно совпадение» не набирается, а
 *     три копии из трёх — это ровно тот дефект, который пришёл в жалобе).
 *
 * Разница в количестве заданий НЕ делает варианты одинаковыми: это AD-8,
 * недостающие задания добираются дозапросом (см. `countMismatch`).
 */
export function variantsDiffer(
  v1Tasks: readonly VariantTaskLike[] | null | undefined,
  v2Tasks: readonly VariantTaskLike[] | null | undefined,
): VariantDiffResult {
  const a = Array.isArray(v1Tasks) ? v1Tasks : [];
  const b = Array.isArray(v2Tasks) ? v2Tasks : [];

  const countV1 = a.length;
  const countV2 = b.length;
  const compared = Math.min(countV1, countV2);

  // Один из вариантов пуст — сравнивать нечего. Это НЕ «варианты одинаковые»:
  // разрыв «второй вариант не пришёл» разбирается отдельно (разрыв 3 ТЗ-25),
  // иначе мы бы сформулировали учителю «два варианта совпали» про лист из
  // одного варианта.
  if (compared === 0) {
    return {
      differ: false,
      compared: 0,
      duplicates: [],
      countV1,
      countV2,
      countMismatch: countV1 !== countV2,
      reason: null,
    };
  }

  const duplicates: number[] = [];
  for (let i = 0; i < compared; i += 1) {
    const left = normalizeTaskText(a[i]?.text);
    const right = normalizeTaskText(b[i]?.text);
    // Пустые тексты не считаем совпадением: два задания без текста не
    // «одинаковые», это две разные бессмыслицы, и ретрай тут не поможет.
    if (left.length > 0 && left === right) duplicates.push(i + 1);
  }

  const countMismatch = countV1 !== countV2;

  // Совпали ВСЕ — плохо при любом количестве.
  if (compared > 0 && duplicates.length === compared) {
    return {
      differ: true,
      compared,
      duplicates,
      countV1,
      countV2,
      countMismatch,
      reason: `совпали все ${compared} заданий (вариант 2 повторяет вариант 1)`,
    };
  }

  const maxDuplicates = maxDuplicatesFor(compared);
  if (duplicates.length > maxDuplicates) {
    return {
      differ: true,
      compared,
      duplicates,
      countV1,
      countV2,
      countMismatch,
      reason: `совпало ${duplicates.length} заданий из ${compared} при допустимых ${maxDuplicates}`,
    };
  }

  return {
    differ: false,
    compared,
    duplicates,
    countV1,
    countV2,
    countMismatch,
    reason: null,
  };
}

/** Сколько заданий не хватает до запрошенного учителем количества. */
export function missingTaskCount(requested: number, actual: number): number {
  if (!Number.isFinite(requested) || requested <= 0) return 0;
  return Math.max(0, Math.floor(requested) - Math.max(0, actual));
}