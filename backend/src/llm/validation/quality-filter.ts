/**
 * Слова, которыми задание просит «сделать как в образце».
 *
 * ВНИМАНИЕ, `\b` НЕ РАБОТАЕТ С КИРИЛЛИЦЕЙ: в JS `\b` — это граница между
 * «словесным» символом `[A-Za-z0-9_]` и остальным. Русские буквы в неё не
 * входят, поэтому `\bпо\s+образцу` в кириллическом тексте просто никогда не
 * срабатывает. Первая версия этого фильтра была написана именно так и молча
 * пропускала ВСЕ ссылки на образец — то есть не ловила ровно то, ради чего
 * написана. Границы слов здесь заданы явно через не-буквенные символы.
 */
const PATTERN_REF =
  /(^|[^a-zа-яёіїєґ])(по\s+образцу|по\s+аналогии|аналогично|таким\s+же\s+способом|таким\s+же\s+образом|такого\s+же\s+вида|такое\s+же\s+отношение|такое\s+же\s+правило|по\s+такой\s+же\s+схеме|см\.\s+задание|см\.\s+задачу|как\s+в\s+предыдущем|как\s+в\s+примере|как\s+выше|аналогичным\s+образом)/iu;

/** Разрешённые ссылки на то, что действительно есть на листе. */
const LEGIT_REF =
  /(^|[^a-zа-яёіїєґ])(в\s+таблице|таблица\s+выше|по\s+формуле|формул[аые]|на\s+полях|схема\s+(на\s+полях|выше|ниже|слева)|прилагаемая\s+схема|на\s+рисунке|рис\.\s*\d|в\s+условии\s+задания\s*\d)/iu;

/**
 * Ответы-заглушки: вместо ответа модель пишет, что ответа нет.
 *
 * Раньше это доходило до учителя как «Ответ: индивидуальный ответ» — то есть
 * лист нельзя было проверить, но он выглядел проверенным.
 *
 * Границы заданы явно по той же причине, что и выше: `\b` с кириллицей не
 * работает.
 */
const PLACEHOLDER_ANSWER =
  /^\s*(?:ответ\s*[:—-]?\s*)?((индивидуальный|свой|своё)\s+ответ|зависит\s+от\s+ученика|по\s+усмотрению(\s+ученика|\s+учителя)?|нет\s+однозначного\s+ответа|любой\s+ответ|ответ\s+ученика|на\s+усмотрение\s+учителя|своё\s+мнение|свое\s+мнение)\s*[.!]?\s*$/iu;

/**
 * Сильные маркеры чужой дисциплины: одного достаточно.
 *
 * Это формулировки, которые в задании по биологии или окружающему миру
 * появиться не могут — они называют чужую дисциплину или её термин целиком.
 */
const FOREIGN_MATH_STRONG =
  /(^|[^a-zа-яёіїєґ])(систем[аыу]\s+уравнени|квадратн(?:ое|ого|ым)\s+уравнени|неравенств[аоу]|теорем[аыу]\s+(Пифагора|косинусов|синусов)|дискриминант|логарифм[аыу]?|производн(?:ая|ой)\s+функци|интеграл|координат[аыой]\s+плоскост|векторн(?:ое|ого)\s+скалярн(?:ое|ого)|алгебраическ(?:ая|ое|ую)\s+дроб|задач(?:а|и|у)\s+по\s+алгебр|по\s+алгебр|по\s+геометр|принцип\s+математическ)/iu;

/**
 * Слабые маркеры: одного недостаточно, нужны два.
 *
 * «Площадь треугольника» может встретиться в географии, «уравнение» — в
 * физике-введении, «синус» — в геометрии угла здания. В одиночку такие слова
 * дефект не доказывают, и резать по ним нельзя: фильтр, который выкидывает
 * нормальные задания, хуже отсутствия фильтра.
 */
const FOREIGN_MATH =
  /(^|[^a-zа-яёіїєґ])(уравнени[еяю]|синус|косинус|тангенс|котангенс|площадь\s+(треугольник|прямоугольник|круга|трапеци|сектор)|объ[её]м\s+(шар|цилиндр|конус|призм))/iu;

/** Признаки того, что предмет естественно о цифрах — пропускаем проверку. */
const NUMERIC_CONTEXT =
  /(^|[^a-zа-яёіїєґ])(\d+\s*(%|см|м|кг|г|л|мин|ч|км|м\/с|руб)|температур|масс[аы]|скорост|длин[аы]|стоимост|цен[аы]|возраст|населен|уровень\s+гряз)/iu;

/**
 * Есть ли в задании разобранный пример, на который можно опереться.
 *
 * Важное различие, из-за которого фильтр писался сначала неверно:
 *   · «Образец: 3/4 = 0,75» — это САМ образец, задание понятно;
 *   · «сложите по образцу» — это ССЫЛКА на образец, которого может не быть;
 *   · «определите, как в примере» — тоже ссылка, и примера в задании нет.
 *
 * То есть слово «образец»/«пример» внутри текста бывает и признаком того, что
 * образец дан, и признаком того, что на него ссылаются. Разводим явно.
 */
function hasExampleInText(text: string): boolean {
  // Явное «Образец: …» / «Пример: …» — образец в задании есть.
  if (/(^|[^a-zа-яёіїєґ])(образец|пример|например|образуется|разоберём|разберём)\s*[:—–-]/iu.test(text)) {
    return true;
  }
  // Разобранный случай — это ЛЮБОЕ вычисление с результатом: «2 + 3 = 5»,
  // «3/4 = 0,75», «12 : 3 = 4».
  //
  // Первая версия искала только пару «число = число», и на этом ломалась
  // половина нормальных примеров: «2 + 3 = 5» под условие не попадал, хотя
  // это ровно тот разобранный случай, который образцом и является. Знак
  // операции в середине неважен — важен результат справа.
  const withSlash = text.replace(/(\d)\s*\/\s*(\d)/g, "$1 = $2");
  if (/\d\s*[-+*/×·:^]?\s*[=]\s*[-−–—+]?\s*[\d.]/u.test(withSlash)) {
    return true;
  }
  // Отсылка к тому, что разобрано выше в том же задании.
  if (/(^|[^a-zа-яёіїєґ])(из\s+этого\s+примера|на\s+основе\s+этого|как\s+в\s+примере\s+выше|таким\s+способом\s+получилось)/iu.test(text)) {
    return true;
  }
  return false;
}

/**
 * Ссылка на образец/предыдущий разбор, которого в задании нет.
 *
 * Возвращает true, когда ссылку надо чинить:
 *   · слово-маркер есть («по образцу», «аналогично», «как в предыдущем», …),
 *   · это не ссылка на то, что реально на листе (таблица, формула, рисунок),
 *   · и в самом задании нет разобранного примера.
 */
export function hasDanglingPatternRef(text: string): boolean {
  if (!PATTERN_REF.test(text)) return false;
  // Ссылка разрешена, если рядом есть таблица/формула/рисунок — она настоящая.
  if (LEGIT_REF.test(text)) return false;
  // «По образцу» внутри задания ок, только если образец на месте.
  return !hasExampleInText(text);
}

/** Ответ-заглушка вместо настоящего ответа. */
export function isPlaceholderAnswer(answer: unknown): boolean {
  if (typeof answer !== "string") return false;
  // Проверяем И С «Ответ: » в начале: модель часто пишет ответ прямо в эту
  // формулировку, и без префикса регулярка с якорем `^…$` такую строку пропускала.
  // Это буквальная строка из жалобы учительницы.
  return PLACEHOLDER_ANSWER.test(answer.trim());
}

/**
 * Есть ли у задания ответ, который годится в ключ (ТЗ-26, Ф-5).
 *
 * «Годится» = непустая строка и не заглушка. Числа, «да», «2 1/3», «б)» —
 * годится. `null`, `""`, пробелы и «индивидуальный ответ» — нет.
 */
export function hasUsableAnswer(answer: unknown): boolean {
  if (typeof answer !== "string") return false;
  if (!answer.trim()) return false;
  return !isPlaceholderAnswer(answer);
}

/**
 * ТЗ-33: непустой список строк.
 *
 * Отдельная проверка вместо `Array.isArray(x) && x.length > 0` — потому что
 * дальше по коду список надо ещё и ОБРЕЗАТЬ до лимита, а пустой после
 * обрезки список — это уже другой случай.
 */
function hasNonEmptyList(value: unknown): boolean {
  return Array.isArray(value) && value.some((v) => typeof v === "string" && v.trim().length > 0);
}

/**
 * ТЗ-33: прислала ли модель образец отдельным полем `sample`.
 *
 * Образец типа `pattern` лежит в своём поле, а не в тексте задания: так его
 * удобно печатать рамкой ДО формулировки. Проверка «есть ли образец» в тексте
 * (`hasExampleInText`) такой образец не видит — поэтому здесь своя проверка.
 */
function hasSampleField(task: RawTask): boolean {
  return typeof task.sample === "string" && task.sample.trim().length > 0;
}

/**
 * ТЗ-34: ждёт ли этот тип критериев вместо эталона.
 *
 * Берётся из реестра (`answerKind === "criteria"`), а не из списка типов в
 * коде: правило живёт рядом с описанием типа, поэтому новый тип с критериями
 * обслуживается автоматически.
 */
export function taskExpectsCriteria(task: RawTask): boolean {
  const rawType = typeof task.type === "string" ? task.type.trim() : "";
  if (!rawType) return false;
  return getTaskTypeSpec(rawType)?.answerKind === "criteria";
}

/**
 * ТЗ-34: есть ли у задания КОНКРЕТНЫЕ критерии приёмки.
 *
 * Для типа с `answerKind: "criteria"` критерий приёмки и ЕСТЬ ключ: эталонного
 * текста там не существует в принципе, и выкидывать такое задание — значит
 * заменить развёрнутый вопрос обычным расчётом (так и было: учитель получал
 * контрольную, где не было ни одного развёрнутого задания).
 */
export function hasConcreteCriteria(task: RawTask): boolean {
  if (!Array.isArray(task.criteria)) return false;
  return task.criteria.some(
    (c) => typeof c === "string" && isConcreteCriterion(c),
  );
}

/**
 * ТЗ-34: почистить список критериев задания.
 *
 * Убираются пустые строки и общие формулировки («ответ неполный», «бывают
 * ошибки»): в ключе они занимают строку и ничего не говорят учителю. Возвращается
 * новый список и признак «что-то вычистили».
 */
function cleanCriteria(task: RawTask): { criteria: string[]; changed: boolean } {
  if (!Array.isArray(task.criteria)) return { criteria: [], changed: false };
  const original = task.criteria;
  const kept = original.filter(
    (c): c is string => typeof c === "string" && isConcreteCriterion(c),
  );
  return { criteria: kept, changed: kept.length !== original.length };
}

/**
 * ТЗ-33: подходит ли задание своему типу из реестра.
 *
 * Проверка по ТРЕБОВАНИЯМ ТИПА, а не по захардкоженному списку: требования
 * лежат в реестре (`src/lib/content/task-types.ts`) рядом с описанием типа,
 * поэтому новая форма задания проверяется автоматически, а не «ещё одним
 * правилом в коде».
 *
 * ТРИ СЛУЧАЯ, И ИХ НЕЛЬЗЯ СМЕШИВАТЬ:
 *
 *   1. ТИПА НЕТ — задание годное. Модель не всегда присылает `type`, и
 *      фильтр не про форму заданий, а про его качество. Раньше такие задания
 *      проходили, и ломать это нельзя: проверка должна ловить ДЕФЕКТ, а не
 *      отсутствие необязательного поля.
 *   2. ТИП НЕИЗВЕСТЕН (модель выдумала свой, например «diagram») — дефект.
 *      Такой тип не напечатать и не сохранить: zod на клиентском сохранении
 *      отвергнет его с 400, и учитель вместо листа получит ошибку.
 *   3. ТИП ИЗ РЕЕСТРА, НО НЕ СООТВЕТСТВУЕТ ТРЕБОВАНИЯМ — дефект.
 *
 * Что требует каждый тип:
 *   · `pattern`         — `sample`: разобранный образец В ТЕКСТЕ задания.
 *                         Без него задание «выполните по образцу» бессмысленно
 *                         (жалоба №5, 08.10.2026).
 *   · `table-task`      — `table`: без таблицы задание не решаемо.
 *   · `sequence`,       — `items`: без элементов нечего упорядочивать,
 *     `classification`,   распределять или сопоставлять.
 *     `matching`, `compare`
 *   · `multiple-choice`, — `options`: без вариантов выбор не из чего делать.
 *     `multi-answer`
 *
 * Возвращает `null`, если задание годное, и строку с причиной — если нет.
 * Причина возвращается текстом, а не флагом, потому что она попадает в лог
 * генерации: по логу должно быть видно, ЧТО именно не так с заданием.
 */
export function checkTaskTypeRequirements(task: RawTask): string | null {
  const rawType = typeof task.type === "string" ? task.type.trim() : "";

  // Случай 1: типа нет — проверять нечего, задание не трогаем.
  if (!rawType) return null;

  const spec = getTaskTypeSpec(rawType);
  // Случай 2: тип есть, но в реестре его нет.
  if (!spec) return `unknown-type:${rawType}`;

  if (spec.needsSample && !hasNonEmptyList(task.sample ? [task.sample] : [])) {
    return "pattern-without-sample";
  }
  if (spec.needsTable) {
    const table = task.table as { headers?: unknown; rows?: unknown } | undefined | null;
    const headers = Array.isArray(table?.headers) ? table.headers : [];
    const rows = Array.isArray(table?.rows) ? table.rows : [];
    if (headers.length === 0 || rows.length === 0) return "table-task-without-table";
  }
  if (spec.needsOptions && !hasNonEmptyList(task.options)) {
    return `${rawType}-without-options`;
  }
  // Типы, которым нужны элементы для работы. `items` — это НЕ то же самое,
  // что `options`: варианты ответа выбирают, элементы — упорядочивают.
  if (
    (rawType === "sequence" ||
      rawType === "classification" ||
      rawType === "matching" ||
      rawType === "compare") &&
    !hasNonEmptyList(task.items)
  ) {
    return `${rawType}-without-items`;
  }
  return null;
}

/**
 * Чужая математика в задании по предмету, который ею не занимается.
 *
 * Пороги: 2+ маркера в тексте задания. Один маркер — ложное срабатывание
 * («треугольник» в географии, «площадь» в технологии как площадь материала).
 */
/**
 * Сколько РАЗ встретился маркер в тексте.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ НЕ `text.match(FOREIGN_MATH).length`
 * ─────────────────────────────────────────────────────────────────────────────
 * Первая версия считала так. Это была тихая поломка: `String.match` без флага
 * `g` возвращает массив из САМОГО СОВПАДЕНИЯ и ЕГО ГРУПП ЗАХВАТА, а не из
 * вхождений. Наш regex содержит одну группу захвата, поэтому длина массива
 * была 3 при ОДНОМ маркере и столько же при двух.
 *
 * Из этого следовало ровно обратное тому, чего мы хотели: условие
 * `matches.length < 2` никогда не выполнялось, и ЛЮБОЕ задание с ОДНИМ
 * математическим маркером по нем��тематическому предмету выбрасывалось.
 * То есть фильтр не «ловил два признака», а резал всё подряд — «площадь
 * треугольника в горах» в географии ушло бы в мусор.
 *
 * Считаем сами, через цикл `exec` с глобальным флагом. Regex создаётся
 * ЗДЕСЬ, заново на каждый вызов: у глобального regex состояние `lastIndex`
 * живёт в самом объекте, и общий экземпляр между вызовами «сбился бы».
 */
function countMatches(text: string, source: RegExp): number {
  const re = new RegExp(source.source, source.flags.replace("g", "") + "g");
  let count = 0;
  // `exec` на глобальном regex проходит строку целиком; защищаемся от
  // бесконечного цикла на нулевой длине совпадения.
  let guard = 0;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) {
    count += 1;
    if (m[0].length === 0) re.lastIndex += 1;
    if (++guard > 200) break;
  }
  return count;
}

/**
 * Чужая математика в задании по предмету, который ею не занимается.
 *
 * Порог — 2 независимых маркера. Один маркер — ложное срабатывание:
 * «треугольник» в географии, «площадь» в технологии как площадь материала.
 */
export function looksLikeForeignMath(text: string, subject: string): boolean {
  if (MATH_SUBJECTS.has(subject)) return false;
  // Один сильный маркер («решите задачу по алгебре») решает всё.
  if (countMatches(text, FOREIGN_MATH_STRONG) >= 1) return true;
  // Слабые маркеры («площадь», «уравнение») требуют подтверждения.
  if (countMatches(text, FOREIGN_MATH) < 2) return false;
  // Если вокруг маркеров задание про измерения/количество — это нормальный
  // количественный вопрос по предмету («сколько деревьев растёт»), а не
  // чужая дисциплина.
  if (NUMERIC_CONTEXT.test(text)) return false;
  return true;
}

/**
 * Основная точка входа: почистить массив заданий.
 *
 * Мутирует элементы на месте там, где это уместно, и возвращает новый массив
 * без заданий, которые починить нельзя. Порядок заданий сохраняется — после
 * удаления номера не перенумеровываются (учитель сверяет по номерам со своим
 * планом урока, и «задание 7» из его распечатки должно остаться седьмым).
 */
/** Опции фильтра. */
export interface FilterTasksOptions {
  /**
   * Ответы обязательны (учитель нажал «С ответами»).
   *
   * ТЗ-26, Ф-5. Пока ответы НЕ обязательны, `answer: null` — законное
   * значение: так просил учитель. Пока обязательны, задание без ответа —
   * дефект схемы, и оно выкидывается, чтобы дозапрос поставил на его место
   * нормальное. Раньше ответ просто обнулялся, и такое задание доходило до
   * DOCX вообще без строки ответа — учитель сверял работу и не находил ключа.
   *
   * По умолчанию `false`: без явного требования поведение прежнее.
   */
  requireAnswer?: boolean;
}

export function filterTasks(
  tasks: RawTask[],
  subject: string,
  options: FilterTasksOptions = {},
): {
  tasks: RawTask[];
  report: QualityFilterReport;
} {
  const requireAnswer = options.requireAnswer === true;
  const report: QualityFilterReport = {
    droppedPatternRef: [],
    cleanedAnswer: [],
    droppedForeignMath: [],
    droppedNoAnswer: [],
    droppedTypeMismatch: [],
    droppedUnknownType: [],
    cleanedCriteria: [],
    cleanedCriteriaAnswer: [],
    before: tasks.length,
    after: tasks.length,
    // Откат ставят ниже, в ветке отката. Инициализация — «отката не было».
    rolledBack: false,
  };

  const kept: RawTask[] = [];

  tasks.forEach((task, index) => {
    if (!task || typeof task !== "object") return;

    const text = typeof task.text === "string" ? task.text : "";

    // 0. ТЗ-33: тип из реестра и соответствие типа его требованиям.
    //    Идёт ПЕРВЫМ, потому что остальные проверки бессмысленны для задания
    //    неизвестного типа: нечем ни печатать, ни проверять.
    const typeProblem = checkTaskTypeRequirements(task);
    if (typeProblem !== null) {
      if (typeProblem.startsWith("unknown-type:")) {
        report.droppedUnknownType.push(index + 1);
      } else {
        report.droppedTypeMismatch.push(index + 1);
      }
      return;
    }

    // 1. Ссылка на образец, которого нет. Чинить нечем — задание неоднозначно
    //    для ученика, поэтому выкидываем.
    //
    //    ТЗ-33: образец может лежать в отдельном поле `sample` — тогда ссылка
    //    «выполните по образцу» НЕ висячая: образец есть, просто не в тексте,
    //    а в своём поле (так его и печатают — рамкой ДО текста задания).
    //    Без этой поправки фильтр выкидывал бы правильные задания типа
    //    `pattern`: образец прислали, а проверка его не видела.
    if (!hasSampleField(task) && hasDanglingPatternRef(text)) {
      report.droppedPatternRef.push(index + 1);
      return;
    }

    // 2. Чужой предмет: несколько формул в задании по нематематике.
    if (looksLikeForeignMath(text, subject)) {
      report.droppedForeignMath.push(index + 1);
      return;
    }

    // 3. Ответ-заглушка. Задание оставляем (оно может быть нормальным), но
    //    ответ обнуляем: лучше «ответ не заполнен» с пояснением, чем
    //    «Ответ: индивидуальный ответ» в ключе, который учитель сверяет.
    if (isPlaceholderAnswer(task.answer)) {
      task.answer = null;
      report.cleanedAnswer.push(index + 1);
    }

    // 3-бис. ТЗ-34: КРИТЕРИИ ЧИСТЯТСЯ, А У ТИПА С КРИТЕРИЯМИ ОБНУЛЯЕТСЯ ОТВЕТ.
    //
    //    Критерии приёмки лежат в поле `criteria` (AD-4: один носитель, а не
    //    два). Пустые строки и общие формулировки («ответ неполный») убираются:
    //    в ключе они занимают строку и ничего не говорят учителю.
    //
    //    Ответ у типа с `answerKind: "criteria"` обнуляется, если модель
    //    положила туда критерии (старое правило 17) или любой текст со
    //    словом «критери». Такой текст выглядит как эталонный ответ, которым
    //    учитель будет сверять работу, а эталонного ответа у такого типа не
    //    существует в принципе.
    const expectsCriteria = taskExpectsCriteria(task);
    const cleaned = cleanCriteria(task);
    if (cleaned.changed) {
      report.cleanedCriteria.push(index + 1);
      task.criteria = cleaned.criteria.length > 0 ? cleaned.criteria : null;
    }
    if (
      expectsCriteria &&
      typeof task.answer === "string" &&
      /критер/i.test(task.answer)
    ) {
      task.answer = null;
      report.cleanedCriteriaAnswer.push(index + 1);
    }

    // 3a. ТЗ-26, Ф-5: ответов не оказалось — задание без ответа. Если учитель
    //     просил ответы, такое задание в выгрузку не идёт: в DOCX у него нет
    //     строки ответа, и учитель не может сверить работу. Выкидываем, чтобы
    //     дозапрос занял его место нормальным заданием.
    //
    //     При `withAnswers = false` НЕ выкидываем: там null — то, что просил
    //     учитель, и выкидывание съело бы весь лист.
    //
    //     ТЗ-34, AD-5: ИСКЛЮЧЕНИЕ ДЛЯ ТИПА С КРИТЕРИЯМИ. У эссе, открытого
    //     ответа, практической работы и работы с источником эталонного текста
    //     не существует — критерий приёмки и ЕСТЬ ключ. Раньше такое задание
    //     выкидывалось, и на его место дозапрос ставил обычный расчёт: учитель
    //     получал контрольную, в которой не было ни одного развёрнутого
    //     задания. Правило выводится из `answerKind` в реестре, а не из
    //     списка типов в коде.
    if (requireAnswer && !hasUsableAnswer(task.answer) && !hasConcreteCriteria(task)) {
      report.droppedNoAnswer.push(index + 1);
      return;
    }

    kept.push(task);
  });

  report.after = kept.length;

  // ─────────────────────────────────────────────────────────────────────────────
  // ЗАЩИТА ОТ ПУСТОГО ЛИСТА (добавлено после проверки 08.10.2026)
  // ─────────────────────────────────────────────────────────────────────────────
  // Фильтр умеет выкинуть задание, но не может его починить. Если модель
  // отдала пачку «выполните по образцу» (у учительницы их было 26 штук из 26),
  // на выходе остаётся НОЛЬ — и учитель получает пустой лист, причём попытка уже
  // списана. Это хуже, чем показать то, что пришло.
  //
  // Поэтому: если отфильтровали ВСЁ, возвращаем исходный набор как есть.
  // Учитель увидит «по образцу» без образца и сможет попросить переделать —
  // это ощутимая проблема. Молчаливый пустой лист — не ощутимая, а просто
  // невидимая: учитель потратил попытку и не понял, куда делся материал.
  //
  // Если осталось МЕНЬШЕ трети — тоже возвращаем исходные: значит, сработало
  // слишком агрессивно (см. историю с порогом маркеров), и доверять такому
  // результату нельзя.
  //
  // ─────────────────────────────────────────────────────────────────────────────
  // ТЗ-33: ОТКАТ ВОЗВРАЩАЕТ ТОЛЬКО МЯГКИЕ ПОТЕРИ.
  //
  // Откат существует, чтобы учитель получил хоть какой-то материал. Но есть
  // два вида потерь, и откатывать их нельзя:
  //
  //   · НЕИЗВЕСТНЫЙ ТИП — задание нельзя ни напечатать, ни сохранить (zod
  //     отвергнет с 400). Вернуть его в откате значит подсунуть учителю
  //     материал, который сломается на следующем шаге.
  //   · НЕСООТВЕТСТВИЕ ТИПУ — «по образцу» без образца, «задание по таблице»
  //     без таблицы. Такое задание бессмысленно ПО СМЫСЛУ: учитель отдаст
  //     классу «выполните по образцу», которого нет. Откат здесь означал бы,
  //     что вся работа ТЗ-33 (сделать форму, а не выкидывать её) обнуляется
  //     ровно в том случае, когда модель ошиблась чаще обычного.
  //
  // Мягкие потери (ссылка на образец в тексте, чужая математика, нет ответа)
  // откатываются, как и раньше: там задание можно починить или показать.
  // ─────────────────────────────────────────────────────────────────────────────
  if (kept.length === 0 || kept.length < tasks.length / 3) {
    // ТЗ-34, AD-4: откат — это событие, и оно отмечается ЗДЕСЬ, а не
    // вычисляется по косвенным признакам на стороне конвейера.
    //
    // Раньше следов не оставалось: конвейер выводил откат из
    // `before - after == 0`, а этим же равенством описывается «фильтр ничего
    // не отбросил». Два разных события выглядели одинаково, и признак
    // `filterBackedOff` в ответе API врал именно поэтому.
    report.rolledBack = true;
    const recoverable = tasks.filter((task) => {
      const problem = checkTaskTypeRequirements(task);
      return problem === null;
    });
    // Если после жёсткой отсечки не осталось ничего — вернуть всё равно
    // нечего. Но тогда возвращаем ПУСТОЙ набор, а не исходный: исходный
    // состоит ровно из тех заданий, которые мы только что признали
    // непригодными. Пустой лист учитель поймёт (признак в ответе API),
    // а бессмысленное задание он унесёт в класс и не поймёт, почему оно
    // там было.
    return { tasks: recoverable, report };
  }
  return { tasks: kept, report };
}