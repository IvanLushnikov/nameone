/**
 * Детектор повторяющегося навыка ВНУТРИ одного листа (ТЗ-26, Ф-2, 13.10.2026).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ЕЩЁ ОДИН ДЕТЕКТОР, РАЗ УЖЕ ЕСТЬ `variant-check.ts`
 * ─────────────────────────────────────────────────────────────────────────────
 * `variant-check.ts` смотрит на ДВА ВАРИАНТА КОНТРОЛЬНОЙ: задание N первого
 * против задания N второго. Это межвариантный контроль — он ловит «оба
 * варианта совпали».
 *
 * Дыра была в другом месте: ВНУТРИ одного листа. Аудит 13.10 нашёл три
 * воспроизведённых случая:
 *   · русский 8, задания 6 и 9 — бессоюзное предложение, вторая часть
 *     поясняет первую, и одна и та же рамка «Я выглянул в окно / в сад»;
 *   · английский 11, вариант 1, задания 2 и 10 — конструкция
 *     `haven't + V3 + yet`;
 *   · карточки, задания 2 и 3 — деление объектов на «живая / неживая
 *     природа».
 *
 * Для учителя это 12 заданий, которые фактически дают 11.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ИМЕННО СРАВНИВАЕМ: «НАВЫК + КЛЮЧЕВОЙ ОБЪЕКТ»
 * ─────────────────────────────────────────────────────────────────────────────
 * НЕ буквальное совпадение текста. Литеральное сравнение поймало бы пару
 * заданий, где совпали слова-разделители, и пропустило бы настоящий дубль,
 * отличающийся одним словом.
 *
 * НЕ сравниваем и слова-разделители вроде «Вычислите», «Найдите», «Решите».
 * Это проверено на реальных данных: у математики `Jaccard 1.00` между
 * «Вычислите 3/4 + 1/4» и «Вычислите 5/8 + 3/8» — артефакт общего слова
 * «Вычислите». Считать такие задания дублями нельзя: это ложное срабатывание,
 * а ложный дефект хуже пропущенного (правило аудита, §12).
 *
 * Сигнатура задания = текст без разделителей, без чисел и без пунктуации,
 * приведённый к нижнему регистру. Это и есть «навык + ключевой объект»:
 * числа уходят, потому что по условию ТЗ-26 два задания на одном навыке
 * допустимы, если числа и формулировки РАЗНЫЕ.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ГРАНИЦА ТОЧНОСТИ — ЧЕСТНО О ПРОПУСКАХ
 * ─────────────────────────────────────────────────────────────────────────────
 * Детектор ловит дубль, когда совпадает весь остаток задания. Он НЕ ловит
 * повтор одной конструкции при разных объектах — как английский
 * `haven't + V3 + yet` в заданиях 2 и 10, если в них разные глаголы и
 * дополнения. Ловить такое общим правилом нельзя: «два задания на времена
 * Present Perfect» в листе по английскому 11 это нормальная методика, и
 * автопометка на них даст ложные срабатывания на живых листах.
 *
 * Вывод: этот модуль — фильтр БЕЗОПАСНОСТИ (гарантированно не врёт на
 * отличиях) плюс точный детектор полных дублей. Повтор конструкции при разных
 * объектах ловится правилом 15 в промпте (разнообразие навыков), а не кодом.
 */

/** Задание в том виде, в каком лежит в листе. */
export interface SkillTaskLike {
  text?: unknown;
  number?: unknown;
}

/**
 * Слова-разделители: они есть в начале почти каждого задания и НЕ являются
 * ни навыком, ни объектом. Список открытый по составу, но не по принципу:
 * добавляем сюда слово только тогда, когда оно встречается в десятках
 * разных заданий и само по себе ничего не различает.
 *
 * Учтено и слово «вычисли» — модель пишет и «Вычислите», и «Вычисли».
 */
const SEPARATOR_WORDS = new Set([
  "вычислите", "вычисли", "найдите", "найди", "решите", "реши",
  "определите", "определи", "запишите", "запиши", "выпишите", "выпиши",
  "составьте", "составь", "постройте", "построй", "изобразите", "изобрази",
  "представьте", "представь", "раскройте", "раскрой", "упростите", "упрости",
  "сократите", "сократи", "приведите", "приведи", "распределите", "распредели",
  "округлите", "округли", "оцените", "оцени", "сравните", "сравни",
  "выберите", "выбери", "прочитайте", "прочитай", "подчеркните", "подчеркни",
  "объясните", "объясни", "докажите", "докажи", "вставьте", "вставь",
  "укажите", "укажи", "подпишите", "подпиши", "замените", "замени",
  "назовите", "назови", "перечислите", "перечисли", "выберите верный",
  "верно", "неверно", "ответ", "задание", "задача", "условие", "текст",
]);

/**
 * Глаголы описания — отдельным списком, а не в общем.
 *
 * «Опишите строение клетки растения» и «Опишите строение клетки животного» —
 * это РАЗНЫЕ задания по ТЗ-26: формулировки различаются, объект разный,
 * повторяется только рамка «описать строение клетки». Если бы «опишите»
 * осталось в сигнатуре, цепочка «описать строение клетки» совпала бы, и
 * нормальная пара заданий была бы объявлена дублем.
 *
 * Проверено на биологии 7: три задания «опишите строение клетки» подряд —
 * это однообразие (В-1), но не ДУБЛЬ, и ловить его должна другая мера.
 */
const DESCRIBE_VERBS = new Set([
  "опишите", "опиши", "описать", "описал", "описала", "описали",
  "охарактеризуйте", "охарактеризуй", "характеризуйте", "характеризуй",
  "расскажите", "расскажи", "объясните", "объясни", "объяснить",
]);

/**
 * Слова, которые почти не встречаются как «объект», но встречаются как
 * служебная обвязка формулировки. Без их снятия задание «Сравните дроби» и
 * «Сравните числа» дали бы общий остаток «сравните» — и мы объявили бы их
 * дублями, хотя проверяют они разное.
 */
const LOW_INFO_WORDS = new Set(["дроби", "дробь", "числа", "число", "значения", "примеры"]);

/**
 * Нормализация текста перед извлечением сигнатуры.
 *
 * Порядок обязателен: сначала пробелы, потом ведущий номер, потом уже всё
 * остальное. Иначе номер не снимется (см. замечание в `normalizeTaskText`
 * из `variant-check.ts` — та же ловушка описана там для вариантов).
 */
function normalizeForSignature(value: unknown): string {
  if (typeof value !== "string") return "";
  return value
    .trim()
    .toLowerCase()
    .replace(/\s+/g, " ")
    .replace(/^\d+\s*[.)—\-:]\s*/, "")
    .replace(/^\d+\s+/, "")
    .trim();
}

/**
 * Минимальная длина совпавшей цепочки СОДЕРЖАТЕЛЬНЫХ слов, при которой два
 * задания считаются повтором одного навыка.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ИМЕННО СЛОВА, А НЕ ВЕСЬ ОСТАТОК ЗАДАНИЯ
 * ─────────────────────────────────────────────────────────────────────────────
 * Первая версия детектора сравнивала остаток ЦЕЛИКОМ и на фикстурах аудита
 * показала свою границу сразу: у карточек «Разделите объекты на живую и неживую
 * природу: корова, камень…» и «Живая и неживая природа: распределите солнце,
 * вода…» остатки РАЗНЫЕ — отличаются списком объектов, а повторяется сама
 * рамка «живая / неживая природа». То есть повторяется НАВЫК, а данные к нему
 * меняются. Именно это и есть дефект из отчёта: учитель получает 12 заданий,
 * которые дают 11.
 *
 * Поэтому сравнивается не весь текст, а ЦЕПОЧКА из трёх содержательных слов:
 * «навык + ключевой объект» в ней и живут, а числа и примеры — нет.
 *
 * ПОЧЕМУ ТРИ, А НЕ ОДИН И НЕ ПЯТЬ
 *   · одно слово — ложное срабатывание гарантировано: «предложение» есть в
 *     половине заданий по русскому языку;
 *   · пять — пропуск настоящего дефекта: «живая неживая природа» это ровно три
 *     слова, и рамка из трёх слов не попала бы в пятёрку.
 */
export const MIN_SHARED_PHRASE = 3;

/**
 * Огрубление окончания — не морфология, а «хвост» слова.
 *
 * Нужен ровно для одной вещи: «живую / живая», «природу / природа» должны
 * считаться одним и тем же словом. Полноценный стеммер здесь был бы лишним —
 * и рискованным: чем он умнее, тем выше шанс склеить разные слова и выдать
 * нормальный лист за дефектный.
 */
function stem(token: string): string {
  // Сначала режем самые длинные окончания: иначе «живую» успеет превратиться
  // в «жив» + «ю», и совпадения не будет.
  const endings = [
    "иями", "ями", "ами", "ого", "его", "ому", "ему", "ыми", "ими",
    "ую", "юю", "ой", "ей", "ый", "ая", "яя", "ое", "ее", "ые", "ие",
    "ом", "ем", "ам", "ям", "ах", "ях", "ов", "ев", "ью", "ия",
    "а", "я", "о", "е", "ы", "и", "у", "ю", "ь",
  ];
  for (const ending of endings) {
    if (token.length > ending.length + 2 && token.endsWith(ending)) {
      return token.slice(0, -ending.length);
    }
  }
  return token;
}

/**
 * Сигнатура задания — «навык + ключевой объект» без чисел и разделителей.
 *
 * Возвращает МАССИВ ОГРУБЛЁННЫХ СЛОВ, а не строку: сравнение идёт по цепочкам
 * длиной `MIN_SHARED_PHRASE`, и строка для этого неудобна.
 *
 * Пустой массив означает, что после снятия разделителей и чисел ничего не
 * осталось. Такое задание (например, «Вычислите 3/4 + 1/4») отличается от
 * другого только числами — а это РАЗРЕШЁННАЯ ситуация по ТЗ-26. Поэтому
 * короче `MIN_SHARED_PHRASE` слов сигнатурой дубля не считается.
 */
export function taskSignature(value: unknown): string[] {
  const normalized = normalizeForSignature(value);
  if (!normalized) return [];

  return normalized
    // Знаки препинания склеивают слова: «3/4+1/4» → одно слово. Режем их
    // ДО разбиения на слова, иначе получим мусорные остатки.
    .replace(/[^\p{L}\p{N}\s/\\^_+*-]/gu, " ")
    .split(/\s+/)
    .filter(Boolean)
    // Дробь вроде «3/4» или «x^2» — это ЧИСЛО, оно допустимо отличаться.
    // Такие токены снимаем целиком.
    .filter((token) => !/^[\d/,.]+$/.test(token) && !/^[\d/]+$/.test(token))
    // Степень/индекс: «x^2», «a_1» — числовая часть, снимаем её, оставляя букву.
    .map((token) => token.replace(/[\^_][\d]+$/, ""))
    .filter(Boolean)
    .filter((token) => !SEPARATOR_WORDS.has(token))
    .filter((token) => !DESCRIBE_VERBS.has(token))
    .filter((token) => !LOW_INFO_WORDS.has(token))
    // Слова короче трёх букв ничего не различают («да», «не», «в»).
    .filter((token) => token.length >= 3)
    .map(stem);
}

/**
 * Содержимое пары, если она дубль: общая цепочка слов.
 *
 * Это попадает и в лог, и в сообщение о замене — по нему видно, ЧТО именно
 * повторилось, а не просто «задания 6 и 9 похожи».
 */
function sharedPhrase(a: string[], b: string[]): string | null {
  const grams = new Map<string, string>();
  for (let i = 0; i + MIN_SHARED_PHRASE <= a.length; i += 1) {
    grams.set(a.slice(i, i + MIN_SHARED_PHRASE).join(" "), a.slice(i, i + MIN_SHARED_PHRASE).join(" "));
  }
  for (let i = 0; i + MIN_SHARED_PHRASE <= b.length; i += 1) {
    const gram = b.slice(i, i + MIN_SHARED_PHRASE).join(" ");
    if (grams.has(gram)) return gram;
  }
  return null;
}

/** Найденная пара-дубль внутри одного листа. */
export interface SkillDupePair {
  /** Номер первого задания (как его видит учитель, с 1). */
  first: number;
  /** Номер второго задания. */
  second: number;
  /** Общая сигнатура — по ней видно, что именно повторилось. */
  signature: string;
}

/** Результат проверки листа на повторяющийся навык. */
export interface SkillDupeResult {
  /** Есть ли в листе повторяющиеся задания. */
  hasDupes: boolean;
  /** Все найденные пары, по возрастанию номера первого задания. */
  pairs: SkillDupePair[];
  /** Сколько заданий сравнили. */
  compared: number;
}

/**
 * Найти повторяющиеся задания ВНУТРИ одного листа.
 *
 * Чистая функция: на вход массив заданий, на выходе — список пар. Никаких
 * запросов к сети, никаких побочных эффектов, порядок входа не меняется.
 *
 * Сравниваются ВСЕ пары, а не соседние: в примере из аудита дубли стояли в
 * заданиях 2 и 3 (карточки), 6 и 9 (русский 8) — не подряд.
 */
export function findSkillDupes(
  tasks: readonly SkillTaskLike[] | null | undefined,
): SkillDupeResult {
  const list = Array.isArray(tasks) ? tasks : [];
  const pairs: SkillDupePair[] = [];

  const signatures = list.map((task) => taskSignature(task?.text));

  // Сравниваются ВСЕ пары, а не соседние: в примерах из аудита дубли стояли
  // в заданиях 2 и 3 (карточки), 6 и 9 (русский 8) — не подряд.
  for (let i = 0; i < signatures.length; i += 1) {
    for (let j = i + 1; j < signatures.length; j += 1) {
      // Короткая сигнатура — задание, различающееся с соседом только
      // числами. По ТЗ-26 это разрешено, дублем не считаем.
      const a = signatures[i];
      const b = signatures[j];
      if (!a || a.length < MIN_SHARED_PHRASE) continue;
      if (!b || b.length < MIN_SHARED_PHRASE) continue;

      const phrase = sharedPhrase(a, b);
      if (phrase) {
        pairs.push({ first: i + 1, second: j + 1, signature: phrase });
      }
    }
  }

  pairs.sort((a, b) => a.first - b.first || a.second - b.second);

  return {
    hasDupes: pairs.length > 0,
    pairs,
    compared: list.length,
  };
}

/**
 * Номера заданий, которые надо заменить: в каждой паре — второе задание.
 *
 * Именно второе, а не первое: первое задание уже стоит в листе, учитель его
 * видит, и замена ломала бы нумерацию сильнее, чем польза от снятия дубля.
 * Возвращается список без повторов и по возрастанию.
 */
export function tasksToReplace(result: SkillDupeResult): number[] {
  const numbers = new Set(result.pairs.map((pair) => pair.second));
  return [...numbers].sort((a, b) => a - b);
}