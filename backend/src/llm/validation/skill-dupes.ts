/**
 * Стоп-словарь, понимающий и исходную форму, и огрублённую.
 *
 * Кэш строится один раз на каждое множество. Без этого русские словари
 * разваливаются целиком: «форма» огрубляется до «форм», «завершите» — до
 * «завершит», и исходное слово больше не совпадает. Русские окончания длиннее
 * английских, поэтому страдал именно русский список — а ложные срабатывания
 * приходили именно из него.
 */
function stopSet(words: Set<string>): Set<string> {
  const out = new Set<string>(words);
  for (const w of words) out.add(stem(w));
  return out;
}

