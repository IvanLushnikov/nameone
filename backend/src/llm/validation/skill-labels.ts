/**
 * Метки тем у заданий листа (ТЗ-27, ПРОБЕЛ 2).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ЭТОТ ФАЙЛ, А НЕ ПРОМПТ
 * ─────────────────────────────────────────────────────────────────────────────
 * Метка нужна КАЖДОМУ заданию, иначе разбор «тем, где просели» молчит: строки
 * пишутся только по заданиям с меткой (`db/skill-attempts.ts`, `readTaskSkills`).
 * Попросить модель «верни поле skill» — можно, но это просьба, а не гарантия:
 * модель его то присылает, то нет, а фича от этого целиком зависит. Причины у
 * модели две: в системном промпте формат ответа зафиксирован (его менять нельзя
 * — сброс prompt cache у тарифа «Плюс» стоит денег, см. шапку
 * `prompts/worksheet-gen.ts`), а лист без плана вообще не о чем раскладывать —
 * все задания по одной теме.
 *
 * Поэтому метку проставляет СЕРВЕР, из источников, которые уже есть:
 *   1. метка от модели (если пришла) — она узкая и честная;
 *   2. навык из ПЛАНА листа по позиции — план уже раскладывает тему на разные
 *      навыки, и это ровно то, что учитель потом увидит в разборе;
 *   3. тема запроса — последний рубеж: лист по одной теме, значит и метка у
 *      всех его заданий одна. Разрез получится «одна тема, 100%», и это правда,
 *      а не поломка.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧЕГО ФУНКЦИЯ НЕ ДЕЛАЕТ
 * ─────────────────────────────────────────────────────────────────────────────
 * Не придумывает метку там, где учитель её уже стёр: пустая строка — это
 * «метки нет», и подставлять вместо неё тему молча нельзя, иначе учитель не
 * смог бы убрать метку с задания. Отличает это только отдельный флаг
 * `respectBlank` — его ставит правка листа (`routes/f08.ts`), где пустое поле
 * означает «убери метку».
 */

import type { WorksheetTask } from "../../types";

/** Одна позиция плана листа — ровно те поля, которые нужны метке. */
export interface PlanSkillItem {
  навык?: string;
  подтема?: string;
}

/** Длина метки. 120 — тот же предел, что и в `routes/f08.ts`. */
const MAX_SKILL_LENGTH = 120;

/**
 * Причесать метку: обрезать, схлопнуть пробелы, ограничить длину.
 *
 * Пустая строка на выходе означает «метки нет» — и именно это значение должен
 * получить `readTaskSkills`, чтобы задание не попало в разрез.
 */
export function cleanSkillLabel(value: unknown): string | null {
  if (typeof value !== "string") return null;
  // Пробелы внутри схлопываем: модель пишет «Давление  твёрдых  тел», а в
  // раззе такое пишется двумя разными метками, если учитель правил одну вручную.
  const trimmed = value.replace(/\s+/gu, " ").trim();
  if (!trimmed) return null;
  return trimmed.length > MAX_SKILL_LENGTH ? trimmed.slice(0, MAX_SKILL_LENGTH).trim() : trimmed;
}

/**
 * Проставить метку каждому заданию.
 *
 * Мутирует `tasks` на месте и возвращает его же: вызывающий код (конец
 * `generateWorksheet`) уже держит готовый лист и дальше только сохраняет его в
 * кэш и отдаёт, поэтому копия здесь была бы лишним объектом в горячем пути.
 */
export function assignTopicSkills<T extends WorksheetTask>(
  tasks: T[],
  planItems: readonly PlanSkillItem[] | null | undefined,
  topic: string,
  options?: { respectBlank?: boolean },
): T[] {
  const fallback = cleanSkillLabel(topic);
  const respectBlank = options?.respectBlank === true;

  for (const [index, task] of tasks.entries()) {
    // Метка от модели — самая узкая, её не трогаем, если она есть.
    const fromModel = cleanSkillLabel((task as WorksheetTask).skill);
    if (fromModel) {
      (task as WorksheetTask).skill = fromModel;
      continue;
    }
    // Учитель стёр метку — уважаем: пусто значит «без метки», а не «верни
    // то, что было».
    if (respectBlank && (task as WorksheetTask).skill !== undefined && (task as WorksheetTask).skill === "") {
      continue;
    }
    // Позиция плана. Нумерация в плане — с единицы (`normalizePlan` сам
    // проставляет `n`), но берём позицию массива: план и лист строятся по
    // одному и тому же количеству, а после фильтра качества позиции разъезжаются.
    const planned = planItems?.[index];
    const fromPlan = cleanSkillLabel(planned?.навык) ?? cleanSkillLabel(planned?.подтема);
    (task as WorksheetTask).skill = fromPlan ?? fallback;
  }

  return tasks;
}