export interface BuildExamPromptArgs {
  exam: "oge" | "ege";
  subject: SubjectSlug;
  variantNumber: number;
}

/**
 * Собрать { system, user } для генерации экзаменационного варианта.
 *
 * Дополнительно возвращаем expectedDuration — caller подмешает его в title.
 */
export function buildExamPrompt(args: BuildExamPromptArgs): {
  system: string;
  user: string;
  expectedDuration: number;
} {
  const expectedDuration = args.exam === "oge" ? 235 : 235; // TODO: разделить базовый/профильный позже

  // TZ-13: явный таргет языка. Без этого LLM для не-языковых предметов
  // периодически отдаёт английские грамматические упражнения («Open the brackets: ...»).
  const SUBJECT_LANG: Record<string, string> = {
    english: "английский",
    german: "немецкий",
  };
  const targetLang = SUBJECT_LANG[args.subject] ?? "русский";

  const user = JSON.stringify(
    {
      задача: "Сгенерируй экзаменационный вариант",
      параметры: {
        экзамен: args.exam,
        предмет: args.subject,
        язык_текста: targetLang,
        номер_варианта: args.variantNumber,
      },
      структура: {
        часть_1: "short-answer / choice задания с кратким ответом",
        часть_2: "detailed задания с развёрнутым решением",
        продолжительность_мин: expectedDuration,
      },
      язык_формулировок:
        args.subject === "english"
          ? "ENGLISH: пиши все формулировки, вопросы и варианты ответов на английском языке."
          : args.subject === "german"
            ? "GERMAN: пиши все формулировки, вопросы и варианты ответов на немецком языке."
            : "РУССКИЙ: пиши все формулировки, вопросы и варианты ответов СТРОГО на русском языке. Никакого английского.",
      верни: "JSON по схеме. Без markdown.",
    },
    null,
    2,
  );

  return { system: EXAM_GEN_SYSTEM, user, expectedDuration };
}

