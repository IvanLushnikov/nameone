/**
 * Промпт ранклера интерактивов: `interactive-pack` (TZ-13 §4.7).
 *
 * КЛЮЧЕВОЕ ПРАВИЛО ТЗ: «генерация новых заданий с нуля — НЕТ». Мы уже
 * сгенерировали и проверили лист, поэтому модель НЕ придумывает новые
 * задания, а РАСКЛАДЫВАЕТ существующие `payload_json.tasks` по механике
 * формата. Второй вызов LLM на генерацию контента = двойной COGS без выгоды.
 *
 * Что именно делает модель (механическая, но не тривиальная работа):
 *   quiz-race / fortune-wheel — превратить `short-answer`/`computation`
 *     задание в вопрос с вариантами: сформулировать 3–4 варианта и выбрать
 *     правильный (это единственное место, где модель пишет новое — варианты
 *     ответа, а не новые задания);
 *   jump-truth — превратить задание в утверждение «правда/ложь»;
 *   sort-baskets / fortune-wheel / jeopardy — разложить задания по секторам,
 *     корзинам и категориям, придумав НЕЗАВИСИМЫЕ от учителя названия;
 *   sort-sequence — расставить `orderIndex`.
 *
 * Формат ответа — строгий JSON: валидатор (`deepseek-v4-flash`) и серверный
 * скоринг читают именно его, поэтому лишние поля запрещены.
 */

import type { InteractiveFormat, InteractiveOptions } from "../../lib/interactives/types";
import type { Worksheet } from "../../types";

export interface InteractivePackPromptArgs {
  worksheet: Worksheet;
  format: InteractiveFormat;
  options: InteractiveOptions;
}

/**
 * Требования к каждому формату. Отдельный блок на формат вместо общих слов:
 * модели надёжнее следуют явному списку полей, а не абзацам прозы.
 */
const FORMAT_RULES: Record<InteractiveFormat, string> = {
  "quiz-race": `ФОРМАТ quiz-race (вопросы подряд, очки за скорость).
- items: 10–20 заданий из листа.
- Для каждого задания ОБЯЗАТЕЛЬНЫ options: 3–4 варианта, ВКЛЮЧАЯ правильный.
- correctIndex: индекс правильного варианта (0-based), ровно один.
- Варианты формулируй кратко, это ответы на игровое задание, а не эссе.
- points не выставляй — движок считает очки сам (100 + бонус за скорость).`,

  "sort-baskets": `ФОРМАТ sort-baskets (перетащить карточки в 2–4 корзины).
- options.baskets: 2–4 коротких названия категорий, придумай сам по теме листа.
- items: 8–20 карточек. Это НЕ задания целиком, а предметы для сортировки:
  формулируй их короткими существительными («берёза», «куб 4×4»), без вопроса.
- correctBucket: id корзины, в которую карточка кладётся правильно (одно из options.baskets).
- 1–3 карточки помечай isTrap: true — они не относятся ни к одной корзине,
  у них correctBucket НЕ заполняй (null).
- options у item не нужны (null), correctIndex не нужен (null).`,

  "jump-truth": `ФОРМАТ jump-truth (ход по полю, утверждения правда/ложь).
- items: 10–30 утверждений по теме листа.
- prompt: самоутверждение, БЕЗ вопросительного знака, eg «Неправильные дроби меньше 1».
- isTrue: true или false. Ровно одно поле, без строк "да"/"нет".
- Сбалансируй: примерно поровну true и false.
- options у item = null, correctIndex = null, points = null.`,

  "fortune-wheel": `ФОРМАТ fortune-wheel (колесо с секторами, вопрос из выпавшего сектора).
- options.sectors: 4–8 названий секторов, eg «Сложение», «Порядок действий».
- items: 8–24 вопроса, у КАЖДОГО обязательно bucket = одно из options.sectors.
- questionsPerSector: сколько вопросов в секторе (напиши в options).
- Для каждого items нужны options (3–4 варианта) и ровно один correctIndex.
- Сектора должны быть примерно равными по количеству вопросов.`,

  jeopardy: `ФОРМАТ jeopardy (доска: номинации × категории, очки 100/200/300/400).
- options.categories: 3–4 названия категорий.
- options.rows: сколько номинаций (3–5).
- options.pointLadder: [100, 200, 300, 400] — очки по столбцам.
- items: 3–4 вопроса на КАЖДУЮ клетку доски (категория × номинация), итог 9–20 items.
- У каждого item: bucket = categories[i], points = pointLadder[i] (по позиции в клетке).
- options (3–4 варианта) и ровно один correctIndex обязательны.
- Вопросы в дорогих клетках (300/400) — посложнее.`,

  "sort-sequence": `ФОРМАТ sort-sequence (упорядочить набор по принципу).
- options.principle: принцип сортировки ОДНОЙ фразой, eg «по возрастанию»,
  «по алфавиту», «по размеру», «по хронологии». Своё не придумывай — только эти.
- options.mode: "order" (порядок).
- items: 5–12 объектов, коротко: «2/9», «10/11», «0,3».
- orderIndex: позиция объекта в ЭТАЛОННОМ порядке, 0-based, без пропусков и повторов.
- В prompt объекта НЕТ вопроса — только сам объект.
- options у item = null, correctIndex = null, points = null.`,
};

/**
 * Ограничение на графику. Модель возвращает спецификацию ChartSpec, а рендерит
 * сервер (ТЗ §4.8). На сервере умеем bar / pie / number_line — остальное
 * сервер не отрендерит, поэтому ЗАПРЕЩАЕМ просить, чтобы задание не осталось
 * без картинки.
 */
const CHART_RULES = `ГРАФИКА (необязательна).
- Можешь приложить chart к 1–3 заданиям, где без картинки не понять вопрос
  («какая доля на диаграмме», «отметь число на прямой»).
- chart — это ОБЪЕКТ со spec, а не строка SVG: {"spec": {...}}.
- Допустимы только три типа: "bar" (type:"bar", data:{labels:[], values:[]}),
  "pie" (type:"pie", data:{labels:[], values:[]}),
  "number_line" (type:"number_line", range:[min,max], points:[{value,label}]).
- ВЕЗДЕ, где картинки нет, chart = null. Типов line/geometry/biology/chemistry НЕ используй.`;

/** Сборка промпта. Возвращает пару system/user, как принято в llm/prompts. */
export function buildInteractivePackPrompt(args: InteractivePackPromptArgs): {
  system: string;
  user: string;
} {
  const { worksheet, format, options } = args;

  // Лист режем до нужного: тексты заданий нужны, служебные поля — нет.
  // Это уменьшает вход (ТЗ оценивает 2–3k токена) и убирает мусор из промпта.
  const tasks = worksheet.tasks.map((t) => ({
    number: t.number,
    text: t.text,
    type: t.type,
    options: t.options ?? null,
    answer: t.answer ?? null,
    points: t.points,
  }));

  const system = `Ты — методист, который превращает ГОТОВЫЙ рабочий лист в игровой интерактив для класса.

ЖЁСТКОЕ ПРАВИЛО: новые задания НЕ придумывать. У тебя есть проверенный лист с заданиями.
Твоя работа — РАЗЛОЖИТЬ эти задания по механике выбранного формата: сформулировать
варианты ответа к существующему заданию, придумать названия корзин/секторов/категорий,
превратить задание в утверждение «правда/ложь», расставить порядок.
Количество и смысл заданий сохраняются — меняется только форма подачи.

Ответ — СТРОГО ОДИН JSON-объект без markdown и без текста вокруг. Структура:
{
  "title": "название интерактива для класса, до 60 символов",
  "items": [ ... ],
  "options": { ... },
  "summary": "одно предложение: что делает этот интерактив"
}

ОДИН item = один JSON-объект. Поля, которые формату не нужны, ставь null — не опускай.
id у item — короткая строка "i1", "i2", … в порядке следования.

${FORMAT_RULES[format]}

${CHART_RULES}

ЧЕГО НЕ ДЕЛАТЬ:
- не выдумывать темы и факты, которых нет в листе;
- не оставлять задание без правильного ответа (correctIndex обязателен там, где есть варианты);
- не дублировать варианты ответа внутри одного задания;
- не писать «правильный ответ: 5» в prompt — правильный ответ живёт в correctIndex / isTrue;
- не добавлять поля, которых нет в описании формата.`;

  const user = `ТЕМА: ${worksheet.subject}, ${worksheet.grade} класс
ТЕМА УРОКА: ${worksheet.topic}
СЛОЖНОСТЬ: ${worksheet.difficulty}
ЗАГОЛОВОК ЛИСТА: ${worksheet.title}

ЗАДАНИЯ ЛИСТА (${tasks.length} шт.), кладём их в формат "${format}":
${JSON.stringify(tasks, null, 2)}

НАСТРОЙКИ ФОРМАТА ОТ УЧИТЕЛЯ (учитывай их, но можешь дополнить):
${JSON.stringify(options, null, 2)}

Верни JSON по схеме из system.`;

  return { system, user };
}
