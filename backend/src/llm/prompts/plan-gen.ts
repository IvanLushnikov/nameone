/**
 * Проверить план и почистить.
 *
 * План — результат чужой модели, поэтому доверять ему нельзя. Плохой план
 * хуже отсутствия плана: он навязал бы листу конкретные навыки, часть которых
 * может оказаться за пределами класса.
 *
 * Возвращает `null`, если план не годится: конвейер продолжит старым путём,
 * без плана. Это осознанно — план улучшает качество, но не должен быть
 * условием выдачи листа.
 */
export function normalizePlan(raw: unknown, count: number): SheetPlan | null {
  if (!raw || typeof raw !== "object") return null;
  const items = (raw as { items?: unknown }).items;
  if (!Array.isArray(items) || items.length === 0) return null;

  const seen = new Set<string>();
  const clean: PlanItem[] = [];

  for (const item of items) {
    if (clean.length >= count) break;
    if (!item || typeof item !== "object") continue;

    const подтема = typeof (item as Record<string, unknown>).подтема === "string"
      ? String((item as Record<string, unknown>).подтема).trim()
      : "";
    const навык = typeof (item as Record<string, unknown>).навык === "string"
      ? String((item as Record<string, unknown>).навык).trim()
      : "";
    const тип = typeof (item as Record<string, unknown>).тип === "string"
      ? String((item as Record<string, unknown>).тип).trim()
      : "";

    if (!подтема || !навык) continue;

    // Навык обязан быть уникальным — это весь смысл плана.
    const key = `${подтема.toLowerCase()}|${навык.toLowerCase()}`;
    if (seen.has(key)) continue;
    seen.add(key);

    const rawDiff = String((item as Record<string, unknown>).сложность ?? "").toLowerCase();
    const сложность = /сложн|hard|трудн/.test(rawDiff)
      ? "сложная"
      : /лёгк|легк|easy|прост/.test(rawDiff)
        ? "лёгкая"
        : "средняя";

    clean.push({ n: clean.length + 1, подтема, навык, тип, сложность });
  }

  // Неполный план хуже никакого: листу не хватает заданий, а добор идёт
  // без плана и без пользы.
  if (clean.length < count) return null;

  return { items: clean };
}