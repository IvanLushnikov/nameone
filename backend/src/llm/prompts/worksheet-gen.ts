/**
 * Предел длины одного блока `$...$` в `text_latex`.
 * Дублируется в промпте (правило 8) и в `src/lib/math/latex.ts`
 * (MAX_LATEX_BLOCK_LENGTH) — на клиенте это вторая линия защиты.
 */
export const MAX_TEXT_LATEX_BLOCK = 200;

/**
 * Санитайзер `text_latex` из ответа модели.
 *
 * ЗАЧЕМ. Модель периодически «залипает» на длинной математике и отдаёт блок
 * `$...$` на пол-экрана либо незакрытую конструкцию. Такое рендерить нельзя,
 * поэтому блок выкидывается целиком, и задание показывается обычным текстом.
 *
 * ГЛАВНОЕ ПРАВИЛО. `text` тут НЕ трогаем. Он остаётся эталоном для
 * self-verification и сверки ответов; чистится только дополнительное поле
 * `text_latex`, которое на проверку ответов не влияет вообще.
 *
 * ГДЕ ПРИМЕНЯТЬ. На разборе JSON-ответа модели (backend/src/llm/index.ts),
 * до сохранения задания. Живёт рядом с промптом намеренно: правило в промпте
 * и фильтр в коде должны быть рядом, иначе модель продолжит писать длинные
 * формулы, которые молча выкидываются.
 *
 * @returns очищенный `text_latex` либо `undefined`, если его не было или после
 *          чистки не осталось ничего осмысленного.
 */
export function sanitizeTextLatex(value: unknown): string | undefined {
  if (typeof value !== "string") return undefined;
  const cleaned = value.replace(/\$([^$]+)\$/g, (whole, body: string) =>
    body.trim().length > MAX_TEXT_LATEX_BLOCK ? "" : whole
  );
  return cleaned.trim() ? cleaned : undefined;
}

/**
 * Собрать { system, user } для генерации рабочего листа.
 */
export function buildWorksheetPrompt(req: GenerationRequest): {
  system: string;
  user: string;
} {
  const user = JSON.stringify(
    {
      задача: "Сгенерируй рабочий лист по параметрам ниже",
      параметры: {
        subject: req.subject,
        grade: req.grade,
        topic: req.topic,
        difficulty: req.difficulty,
        count: req.count,
        type: req.type,
        withAnswers: req.withAnswers,
        withExplanations: req.withExplanations,
      },
      требования: {
        точно_count: req.count,
        все_ответы_обязательны: req.withAnswers,
        все_пояснения_обязательны: req.withExplanations,
        тип_работы: req.type,
      },
      верни: "JSON по схеме из системного промпта. Без markdown-блоков.",
    },
    null,
    2,
  );

  return { system: WORKSHEET_GEN_SYSTEM, user };
}
