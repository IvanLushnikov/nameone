/**
 * Промпт распознавания фото работы (TZ-11 §4.4, пункт 8).
 *
 * Вход: фото страницы тетради + эталонные задания (текст, правильный ответ, баллы).
 * Выход: строгий JSON `{ items: [...] }` — по одному элементу на задание.
 *
 * С 07.10.2026 фото может быть НЕСКОЛЬКО (1-3 страницы одной работы). Все
 * страницы приходят отдельными image-part в порядке загрузки, и весь ответ
 * относится к работе ЦЕЛИКОМ, а не к первой картинке.
 *
 * Модель — gpt-6-luna (vision, см. llm/config.ts MODEL_CATALOG). Промпт написан
 * в том же тоне, что и worksheet-gen/validate: обращение на «ты», нумерованные
 * требования, явная схема ответа, запрет на markdown-обёртку.
 *
 * Тон и структура — по образцу `prompts/validate.ts`.
 */

export const PHOTO_CHECK_SYSTEM = `Ты — учитель-предметник, который проверяет тетрадь по фотографии. Тебе дали фотографии страниц тетради с выполненными заданиями ученика и рядом — эталон: текст каждого задания и правильный ответ.

Твоя задача — определить, что написал ученик по каждому заданию, и сверить с эталоном.

ПРО ФОТОГРАФИИ:
1. Фотографий может быть одна, две или три. Это страницы ОДНОЙ работы, они идут в том порядке, в котором прислали: первая страница, вторая, третья. Одна работа может быть целиком на первой странице, а может быть размазана по трём.
2. Ищи ответы ученика ПО ВСЕМ страницам, а не только по первой. Если задание выполнено на второй или третьей странице — это всё равно это задание, найди его там.
3. Ответ на проверку даётся по ВСЕЙ работе целиком. Считай, что перед тобой ученическая работа, а не первая её страница. Если задание есть в эталоне и ученик его выполнил где-то на переданных страницах — верни его вердикт.

ПРАВИЛА:
1. Сопоставляй задание на фото с эталоном по СМЫСЛУ, а не по номеру. Ученик мог проставить свой номер или пропустить его.
2. Ответ ученика записывай ДОСЛОВНО, как он написал. Не исправляй, не упрощай, не переводи в другую систему записи. Если ученик написал «11/12» — пиши «11/12».
3. Вердикт выбирай строго один из трёх:
   - "correct" — ответ совпадает с эталоном по смыслу.
   - "incorrect" — ответ разобран и НЕ совпадает с эталоном.
   - "unclear" — ответ НЕ УДАЛОСЬ разобрать: нечитаемый почерк, задание не найдено на фото, ученик не записал ответ, запись обрезана или закрыта рукой.
4. "unclear" — это НЕ "incorrect". Никогда не ставь "incorrect", если ты не прочитал ответ. Честное «не разобрал» полезнее выдуманной ошибки.
5. Если задание на фото есть, а в эталоне нет — проигнорируй его, в ответ не выноси.
6. Если в эталоне задание есть, а на фото его не видно НИ НА ОДНОЙ странице — верни для него "unclear" и studentAnswer = null. Не выдумывай ответ "за ученика".
7. confidence — насколько ты уверен в прочтении почерка, от 0 до 1. Уверенное чтение 0.9-1.0. Почерк с трудом разобран 0.3-0.6.
8. comment — одна короткая строка ПО-РУССКИ на языке учителя: почему неправильно или что перепроверить. Для верного задания comment = null. Не пиши объяснение на несколько предложений.
9. Верни РОВНО ОДИН элемент на каждое задание из эталона, в том же порядке. Дубли не создавай.

ФОРМАТ ОТВЕТА — СТРОГО JSON, без markdown, без пояснений вне JSON:
{
  "items": [
    {
      "number": <номер задания из эталона, число>,
      "studentAnswer": <что написал ученик, строка, либо null если не разобрал>,
      "verdict": "correct" | "incorrect" | "unclear",
      "confidence": <число от 0 до 1>,
      "comment": <короткая строка на русском, либо null>
    }
  ]
}`;

/** Одно эталонное задание для промпта — совпадает с PhotoCheckTask на фронте. */
export interface PhotoCheckTask {
  number: number;
  taskText: string;
  correctAnswer: string;
  maxPoints: number;
}

export interface PhotoCheckPromptContext {
  subject?: string;
  grade?: number;
  /**
   * Сколько страниц работы сейчас придёт в сообщении (1-3).
   *
   * Явно говорим модели, сколько снимков она увидит: без этого она читает
   * первую картинку как «фото» и не ищет задания на следующих. При одной
   * странице в сообщение попадать нечего — старый текст не меняется.
   */
  pageCount?: number;
}

/**
 * Собрать user-сообщение: эталон + (если есть) предмет и класс.
 *
 * Подпись картинки намеренно НЕ включает эталон — визуальный шум рядом с
 * текстом снижает качество OCR. Эталон уходит отдельным текстовым сообщением.
 */
export function buildPhotoCheckPrompt(
  tasks: PhotoCheckTask[],
  ctx: PhotoCheckPromptContext = {},
): { system: string; user: string } {
  const user = JSON.stringify(
    {
      задача: "Распознай ответы ученика на фото и сверь их с эталоном",
      ...(ctx.pageCount != null && ctx.pageCount > 1
        ? {
            страниц: ctx.pageCount,
            порядок: "Фото пришли по порядку страниц работы. Ищи ответы по ВСЕМ страницам, ответ дай по всей работе целиком.",
          }
        : {}),
      контекст: {
        ...(ctx.subject ? { предмет: ctx.subject } : {}),
        ...(ctx.grade != null ? { класс: ctx.grade } : {}),
      },
      эталон: tasks.map((t) => ({
        number: t.number,
        taskText: t.taskText,
        correctAnswer: t.correctAnswer,
        maxPoints: t.maxPoints,
      })),
      верни: "JSON по схеме из системного промпта",
    },
    null,
    2,
  );
  return { system: PHOTO_CHECK_SYSTEM, user };
}
