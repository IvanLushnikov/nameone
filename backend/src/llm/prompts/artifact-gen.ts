// ─────────────────────────────────────────────────────────────────────────────
// Помощники разбора ответа модели.
//
// Модель — не источник истины по типам: она возвращает `null` вместо массива,
// число строкой и значение enum'а, которого нет в списке. Разбор приводит ответ
// к контракту, который потом проверяет zod на `/api/worksheets/save`. Если
// привести не к чему (пустой обязательный массив) — вызывающий бросает
// ошибку, а НЕ подставляет заготовку: заготовка здесь означала бы, что
// учителю отдали сгенерированный материал, которого не генерировали.
// ─────────────────────────────────────────────────────────────────────────────

/** Объект или null. Примитивы и массивы отбрасываются. */
export function asRecord(value: unknown): Record<string, unknown> | null {
  if (!value || typeof value !== "object" || Array.isArray(value)) return null;
  return value as Record<string, unknown>;
}

/** Непустая строка или "". Числа и булевы значения строкой НЕ становятся. */
export function asText(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

/** Массив непустых строк. Не массив — пустой список. */
export function asTextList(value: unknown): string[] {
  if (!Array.isArray(value)) return [];
  return value
    .map((item) => asText(item))
    .filter((item): item is string => item.length > 0);
}

/**
 * Значение из закрытого списка.
 *
 * `fallback = null` означает «не знаю такого значения — выброси элемент».
 * Это осознанный выбор: подставить соседнее значение значит выдумать смысл
 * (этап урока, названный учителем «разбором», тихо стал бы «practice»).
 * Лучше меньше элементов, чем неверно названные, — но если не осталось ни
 * одного, вызывающий сообщит об ошибке.
 */
export function pickEnum<T extends string>(
  value: unknown,
  allowed: readonly T[],
): T | null {
  return typeof value === "string" && (allowed as readonly string[]).includes(value)
    ? (value as T)
    : null;
}

/** Целое число в диапазоне. Строка с цифрами допускается, дробь — нет. */
export function asIntInRange(value: unknown, min: number, max: number): number | null {
  const n = typeof value === "string" ? Number(value) : value;
  if (typeof n !== "number" || !Number.isFinite(n)) return null;
  const rounded = Math.round(n);
  if (rounded < min || rounded > max) return null;
  return rounded;
}