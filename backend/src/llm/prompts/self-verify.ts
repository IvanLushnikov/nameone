/**
 * Промпты для self-verification (перенесены из worker-self-verify/src/prompts.ts).
 *
 * Двухпроходная схема:
 *   1. SOLVE_PROMPT  — LLM решает задачу НЕ ЗНАЯ ответа, получает answer.
 *   2. VERIFY_PROMPT — LLM сверяет полученный ответ с эталоном из банка задач.
 *
 * В обоих случаях модель получает минимальный контекст: subject / grade / topic,
 * формулировку задачи и, во втором проходе, эталон.
 *
 * Температура 0 на обоих проходах — нам нужна воспроизводимость, не креатив.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ В SOLVE_PROMPT НЕТ `expectedAnswer` (06.10.2026)
 * ─────────────────────────────────────────────────────────────────────────────
 * Раньше он там был — строкой «Известный ответ (подсказка для самопроверки…)».
 * Из-за этого первый проход подстраивался под эталон, а второй сравнивал
 * подстроенное решение с ТЕМ ЖЕ эталоном: совпадение было гарантировано по
 * построению. Это было равенство, а не проверка. Живая проверка на проде это
 * подтвердила: задача «3/8 + 1/8» с заведомо неверным эталоном «42» вернула
 * `verified: true`, причём числа 42 не было даже в тексте объяснения.
 *
 * В первой версии этой правки параметр ещё оставался в сигнатуре
 * `SOLVE_PROMPT` — чтобы «не ломать вызовы». Так делать нельзя: параметр в
 * сигнатуре читается как разрешение его использовать, и подсказка возвращается
 * при первом же «улучшении точности». Поэтому поле удалено ИЗ ТИПА: передать
 * эталон в решающий промпт теперь нельзя даже на уровне компиляции, а
 * тест в tests/unit/selfVerify.test.ts падает, если он вернётся.
 *
 * Побочный плюс: эталон больше не утекает в текст решения, который учитель
 * видит на странице.
 */

export const SOLVE_PROMPT = (input: {
  subject: string;
  grade: number;
  topic: string;
  taskText: string;
  /**
   * `expectedAnswer` здесь НЕТ и не должен появляться: первый проход обязан
   * решать задачу независимо, иначе проверяющая не проверяет (см. шапку файла).
   */
}): string => {
  return `Ты — решатель математических задач для школьников.
Предмет: ${input.subject}, класс: ${input.grade}, тема: ${input.topic}.

Задача:
${input.taskText}

Реши задачу САМ, опираясь только на её условие.
Ты не знаешь заранее правильный ответ и не должен угадывать его — просто реши.

Дай КРАТКОЕ решение по шагам и финальный числовой ответ в конце.
Формат:
Шаг 1: ...
Шаг 2: ...
Ответ: <число или выражение>`;
};

/**
 * Второй проход: единственное место, где эталон вообще участвует.
 *
 * Правило проверки расписано явно и по пунктам, потому что «сравнить
 * предложенное с эталоном» модель читает как «вежливо согласиться»: в первой
 * версии промпта это правило было одной фразой без правил на эквивалентные
 * записи, и результатом был почти всегда `true`.
 */
export const VERIFY_PROMPT = (input: {
  subject: string;
  grade: number;
  taskText: string;
  /** Извлечённый финальный ответ решения — не весь текст с шагами. */
  proposedAnswer: string;
  expectedAnswer?: string;
}): string => {
  const hasExpected = Boolean(input.expectedAnswer && input.expectedAnswer.trim().length > 0);

  const expectedBlock = hasExpected
    ? `Эталонный ответ из банка задач: ${input.expectedAnswer!.trim()}`
    : `Эталона нет. Проверь только корректность решения по условию задачи.
Это нормальный случай, отсутствие эталона НЕ является поводом ответить
{"verified": false, "reason": "нет эталона"}.`;

  const rule = hasExpected
    ? `ПРАВИЛА ПРОВЕРКИ (соблюдай буквально):
1. Сравни «Ответ решения» с «Эталонным ответом из банка задач».
2. Совпадают → {"verified": true, "reason": "ответ совпадает с эталоном"}.
3. Расходятся → {"verified": false, "reason": "ответ не совпадает: получили <X>, эталон <Y>"},
   где <X> — ответ решения, а <Y> — эталон. Оба значения обязательны в reason.
4. Сравнивай ЗНАЧЕНИЕ, а не символы. Одни и те же ответы:
     4/8 и 1/2; 1 1/2 и 3/2; 0.50 и 0.5; 2 и 2,0.
   Это СОВПАДЕНИЕ (verified: true).
   Разные ответы: 42 и 1/2; 5/6 и 5/7; 12 и 21.
   Это НЕСОВПАДЕНИЕ (verified: false), даже если записи выглядят похоже.
5. Если ответ не приводится к числу (текст, слово, перечисление) и его нельзя
   привести к эталону по смыслу — это verified: false с указанием обоих
   ответов в reason. Не ставь true «на всякий случай».`
    : `ПРАВИЛА ПРОВЕРКИ (соблюдай буквально):
1. Проверь, что решение правильное по условию задачи.
2. Если решение верное → {"verified": true, "reason": "решение корректно"}.
3. Если в решении ошибка → {"verified": false, "reason": "в решении ошибка: ..."},
   обязательно указав, где именно.`;

  return `Ты — проверяющий решений математических задач.
Предмет: ${input.subject}.

Задача:
${input.taskText}

Ответ решения (извлечён из независимого решения этой же задачи):
${input.proposedAnswer.trim()}

${expectedBlock}

${rule}

Верни СТРОГО JSON без пояснений вокруг:
{"verified": true | false, "reason": "короткое объяснение на русском"}`;
};
