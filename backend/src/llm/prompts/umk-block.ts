/**
 * ОБЩИЙ БЛОК ПРО ВЫБРАННЫЙ УЧЕБНИК (лист 2.1.7).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ
 * ─────────────────────────────────────────────────────────────────────────────
 * Лист 2.1.1 довёл выбор учебника только до рабочего листа: правило жило
 * локальной функцией внутри `worksheet-gen.ts`, а план урока, презентация, КТП,
 * карточки и материалы про учебник не знали вообще. Учитель ставит галочку
 * «Мерзляк» и получает шесть одинаковых материалов — выбор виден в галочке и
 * больше нигде.
 *
 * Шесть копий правила — хуже отсутствия правила: через месяц в копии для КТП
 * забудут запрет выдумывать параграфы, и учитель получит две разные честности
 * на одном экране. Поэтому блок ОДИН, а шесть типов только называют свою опору.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ
 * ─────────────────────────────────────────────────────────────────────────────
 * 1) НЕ обещаем дословного совпадения с учебником. Текста учебника у модели
 *    нет, совпадения не будет, а обещание, которое продукт не держит, уже
 *    стоило проекту репутационных правок. Обещаем подход, обозначения и
 *    порядок — то, что учителю реально нужно, чтобы вести урок.
 *
 * 2) ЗАПРЕЩАЕМ выдумывать номера параграфов, страниц и упражнений. Учебник в
 *    промпте — новый повод выдумать параграф. `NO_TECHNICAL_FIELDS_RULE` в
 *    `artifact-gen.ts` запрещает это для остальных типов, но правило, о котором
 *    модель не знает, в этом месте не работает.
 *
 * 3) ОТДАЁМ ТОЛЬКО `id`. Таксономия учебников живёт во фронте
 *    (`src/lib/content/umk.ts`), и backend не должен её дублировать: копия
 *    устареет тихо, и тогда модель будет получать учебник, которого в каталоге
 *    уже нет. Вместо этого прямо сказано: не узнал учебник — работай по программе
 *    предмета. Тихая подмена на «программу вообще» лучше выдуманного учебника.
 *
 * 4) НЕ ССЫЛАЕМСЯ НА НОМЕРА ПРАВИЛ. Общий блок едет в шесть промптов, а
 *    «правило 9» и «правило 13» существуют только в системном промпте листа.
 *    Ссылка на них в КТП была бы висячей, поэтому граница названа словами:
 *    программа предмета и класс из параметров главнее учебника.
 *
 * 5) ТОКЕНЫ. Блок едет ТОЛЬКО когда учитель выбрал учебник (см. разворот
 *    `...(umk ? … : {})` в каждом билдере) — без выбора промпт не меняется ни на
 *    токен. При выборе блок стоит ~1 КБ; потолок задан константой и проверяется
 *    скриптом `scripts/check-umk-coverage.mjs`, чтобы правило не разрослось
 *    незаметно.
 *
 * 6) ПРО КЭШ И ПРО РОУТЫ — НЕ ЗДЕСЬ, НО БЕЗ НИХ ФИЧА НЕ ДОЕЗЖАЕТ.
 *    Пока слой роутов не пробрасывает `meta` (zod-схема
 *    `routes/artifact-generate.ts` по умолчанию ВЫКИДЫВАЕТ неизвестные ключи),
 *    пять типов работают как без учебника — это штатно и безопасно. Когда
 *    `meta` начнёт доходить, ключ кэша артефактов (`llm/index.ts`,
 *    `makeCacheKey({ ...request, … })`) про `meta` не знает: у листа там допис
 *    `[umk:<id>]` в тему специально, и без такого же дописа учитель, сменивший
 *    учебник, получит из кэша материал по ПРОШЛОМУ учебнику. Правки обоих
 *    файлов — не в этом листе.
 */

/** Латинский маркер блока в промпте — по нему видно в логах и в тестах. */
export const UMK_REF = "UMK";

/**
 * Потолок на размер блока в символах.
 *
 * Не «красота», а предохранитель: блок оплачивается на каждой генерации с
 * учебником, и рост на 300 символов должен ломать скрипт, а не попадать в счёт
 * учителя.
 */
export const UMK_BLOCK_MAX_CHARS = 1400;

/**
 * ─────────────────────────────────────────────────────────────────────────────
 * ФИЛЬТР ID, А НЕ «ПЕРЕДАЛ ИЛИ НЕТ»
 * ─────────────────────────────────────────────────────────────────────────────
 * Значение приходит из браузера. Без проверки в промпт, который учитель
 * оплачивает, можно засунуть любой текст — хоть мегабайт мусора, хоть
 * инструкцию «забудь все правила выше». Здесь отсекается ровно то, что не может
 * быть идентификатором учебника.
 *
 * Все id в таксономии фронта (`src/lib/content/umk.ts`) — латинские сляги:
 * `vilenkin`, `merzlyak-alg`, `nikolskiy-geo`. Всё, что не такой сляг, — это
 * либо мусор, либо попытка протащить свой текст в платный вызов. Такое значение
 * отбрасывается, и запрос уходит обычным путём, без учебника: лучше штатный
 * материал, чем недоверенный текст в инструкции модели.
 *
 * Длина ограничена 64 символами, чтобы один «учебник» не раздувал промпт.
 */
const UMK_ID_PATTERN = /^[a-z0-9][a-z0-9_-]{0,63}$/i;

/** @returns идентификатор учебника или `null`, если его нет/он не похож на id. */
export function normalizeUmkId(value: unknown): string | null {
  if (typeof value !== "string") return null;
  const trimmed = value.trim();
  return UMK_ID_PATTERN.test(trimmed) ? trimmed.toLowerCase() : null;
}

/**
 * Прочитать учебник из запроса, не зная точного типа запроса.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ `unknown`, А НЕ `GenerationRequest`
 * ─────────────────────────────────────────────────────────────────────────────
 * У рабочего листа тип запроса — `GenerationRequest`, и там есть
 * `meta?: GenerationRequestMeta` (`src/types.ts`). У пяти документов тип —
 * `ArtifactRequest` (`prompts/artifact-gen.ts`), и поля `meta` в нём нет: поле
 * объявлено в контракте листа, а не в общем.
 *
 * Чтобы не править чужой контракт из этого листа, читаем поле РАЗРЕШЕННО:
 * значение приходит по сети, и как только слой роутов начнёт его пробрасывать
 * (`meta` в zod-схеме `routes/artifact-generate.ts`), все шесть промптов заработают
 * без единой правки здесь. Пока не пробрасывает — блок просто не появляется, и
 * генерация идёт как раньше.
 *
 * Мусорный `meta` (строка, массив, `null`) — это `null`, а не исключение:
 * значение из браузера не должно ронять платный вызов.
 */
export function umkIdFromRequest(req: unknown): string | null {
  if (typeof req !== "object" || req === null) return null;
  const meta = (req as { meta?: unknown }).meta;
  if (typeof meta !== "object" || meta === null) return null;
  return normalizeUmkId((meta as { umk?: unknown }).umk);
}

/**
 * ОПОРА УЧЕБНИКА НА КАЖДЫЙ ТИП — по одному ключу на тип.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ЧТО ЭТО ТАКОЕ
 * ─────────────────────────────────────────────────────────────────────────────
 * Общая часть блока описывает три рычага (порядок, формулировки, обозначения),
 * но на разных материалах они работают по-разному: презентации учитель не
 * сверяет построчно с книгой, а КТП — это вообще перечень тем, где решает
 * последовательность. Поэтому у каждого типа своя короткая опора: она говорит,
 * на что этот тип смотрит в учебнике.
 *
 * Словарь живёт здесь, а не в шести промптах, по той же причине, что и сам
 * блок: правило в одном месте — иначе через месяц у КТП появится своя версия
 * «как использовать учебник». Ключи — по именам экспортируемых билдеров.
 */
export const UMK_FOCUS = {
  worksheet:
    "Лист отдают классу как есть: ученик сверяется с учебником построчно, " +
    "поэтому порядок тем, термины и обозначения должны быть учебниковыми.",
  lessonPlan:
    "Термины и формулировки целей — учебниковые: названия стадий, цели и " +
    "домашнее задание звучат так же, как у учителя, который ведёт класс по " +
    "этому учебнику. Номер параграфа, страницы или упражнения в домашнем задании " +
    "не выдумывай — у учителя он есть, у тебя нет.",
  presentation:
    "На слайдах термины и обозначения — учебниковые: буквы, запись величин и " +
    "формул — только там, где они реально нужны, а не на каждом слайде.",
  ktp:
    "Последовательность тем в пределах учебного года — как в учебнике, раздел " +
    "называй его словами; темы не переставляй и не переименовывай по-своему.",
  cards:
    "Термины на карточках — учебниковые: лицевая и оборотная стороны говорят " +
    "о понятии теми словами, какими его называет учебник.",
  materials:
    "Словарь и справочные файлы — в терминах и обозначениях учебника: комплект " +
    "должен звучать как страницы из него, а не как пересказ темы.",
} as const;

/** Ключ опоры = тип материала. */
export type UmkType = keyof typeof UMK_FOCUS;

/**
 * Собрать блок учебника для промпта.
 *
 * Единственное место в проекте, где текст про учебник существует: шесть
 * билдеров зовут эту функцию и передают свою опору. Ни одна копия.
 *
 * @param umkId уже проверенный id (см. `normalizeUmkId`).
 * @param type  тип материала — определяет опору.
 */
export function buildUmkBlock(umkId: string, type: UmkType): Record<string, unknown> {
  const focus = UMK_FOCUS[type];
  if (!focus) {
    // Типа из UMK_FOCUS не существует: блок без опоры обещал бы «что-то
    // про учебник» вообще. Штатный путь честнее.
    return {};
  }
  return {
    // Латинский маркер рядом с кириллическим ключом — по нему видно в логах
    // и в тестах, что учебник доехал. Тот же приём, что у `plan_ref`.
    umk_ref: UMK_REF,
    учебник_id: umkId,
    зачем: "Учитель выбрал этот учебник и ведёт по нему урок.",
    что_сделать:
      "1) ПОРЯДОК — темы в том порядке, в каком они идут в учебнике. " +
      "2) ФОРМУЛИРОВКИ — термины и названия разделов теми словами, какими их " +
      "называет учебник. 3) ОБОЗНАЧЕНИЯ И СИМВОЛИКА — буквы, запись дробей, " +
      "единицы измерения и названия величин те же, что в учебнике.",
    // Опора этого типа. Общая часть выше одинакова везде, а этот ключ объясняет,
    // на что смотрит именно этот материал.
    главное_для_этого_типа: focus,
    чего_не_делать:
      "НЕ выдумывай номера параграфов, страниц и упражнений — текста учебника " +
      "у тебя нет. НЕ обещай дословного совпадения с учебником: нужен его " +
      "подход, а не его текст. Учебник не отменяет программу предмета: понятие " +
      "не раньше своего класса и запрет чужого предмета действуют. Если " +
      "учебник тебе незнаком, id не похож ни на один известный или он явно не " +
      "по этому предмету — работай по программе предмета для этого класса, как " +
      "если бы учебника не было.",
  };
}