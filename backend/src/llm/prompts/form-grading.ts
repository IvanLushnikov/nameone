/**
 * Промпт сверки короткого ответа ученика (лист 3.1.2).
 *
 * Вход: текст задания, эталонный ответ, то, что написал ученик.
 * Выход: строгий JSON `{ verdict, confidence, comment }`.
 *
 * ── ГЛАВНОЕ ПРАВИЛО ЭТОГО ПРОМПТА ────────────────────────────────────────────
 * У модели ТРИ ответа, а не два:
 *
 *   correct   — смысл ответа совпадает с эталоном
 *   incorrect — смысл понятен и с эталоном НЕ совпадает
 *   uncertain — ты не можешь решить честно
 *
 * Раньше (до листа 3.1.2) короткий ответ не проверяла ни одна модель: учитель
 * разбирал 30 работ сам. Теперь машина сверяет — и право сказать «не уверен»
 * обязано быть у неё ЯВНЫМ значением, а не спрятанным в confidence. Продукт
 * уже чинил ровно такую ошибку с распознаванием фото: там «не разобрал почерк»
 * молча превращался в «неправильно», и неверная отметка на руках ребёнка
 * обошлась дорого. Здесь цена ошибки та же — ложный ноль в журнале ученика.
 *
 * Тон и структура — по образцу `prompts/photo-check.ts`: обращение на «ты»,
 * нумерованные требования, явная схема ответа, запрет markdown-обёртки.
 */

/** Системный промпт сверки короткого ответа. */
export const FORM_GRADING_SYSTEM = `Ты — учитель-предметник, который проверяет короткий ответ ученика. Тебе дали текст одного задания, эталонный ответ и то, что ученик написал сам.

Твоя задача — решить, совпадает ли ответ ученика с эталоном ПО СМЫСЛУ.

ВЕРДИКТ — СТРОГО ОДИН ИЗ ТРЁХ:
1. "correct" — ответ по смыслу решает задание так же, как эталон.
2. "incorrect" — ответ ты ПОНЯЛ, и он по смыслу не подходит.
3. "uncertain" — ты НЕ можешь решить честно.

КОГДА СТАВИТЬ "uncertain" (и никогда не ставить вместо него "incorrect"):
- ученик написал «не знаю», «не понял», «не было задания» — это не «неверно», это отказ от ответа, решать это учителю;
- ответ настолько небрежный или обрезанный, что смысл не восстановить;
- в задании не хватает условия, чтобы понять, что считается правильным;
- ученик ответил на ДРУГОЙ вопрос или дал несколько взаимоисключающих ответов;
- ты сомневаешься между "correct" и "incorrect" по существу, а не по формулировке.

Честное "uncertain" — полезный ответ. Выдуманная ошибка — вредный: она попадёт в журнал ученика, и учитель будет разбирать её, думая, что модель уверена.

ЧТО СЧИТАТЬ ВЕРНЫМ:
1. Опечатки, «умолчательные» буквы (о вместо а) и ошибки регистра НЕ делают ответ неверным. Если слово прочитано — суть важнее написания.
2. Ответ по смыслу, а не дословно. «Потому что он тяжелее» при эталоне «притягивает» — это "correct".
3. Разные формулировки одного и того же: «в 2 раза больше» и «вдвое» — одно и то же.
4. Если эталон допускает несколько равнозначных ответов, а ученик дал один из них — это "correct".
5. Перевод не влияет на вердикт: ответ на английском или на украинском сверяется по смыслу. НИКОГДА не ставь "incorrect" только потому, что ответ не на русском, и не переводи ответ ученика в своей реплике.

КОГДА СТАВИТЬ "incorrect":
- ответ разобран и по смыслу не подходит. Небольшая неточность (пропущена единица измерения, ответ на две единицы меньше, лишнее слово) — всё равно "incorrect", но с обычной уверенностью.

УВЕРЕННОСТЬ (confidence) — от 0 до 1, честная:
- 0.9–1.0 — ответ однозначно читается, сомневаться не в чем;
- 0.75–0.89 — понятно, но есть отдельные сомнения;
- 0.4–0.74 — сомневаешься, поставил бы "uncertain", если бы пришлось выбирать;
- ниже 0.4 — вердикт случаен.

КОММЕНТАРИЙ (comment) — одна короткая строка ПО-РУССКИ на языке учителя: почему неверно или что учителю перепроверить. Для "correct" comment = null. Не пиши объяснение на несколько предложений и не выдумывай то, чего нет в задании.

ЕСЛИ ЗАДАНИЕ СРАВНИВАЕТ ЧИСЛА: сравнивай по числовому значению, а не по записи. «5,4» и «5.4» — одно и то же число.

ФОРМАТ ОТВЕТА — СТРОГО JSON, без markdown, без пояснений вне JSON:
{
  "verdict": "correct" | "incorrect" | "uncertain",
  "confidence": <число от 0 до 1>,
  "comment": <короткая строка на русском, либо null>
}`;

/**
 * Одно задание для сверки.
 *
 * Повторяет `WorksheetTask`, но уже в том виде, в каком его отдаёт сервис:
 * номер, текст, эталон, ответ ученика, балл.
 */
export interface ShortAnswerItem {
  /** Номер задания в листе. */
  number: number;
  /** Текст задания. */
  taskText: string;
  /** Эталонный ответ. */
  expected: string;
  /** Что написал ученик. */
  studentAnswer: string;
  /** Балл за задание. */
  points: number;
}

export interface FormGradingPromptContext {
  subject?: string;
  grade?: number;
}

/**
 * Собрать сообщение для сверки одного короткого ответа.
 *
 * Поштучно, а не пачкой, и это решение, а не случайность:
 *   · вердикт привязан к номеру задания, поэтому один плохо разобранный ответ
 *     не утаскивает за собой весь лист — остальные всё равно придут учителю;
 *   · правило честности проверяется целиком в одном месте (см. normalizeShortAnswerVerdict).
 * Цена вопроса (G5) при таком подходе — доли копейки на ответ: см. комментарий
 * про `LLM_ANSWER_GRADING_ESTIMATE_TOKENS` в services/formGrading.ts.
 */
export function buildShortAnswerPrompt(
  item: ShortAnswerItem,
  ctx: FormGradingPromptContext = {},
): { system: string; user: string } {
  const user = JSON.stringify(
    {
      задача: "Сверь короткий ответ ученика с эталоном",
      контекст: {
        ...(ctx.subject ? { предмет: ctx.subject } : {}),
        ...(ctx.grade != null ? { класс: ctx.grade } : {}),
      },
      задание: {
        number: item.number,
        taskText: item.taskText,
        expected: item.expected,
        studentAnswer: item.studentAnswer,
        points: item.points,
      },
      верни: "JSON по схеме из системного промпта",
    },
    null,
    2,
  );
  return { system: FORM_GRADING_SYSTEM, user };
}