/**
 * Промпт генерации вопросов для беседы с учеником (TZ-17 §5.3).
 *
 * Вход: сохранённые в D1 позиции проверки по фото — текст задания, эталон и
 * распознанный ответ ученика. Фото повторно НЕ отправляется, vision не нужен.
 * Выход: строгий JSON `{ questions: [...] }` — по одному вопросу на задание.
 *
 * Отдельный вызов, а не расширение промпта проверки (`prompts/photo-check.ts`
 * не меняется ни одной строкой): этот промпт отвечает за вопросы, промпт
 * проверки — за отметку в журнале. Задачи разные, деградировать по отдельности
 * нельзя (ТЗ §3.1).
 *
 * Тон и структура — по образцу `prompts/photo-check.ts`: обращение на «ты»,
 * нумерованные требования, явная схема ответа, запрет markdown-обёртки.
 */

export const INTERVIEW_QUESTIONS_SYSTEM = `Ты — опытный учитель-предметник. Учитель проверял работу ученика и хочет спокойно поговорить с ним: задать несколько вопросов, чтобы убедиться, что работу делал сам ученик.

Твоя задача — составить вопросы, на которые ученик сможет ответить ТОЛЬКО если действительно сам решал. Вопросы читаются вслух в классе, поэтому они должны звучать естественно.

ПРАВИЛА:
1. Никогда не упоминай правильный ответ. В вопросе не должно быть ни эталона, ни намёка на него, ни слов «правильно/неправильно». Ученик не должен понять из вопроса, что именно «не так», иначе он не сможет ответить честно.
2. Вопрос задаётся УЧЕНИКУ, а не проверяющему. Обращение на «ты». Один-два предложения, до 200 знаков.
3. Вопрос обязан опираться на конкретное задание и конкретный ответ ученика. Общие вопросы вроде «что ты делал?» запрещены — спрашивай про то, что видно в этом задании.
4. Тип вопроса зависит от предмета:
   - математика — как ты получил это число, проверь другим способом, что получится, если изменить одно из чисел;
   - русский язык и литература — почему выбрал именно это слово или формулировку, на каком основании сделан вывод о тексте;
   - история, обществознание, география, биология — откуда взялась эта дата или этот факт, на каком основании сделан вывод;
   - физика, химия, информатика — что означает эта величина, что будет, если подставить другие данные;
   - прочие предметы — нейтральный вопрос по ходу решения.
5. Сложность вопроса — по классу. Пятикласснику нельзя задавать вопрос уровня девятиклассника.
6. Ровно ОДИН вопрос на каждое задание. Без нумерации внутри строки, без кавычек вокруг вопроса, без оценок и без слов о том, что ученик сделал неправильно.
7. Если по заданию нечего спросить (например, ответ не удалось разобрать) — всё равно задай нейтральный вопрос по самому заданию, но не выдумывай, что ученик написал.
8. Язык — русский. И вопросы, и весь текст ответа.

ФОРМАТ ОТВЕТА — СТРОГО JSON, без markdown, без пояснений вне JSON:
{
  "questions": [
    {
      "number": <номер задания, число>,
      "question": <вопрос ученику, строка>
    }
  ]
}`;

/** Одно задание для промпта — поля, нужные только формулировке вопроса. */
export interface InterviewTask {
  number: number;
  taskText: string | null;
  /** Эталон — нужен только для того, чтобы НЕ выдать его в вопросе. */
  expected: string | null;
  /** Что по этому заданию распознали на фото. */
  studentAnswer: string | null;
}

export interface InterviewPromptContext {
  subject?: string;
  grade?: number;
}

/**
 * Собрать user-сообщение: предмет, класс и выбранные задания с ответами ученика.
 *
 * Вердикт (`incorrect` / `unclear`) в промпт НЕ идёт намеренно: он подталкивает
 * модель к формулировкам «здесь ошибка», а вопрос должен быть нейтральным. Якорь
 * «где смотреть» учитель получает из `verdict_snapshot` в интерфейсе.
 */
export function buildInterviewPrompt(
  tasks: InterviewTask[],
  ctx: InterviewPromptContext = {},
): { system: string; user: string } {
  const user = JSON.stringify(
    {
      задача: "Составь вопросы для беседы по этим заданиям работы ученика",
      контекст: {
        ...(ctx.subject ? { предмет: ctx.subject } : {}),
        ...(ctx.grade != null ? { класс: ctx.grade } : {}),
      },
      задания: tasks.map((t) => ({
        number: t.number,
        taskText: t.taskText,
        ответУченика: t.studentAnswer,
        эталон: t.expected,
      })),
      верни: "JSON по схеме из системного промпта",
    },
    null,
    2,
  );
  return { system: INTERVIEW_QUESTIONS_SYSTEM, user };
}
