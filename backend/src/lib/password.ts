/**
 * Пароль учителя: хеширование и проверка (ТЗ-23 §7.2).
 *
 * Алгоритм — PBKDF2-HMAC-SHA256 через WebCrypto (`crypto.subtle.deriveBits`).
 * Выбор сделан в ТЗ осознанно: в Workers нет нативных bcrypt/argon2, а тянуть
 * WASM-модуль ради одной строки дороже, чем PBKDF2 из стандартной библиотеки.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * СКОЛЬКО ИТЕРАЦИЙ И ПОЧЕМУ ИМЕННО СТОЛЬКО (замер, а не учебник)
 * ─────────────────────────────────────────────────────────────────────────────
 * OWASP рекомендует для PBKDF2-HMAC-SHA256 600 000 итераций. Это число НЕ взято
 * здесь: оно не влезает в CPU-бюджет бесплатного Workers, а молча упасть на
 * 10-мс лимите нельзя (ТЗ §7.2) — тогда вход по паролю не работает вообще, и
 * это обнаруживается на живом учителе, а не на стенде.
 *
 * Замер: /tmp-скрипт через `node:crypto` webcrypto (тот же V8, что в workerd),
 * Node v23.11.0, darwin arm64, 10 повторов на значение, после прогрева:
 *
 *   итераций   вход (1 проход)   смена (2 прохода)   запас до 10 мс
 *      25 000        3.1 мс            6.2 мс              31 %
 *      30 000        3.7 мс            7.2 мс              17 %
 *      40 000        5.2 мс           10.3 мс              — мимо
 *      50 000        6.1 мс           12.5 мс              — мимо
 *     600 000       66–69 мс         133–138 мс             — мимо
 *
 * Одна итерация на этой машине — около 0.116 мкс.
 *
 * ВЫБРАНО 25 000:
 *   · вход по паролю = 1 проход ≈ 3.1 мс;
 *   · СМЕНА пароля = 2 прохода (проверка старого + хеш нового) ≈ 6.2 мс,
 *     максимум по прогонам 6.9 мс — это 31 % запаса до тарифных 10 мс.
 * Правило выбора: САМЫЙ ТЯЖЁЛЫЙ сценарий ручки должен укладываться в самый
 * строгий лимит. 30 000 давали бы 17 % запаса, 40 000 — уже 10.3 мс, то есть
 * смена пароля упала бы на бесплатном тарифе при живом входе.
 *
 * Почему не 600 000: на платном тарифе (30 с CPU) оно занимает 0.25 % бюджета
 * и было бы лучше во всём. Но тариф аккаунта из репозитория не виден, а цена
 * ошибки несимметрична: занизить итерации — работает везде; завысить — ручка
 * не работает ни у кого. Поэтому берём число, которое работает на обоих
 * тарифах, и фиксируем решение здесь, как ТЗ и требует.
 *
 * КАК ПОДНЯТЬ ДО 600 000, если тариф окажется платным: поменять одну константу
 * ниже. Уже записанные хеши продолжат проверяться по СВОЕМУ числу итераций — оно
 * лежит в колонке `iterations` таблицы user_passwords, поэтому подъём константы
 * не ломает пароли, заданные раньше.
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОВТОРНЫЙ ЗАМЕР НА НАСТОЯЩЕМ РАНТАЙМЕ WORKERS (12.10.2026)
 * ─────────────────────────────────────────────────────────────────────────────
 * Таблица выше — замер через node:crypto, то есть на Node. Настоящий движок
 * прод-ручки — workerd, и он не обязан совпадать. Поэтому те же ручки замерены
 * ещё раз на живом воркере: `npx wrangler dev --local`, порт 8799, вход по
 * паролю и смена пароля через curl, код ответа сверялся (замер отказа на 401
 * ДО хеширования показывает время отказа, а не стоимость PBKDF2 — первые два
 * прогона так и были выкинуты).
 *
 *   операция            проходов PBKDF2   n   медиана   диапазон
 *   вход по паролю            1            16   4.84 мс   4.28–8.75
 *   смена пароля              2            16   7.37 мс   7.09–8.99
 *   задание пароля           1             4   5.55 мс   5.44–10.08
 *
 * Разница «смена минус вход» = 7.37 − 4.84 = 2.53 мс — это и есть цена одного
 * прохода PBKDF2 на 25 000 итераций под workerd. Сама HTTP-ручка стоит около
 * 2.3 мс сверху (D1 и прочее). Вывод: движок подтвердился, PBKDF2 под workerd
 * стоит столько же, сколько под Node, и запас до 10 мс сохраняется.
 *
 * ЧЕГО ЭТОТ ЗАМЕР НЕ ДОКАЗЫВАЕТ (и это важно, чтобы число не выдали за большее,
 * чем оно есть). Мерялось wall-clock время HTTP-ответа на процессоре ЭТОГО
 * ноутбука. Тариф Cloudflare ограничивает CPU-ВРЕМЯ, локально его не отдают,
 * а процессор в дата-центре Cloudflare может быть медленнее. Поэтому фраза
 * «проверено на рантайме Workers» означает «движок и счётчик совпали», а НЕ
 * «на боевой машине уложимся в 10 мс». Для проверки именно боевого CPU нужен
 * реальный запрос к задеплоенному воркеру с замером на стороне Cloudflare.
 * Как только тариф известен, число итераций пересматривается по этому замеру,
 * а не по этому комментарию.
 *
 * Защита от подбора «в онлайне» идёт не от итераций, а от ограничения попыток
 * (ТЗ §7.3, 5 попыток на email в 15 минут), а неразобранная база — от того,
 * что D1 приватна.
 */
export const PASSWORD_HASH_ITERATIONS = 25_000;

/** Длина соли в байтах. ТЗ §4/§7.2: 16 случайных байт на пользователя. */
const SALT_BYTES = 16;

/** SHA-256 даёт 256 бит — столько и сравниваем. */
const DERIVED_BITS = 256;

export const PASSWORD_MIN_LENGTH = 8;
export const PASSWORD_MAX_LENGTH = 128;

/**
 * Текст отказа на слабый пароль. Взят из правил контракта API §5 — учитель
 * должен получить сами требования, а не «Validation failed».
 */
export const PASSWORD_POLICY_MESSAGE =
  "Пароль должен быть от 8 до 128 символов и содержать хотя бы одну букву и одну цифру";

/** Запись пароля в том виде, в каком она лежит в user_passwords. */
export interface PasswordHashRecord {
  /** base64 от 32 байт. */
  hash: string;
  /** base64 от 16 случайных байт. */
  salt: string;
  /** Сколько итераций посчитано ЭТИМ хешем (не константа из кода). */
  iterations: number;
}

/**
 * Проверить правила пароля (ТЗ §7.1). Возвращает текст ошибки или null.
 *
 * Правила ровно те, что в контракте §5:
 *   8…128 символов, обязательны буква и цифра, спецсимволы НЕ требуем,
 *   словарные пароли не проверяем, шкалу надёжности не показываем,
 *   пароль, равный своей почте, РАЗРЕШАЕМ.
 *
 * Буква и цифра ищутся по Unicode-классам: русская раскладка на телефоне —
 * это обычный сценарий учителя, и «qwerty123» с русскими буквами должен
 * проходить так же, как латиницей.
 */
export function checkPasswordPolicy(password: string): string | null {
  // Длина в символах, а не в UTF-16 code units: эмодзи и часть иероглифов
  // занимают два code unit и не должны «съедать» лимит.
  const length = Array.from(password).length;
  if (length < PASSWORD_MIN_LENGTH || length > PASSWORD_MAX_LENGTH) {
    return PASSWORD_POLICY_MESSAGE;
  }
  if (!/\p{L}/u.test(password) || !/\p{Nd}/u.test(password)) {
    return PASSWORD_POLICY_MESSAGE;
  }
  return null;
}

/** Посчитать хеш пароля с новой случайной солью. */
export async function hashPassword(password: string): Promise<PasswordHashRecord> {
  const salt = crypto.getRandomValues(new Uint8Array(SALT_BYTES));
  const bits = await deriveBits(password, salt, PASSWORD_HASH_ITERATIONS);
  return {
    hash: toBase64(new Uint8Array(bits)),
    salt: toBase64(salt),
    iterations: PASSWORD_HASH_ITERATIONS,
  };
}

/**
 * Проверить пароль против записи из базы.
 *
 * Число итераций берётся ИЗ ЗАПИСИ, а не из константы: старые хеши должны
 * считаться по своему правилу, иначе подъём константы молча лишил бы всех
 * существующих учителей пароля (ТЗ §4).
 */
export async function verifyPassword(
  password: string,
  record: PasswordHashRecord,
): Promise<boolean> {
  const salt = fromBase64(record.salt);
  const expected = fromBase64(record.hash);
  const bits = await deriveBits(password, salt, record.iterations);
  return timingSafeEqual(new Uint8Array(bits), expected);
}

/**
 * Посчитать один хеш «в никуда» — для выравнивания времени ответа.
 *
 * Нужно потому, что отказ на «нет такого аккаунта» без единой записи в БД
 * возвращается мгновенно, а отказ на «неверный пароль» — после PBKDF2. Разница
 * в десятки миллисекунд видна по времени ответа и сама по себе раскрывает,
 * зарегистрирован ли адрес, даже когда тексты ответов совпадают побайтово.
 * Соль и итерации здесь — из настоящей константы, чтобы стоимость совпадала.
 */
export async function burnPasswordTime(): Promise<void> {
  const salt = crypto.getRandomValues(new Uint8Array(SALT_BYTES));
  await deriveBits("", salt, PASSWORD_HASH_ITERATIONS);
}

async function deriveBits(
  password: string,
  salt: Uint8Array,
  iterations: number,
): Promise<ArrayBuffer> {
  const material = await crypto.subtle.importKey(
    "raw",
    new TextEncoder().encode(password),
    { name: "PBKDF2" },
    false,
    ["deriveBits"],
  );
  return crypto.subtle.deriveBits(
    { name: "PBKDF2", salt, iterations, hash: "SHA-256" },
    material,
    DERIVED_BITS,
  );
}

/**
 * Сравнение за постоянное время.
 *
 * Ранний выход по первому несовпавшему байту превращает проверку в оракул:
 * по времени ответа можно подбирать хеш байт за байтом. Здесь разность
 * накапливается и проверяется один раз в конце.
 */
function timingSafeEqual(a: Uint8Array, b: Uint8Array): boolean {
  if (a.length !== b.length) return false;
  let diff = 0;
  for (let i = 0; i < a.length; i++) {
    diff |= (a[i] ?? 0) ^ (b[i] ?? 0);
  }
  return diff === 0;
}

function toBase64(bytes: Uint8Array): string {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

function fromBase64(value: string): Uint8Array {
  const binary = atob(value);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  return bytes;
}