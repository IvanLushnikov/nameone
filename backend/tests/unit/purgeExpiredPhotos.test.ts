/**
 * Регресс: автоочистка фото обязана стирать ВСЕ страницы работы (07.10.2026).
 *
 * ─────────────────────────────────────────────────────────────────────────────
 * ПОЧЕМУ ЭТОТ ТЕСТ
 * ─────────────────────────────────────────────────────────────────────────────
 * 07.10.2026 ручка проверки по фото научилась принимать до трёх фотографий —
 * работа ученика часто на двух-трёх страницах. Первая легла в существующую
 * колонку `r2_key`, вторая и третья — в ключи с суффиксами `-2`, `-3`.
 *
 * Скрипт автоочистки `jobs/purgeExpiredPhotos.ts` удалял ТОЛЬКО `r2_key`.
 * То есть через 7 дней первая страница исчезала, а `-2` и `-3` оставались в
 * R2 навсегда. Это персональные данные ребёнка, оставленные в хранилище без
 * всякой возможности их удалить: бессрочное хранение вместо объявленных
 * 7 дней — и учитель, который удалил проверку вручную, всё равно оставил бы
 * фото позади.
 *
 * Тест ловит именно эту дыру: он проверяет не «функция вызвалась», а
 * «после очистки в корзине не осталось ни одной страницы».
 */

import { describe, it, expect, beforeEach } from "vitest";

describe("очистка фото по сроку хранения", () => {
  /** Ключи, дошедшие до удаления, — по порядку вызовов. */
  let deleted: string[];

  /** Минимальная корзина R2: помнит удалённое, отдельно живёт «сбойный» бакет. */
  function bucket(options: { failOn?: (key: string) => boolean } = {}) {
    return {
      async delete(key: string) {
        if (options.failOn?.(key)) throw new Error(`R2 недоступен для ${key}`);
        deleted.push(key);
      },
    } as unknown as R2Bucket;
  }

  beforeEach(() => {
    deleted = [];
  });

  it("удаляет все три страницы, а не только первую", async () => {
    const { deletePhotoObjects } = await import("../../src/routes/f06");
    const base = "pc/1790000000/abc-123.jpg";

    await deletePhotoObjects(bucket(), base);

    // Три вызова delete: базовый ключ + -2 + -3.
    expect(deleted).toHaveLength(3);
    expect(deleted[0]).toBe(base);
    expect(deleted).toContain("pc/1790000000/abc-123-2.jpg");
    expect(deleted).toContain("pc/1790000000/abc-123-3.jpg");
  });

  it("старая запись с одним фото удаляется без ошибки", async () => {
    // У строк, созданных до многостраничной загрузки, ключей -2/-3 просто нет.
    // R2 на отсутствующий объект отвечает успехом, но «мягкое» удаление
    // дополнительных страниц обязано проглатывать возможную ошибку —
    // иначе очистка рушилась бы на самых старых записях.
    const { deletePhotoObjects } = await import("../../src/routes/f06");
    const old = "pc/1600000000/legacy.jpg";
    const errors: number[] = [];

    await deletePhotoObjects(
      bucket({ failOn: (key) => key.includes("-2") || key.includes("-3") }),
      old,
      (page) => errors.push(page),
    );

    expect(deleted).toEqual([old]);
    // Ошибки по допстраницам НЕ бросаются наружу — это мягкая часть.
    expect(errors.sort()).toEqual([2, 3]);
  });

  it("ошибка удаления первой страницы пробрасывается", async () => {
    // Иначе вызывающий решит, что строка удалена, а фото останется в R2.
    const { deletePhotoObjects } = await import("../../src/routes/f06");

    await expect(
      deletePhotoObjects(bucket({ failOn: () => true }), "pc/1/x.jpg"),
    ).rejects.toThrow();
  });
});