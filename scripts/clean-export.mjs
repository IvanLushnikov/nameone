/**
 * Стирает каталог статического экспорта `out/` перед сборкой.
 *
 * ЗАЧЕМ. `next build` при `output: "export"` НЕ удаляет `out/` — он просто
 * дописывает в него. Проверено 16.10.2026: после сборки в `out/subject/`
 * лежали 7 251 каталог тем, а в таксономии их 6 567. 684 каталога — хвост
 * от прежних сборок, по ним темы успели переименовать или объединить.
 *
 * ПОЧЕМУ ЭТО НЕ КосметИКА, а две разные беды.
 *
 * 1) В выкатку уезжали мёртвые страницы: адрес, которого нет в таксономии,
 *    всё ещё отдавался как рабочий. Поисковик мог по нему ходить.
 * 2) Считать размер выкатки по `out/` становилось бессмысленно — счётчик
 *    показывал больше, чем сайт содержит на самом деле. 16.10.2026 из-за
 *    этого пришлось ложно списать рост сайта на темы ФГОС, хотя часть
 *    файлов была мусором от старых сборок.
 *
 * Каталог создаётся заново на каждой сборке, поэтому `next build` отрабатывает
 * как обычно: отсутствующий `out/` для него не ошибка.
 */

import { rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * Каталоги, которые Next не чистит сам и которые уносят в следующую сборку
 * хвосты прошлой.
 *
 * `out/` — собранные страницы. Ушедшие из таксономии темы продолжают лежать
 * готовыми html и уезжают в выкатку как живые.
 *
 * `.next/` — кэш сборки. Тот же класс проблемы, но дороже по последствиям:
 * типы роутов в `.next/types` НЕ удаляются при удалении роута, и `tsc`
 * падает с «Cannot find module .../page.js». 16.10.2026 на этом поймались
 * при удалении страниц «План урока». Вторая неприятная встреча с тем же
 * мусором — `PageNotFoundError: Cannot find module for page: /_error` на
 * шаге экспорта: бандл собран, а страницы в нём нет.
 */
for (const dir of ["out", ".next"]) {
  rmSync(join(ROOT, dir), { recursive: true, force: true });
  console.log(`clean-export: каталог ${dir}/ очищен.`);
}