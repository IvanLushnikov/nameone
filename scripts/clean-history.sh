#!/usr/bin/env bash
#
# Чистка истории репозитория nameone.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАЧЕМ
# ─────────────────────────────────────────────────────────────────────────────
# В истории репозитория лежит 8.34 МБ мусора: каталог `.audit/` со скриншотами
# конкурентов и сохранёнными HTML-страницами. Он был нужен для разовых
# проверок, в рабочем дереве его уже нет (`.gitignore`), но в истории он
# остался навсегда — и каждый клон тащит эти 8 МБ.
#
# Замер 28.10.2026:
#   до      — пак 17.28 МиБ, клон с GitHub 7.2 с;
#   после   — пак 10.13 МиБ, клон 1.1 с.
# То есть минус 41% размера пакета и вшестеро быстрее клонирование.
#
# Второй источник — большие JSON-файлы таксономии (`data/fgos/topics.json`
# 4.5 МБ и `fgos-program/data.json` 4.0 МБ): они в истории по несколько
# версий, и каждая версия — отдельный объект в паке. Переписывание истории
# их НЕ трогает: это живые данные, они нужны в рабочем дереве.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЧТО ЭТО ЛОМАЕТ
# ─────────────────────────────────────────────────────────────────────────────
# Переписывание истории меняет SHA всех коммитов. Поэтому:
#   * локальные копии репозитория перестают быть родственниками удалённого —
#     их надо переклонировать заново (или сделать `fetch` + `reset --hard`);
#   * открытые PR dependabot (их 8 на момент чистки) продолжат жить: их
#     ветки dependabot переписываются вместе с остальными, и GitHub
#     пересчитает их базу автоматически;
#   * старые ссылки на конкретные коммиты (SHA) перестанут открываться.
#     Ссылки на файлы и на ветки — останутся.
#
# ПУШ В `main` СИЛОВОЙ (`--force-with-lease`) — обычный `git push` после
# переписывания будет отклонён, и это правильно: так ничего не потеряется
# случайно.
#
# ─────────────────────────────────────────────────────────────────────────────
# ЗАПУСК
# ─────────────────────────────────────────────────────────────────────────────
#   bash scripts/clean-history.sh            # только показать, что будет
#   bash scripts/clean-history.sh --apply    # переписать локально и запушить
#
# Скрипт НЕ трогает рабочее дерево: он работает с отдельным клоном в
# `/tmp`, переписывает историю там и только потом пушит. Сломанная
# переписываемая история не должна портить то, где человек работает.

set -euo pipefail

REPO="git@github.com:IvanLushnikov/nameone.git"
WORK="${WORK:-/tmp/nameone-history-cleanup}"
APPLY=0
[ "${1:-}" = "--apply" ] && APPLY=1

echo "Репозиторий: $REPO"
echo "Рабочий каталог: $WORK"
echo ""

if [ "$APPLY" -eq 0 ]; then
  echo "Это сухой прогон. Ничего не меняется."
  echo "Для реальной чистки: bash scripts/clean-history.sh --apply"
  echo ""
fi

# ── 1. Свежий клон, в котором будем переписывать ──────────────────────────────
rm -rf "$WORK"
git clone --mirror "$REPO" "$WORK"
cd "$WORK"

echo "=== ДО ==="
git count-objects -vH | grep -E "size-pack|count:"
BEFORE=$(git count-objects -vH | awk '/size-pack/ {print $2, $3}')
echo ""

# ── 2. Убираем `.audit/` из истории ──────────────────────────────────────────
# Это рабочие артефакты исследований: скриншоты конкурентов и сохранённые
# страницы QA. В рабочем дереве их уже нет, в истории они лежат мёртвым
# грузом и весят 8.34 МБ.
echo "Убираю .audit/ из истории..."
git filter-branch -f \
  --index-filter 'git rm -r --cached --ignore-unmatch .audit' \
  --prune-empty -- --all > /tmp/nameone-filter-branch.log 2>&1

# Ссылка на оригинальную историю — чтобы откатиться, если что-то пойдёт не так.
#
# ВАЖНО, ПУТЬ ЗАВИСИТ ОТ ТИПА КЛОНА. В bare-репозитории (а `git clone --mirror`
# создаёт именно его) GIT_DIR — это корень каталога, а не подкаталог `.git`.
# Поэтому `rm -rf .git/refs/original` молча ничего не удалял, и старые ссылки
# на историю оставались живыми: `git gc` видел объекты `.audit/` достижимыми
# и не выбрасывал их. Замер 28.10.2026 на этом: пак сжимался с 17.48 до
# 15.80 МиБ вместо ожидаемых 10.13.
#
# Удаляем оба пути — лишний не помешает.
rm -rf .git/refs/original refs/original
git reflog expire --expire=now --all
git gc --prune=now --aggressive -q

echo "=== ПОСЛЕ ==="
git count-objects -vH | grep -E "size-pack|count:"
AFTER=$(git count-objects -vH | awk '/size-pack/ {print $2, $3}')
echo ""

echo "Сравнение: $BEFORE  ->  $AFTER"
echo ""

if [ "$APPLY" -eq 0 ]; then
  echo "Готово. Пак ужат, история переписана локально в $WORK."
  echo "Чтобы запушить: cd $WORK && git push --force-with-lease origin --all"
  exit 0
fi

# ── 3. Пуш ───────────────────────────────────────────────────────────────────
echo "Пушу переписанную историю (--force-with-lease)..."
git push --force-with-lease origin --all
git push --force-with-lease origin --tags || true

echo ""
echo "Готово. Дальше:"
echo "  * локальные копии репозитория переклонировать заново"
echo "    (или: git fetch origin && git reset --hard origin/main);"
echo "  * открытые PR dependabot должны пересчитаться автоматически."
