/**
 * Проверка читаемости материала под меткой «ДЕМО» (лист 1.1.4).
 *
 * Запуск: node scripts/check-watermark-legibility.mjs
 *
 * Зачем проверять исходник, а не картинку: дефект этого листа — ВИЗУАЛЬНЫЙ,
 * но он полностью определяется тремя числами в классах компонента. Скриншот
 * печати его ловит только глазами и только на одном типе материала; регресс
 * случится снова ровно тогда, когда кто-то «украсит» знак и вернёт `12vw`
 * или `/100`. Здесь это ловится автоматически за секунду.
 *
 * Что именно проверяется и почему именно это:
 *
 *   1. ПРОЗРАЧНОЧНОСТЬ букв. Непрозрачная буква не «мешает», а ЗАТИРАЕТ: под
 *      ней нет ни строки задания, ни номера урока. Поэтому порог не «есть
 *      прозрачность», а «прозрачность не выше 60%» — выше текст уже не
 *      читается (дефект 1.1.4 был ровно про это: непрозрачный `warm-300`).
 *   2. РАЗМЕР букв. Кегль задан в `vw` — процент от ширины печатной страницы.
 *      12vw на A4 = ~27 мм на букву: она перекрывает 6–8 строк таблицы КТП.
 *      Порог 9vw — это ещё заметная надпись, но не более двух строк.
 *   3. РЕЖИМ НАЛОЖЕНИЯ. Прозрачности мало самой по себе: обычное наложение
 *      светлых букв ВЫСВЕЧИВАЕТ тёмный текст под собой, и строка бледнеет
 *      даже при 40% альфы. `mix-blend-multiply` затемняет вместо высветления,
 *      поэтому подпись остаётся читаемой там, где буква её пересекает.
 *   4. `pointer-events-none` — иначе знак перехватывал бы клики по листу.
 *   5. `print-color-adjust: exact` — метка держится на цвете букв, а не фона.
 *      При выключенной «фоновой графике» (в диалоге печати она по умолчанию
 *      выключена) обычный текст печатается, а фон — нет: без этой строки
 *      браузер вправе упростить цвет знака до чёрного, и он снова станет
 *      непрозрачной заливкой поверх материала.
 *
 * Чего скрипт НЕ проверяет и почему это честно: читаемость фактическая.
 * Её меряют скриншоты печати (гейт G1 листа 1.1.4): автомат по исходнику
 * ловит возврат к плохим числам, но не скажет, читается ли конкретная строка
 * конкретного КТП.
 *
 * Зависимостей нет: только node:fs. Выход 1 с понятным списком, если
 * хотя бы один пункт нарушен.
 */

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WATERMARK = "src/components/constructor/PrintWatermark.tsx";

/** Выше этой альфы буква перестаёт просвечивать и начинает затирать текст. */
const MAX_ALPHA = 0.6;
/** Ниже этого кегля надпись перестаёт быть заметной — обратная сторона того же. */
const MIN_ALPHA = 0.15;
/** Выше этого кегля буква перекрывает колонку таблицы (дефект КТП, 12vw). */
const MAX_VW = 9;

const problems = [];
const src = readFileSync(join(ROOT, WATERMARK), "utf8");

/**
 * Класс буквы: тот, что задаёт кегль и цвет текста. Ищем в разметке `<span>`,
 * а не во всём файле — иначе под правила попадут числа из комментария.
 */
const spanMatch = src.match(/<span[\s\S]*?className="([^"]+)"/);
if (!spanMatch) {
  console.error(
    `[check-watermark-legibility] Не нашли <span> с классами в ${WATERMARK} — ` +
      `проверка не сработала, файл разобран не так, как ожидала.`,
  );
  process.exit(1);
}
const spanClasses = spanMatch[1];

/** Класс контейнера с надписями — там живут режим наложения и `pointer-events`. */
const rootMatch = src.match(/<div\n\s*aria-hidden[\s\S]*?className="([^"]+)"/);
const rootClasses = rootMatch ? rootMatch[1] : "";

// 1. Прозрачность букв. Tailwind-синтаксис: `text-warm-400/40` (слэш = альфа).
const alphaMatch = spanClasses.match(/\/(\d{1,3})(?:\s|$)/);
if (!alphaMatch) {
  problems.push(
    `${WATERMARK}: у буквы нет прозрачности — «text-*/NN». Непрозрачная буква ` +
      `не мешает, а затирает строку задания под собой (дефект 1.1.4)`,
  );
} else {
  const alpha = Number(alphaMatch[1]) / 100;
  if (alpha > MAX_ALPHA) {
    problems.push(
      `${WATERMARK}: прозрачность буквы ${alphaMatch[1]}% выше ${MAX_ALPHA * 100}% — ` +
        `под меткой пропадает текст задания`,
    );
  } else if (alpha < MIN_ALPHA) {
    problems.push(
      `${WATERMARK}: прозрачность буквы ${alphaMatch[1]}% ниже ${MIN_ALPHA * 100}% — ` +
        `метка почти не видна, а демо должно быть честно помечено`,
    );
  }
}

// 2. Кегль букв в `vw`: процент от ширины печатной страницы.
const vwMatch = spanClasses.match(/text-\[(\d+(?:\.\d+)?)vw\]/);
if (!vwMatch) {
  problems.push(
    `${WATERMARK}: кегль буквы не задан в vw (вида text-[7vw]) — ` +
      `проверка не сможет сказать, перекрывает ли буква строку`,
  );
} else {
  const vw = Number(vwMatch[1]);
  if (vw > MAX_VW) {
    problems.push(
      `${WATERMARK}: буква ${vw}vw шире ${MAX_VW}vw — на КТП она накрывает ` +
        `номера уроков, даты и текст тем (дефект, который закрывал этот лист)`,
    );
  }
}

// 3. Режим наложения: без него прозрачные буквы высветляют тёмный текст.
if (!/mix-blend-multiply/.test(src)) {
  problems.push(
    `${WATERMARK}: нет mix-blend-multiply — обычное наложение светлых букв ` +
      `ВЫСВЕЧИВАЕТ тёмный текст под собой, строка задания бледнеет`,
  );
}

// 4. Знак не должен перехватывать события.
if (!/pointer-events-none/.test(rootClasses)) {
  problems.push(
    `${WATERMARK}: нет pointer-events-none — знак перехватит клики по листу`,
  );
}

// 5. Цвет букв печатается без «фоновой графики» (галочка в диалоге печати
//    по умолчанию выключена). Иначе браузер вправе упростить знак до заливки.
if (!/print-color-adjust:\s*exact/.test(rootClasses)) {
  problems.push(
    `${WATERMARK}: нет [print-color-adjust:exact] — при выключенной ` +
      `«фоновой графике» метка печатается как обычный текст без своего цвета ` +
      `и может лечь непрозрачной заливкой`,
  );
}

// 6. Метка обязана оставаться многострочной: повтор на каждой странице —
//    требование листа 1.1.3, одна надпись его не выполняет. Надписи рисуются
//    из массива индексов (`{[0, 1, 2].map(...)}`), поэтому считаем элементы
//    массива, а не теги `<span>` — в исходнике он всегда один.
const listMatch = src.match(/\{(\[[\d,\s]+\])\.map\(/);
const repeatCount = listMatch ? (listMatch[1].match(/\d+/g) ?? []).length : 0;
if (repeatCount < 2) {
  problems.push(
    `${WATERMARK}: надписей ${repeatCount} — метка должна повторяться ` +
      `на каждой странице печати (нужно минимум 2)`,
  );
}

console.log("[check-watermark-legibility] Метка «ДЕМО» и читаемость материала:");
console.log(`  кегль буквы:        ${vwMatch ? `${vwMatch[1]}vw` : "не задан"}`);
console.log(`  прозрачность буквы: ${alphaMatch ? `${alphaMatch[1]}%` : "не задана"}`);
console.log(`  надписей на листе:  ${repeatCount}`);
console.log(`  режим наложения:    ${/mix-blend-multiply/.test(src) ? "mix-blend-multiply" : "нет"}`);
console.log(`  события листа:      ${/pointer-events-none/.test(rootClasses) ? "не перехватывает" : "ПЕРЕХВАТЫВАЕТ"}`);

if (problems.length > 0) {
  console.error("\n[check-watermark-legibility] Нарушения:");
  for (const p of problems) console.error(`  ✗ ${p}`);
  process.exit(1);
}

console.log(
  "\n[check-watermark-legibility] Метка заметна, повторяется на каждой странице и не закрывает текст.",
);
console.log("WATERMARK_LEGIBLE_OK");